// OwnershipPhase describes the lifecycle phase of a hostname ownership record.
// +k8s:openapi-gen=true
type OwnershipPhase string

const (
	// OwnershipPhaseActive means the recorded owner is the single Gslb allowed
	// to publish DNS results for the hostname.
	OwnershipPhaseActive OwnershipPhase = "Active"
	// OwnershipPhaseReleasing means the owner is handing the hostname over to
	// the recorded successor; old targets stay published until the successor
	// confirms publication.
	OwnershipPhaseReleasing OwnershipPhase = "Releasing"
)

// HostnameClaimant identifies a Gslb claiming a hostname and records the
// information needed to arbitrate ownership and verify published content.
// +k8s:openapi-gen=true
type HostnameClaimant struct {
	// Name of the claimant Gslb
	Name string `json:"name"`
	// Namespace of the claimant Gslb
	Namespace string `json:"namespace"`
	// UID of the claimant Gslb
	UID types.UID `json:"uid"`
	// Generation of the claimant Gslb at the time of the claim
	Generation int64 `json:"generation"`
	// Strategy type declared by the claimant Gslb
	Strategy string `json:"strategy"`
	// PrimaryGeoTag declared by the claimant Gslb (failover strategy)
	PrimaryGeoTag string `json:"primaryGeoTag,omitempty"`
	// TargetsDigest is a stable digest of the A record targets the claimant
	// publishes for the hostname (record type, TTL and sorted targets).
	TargetsDigest string `json:"targetsDigest,omitempty"`
}

// HostnameOwnershipSpec is the persistent, arbitrated ownership state of one
// normalized hostname.
// +k8s:openapi-gen=true
type HostnameOwnershipSpec struct {
	// Hostname is the normalized DNS name this record governs.
	Hostname string `json:"hostname"`
	// Phase is the current ownership phase.
	Phase OwnershipPhase `json:"phase"`
	// Epoch is the ownership version. It is bumped every time ownership or
	// the phase transitions and fences stale arbitration results across
	// reconciler restarts and concurrent claimants.
	Epoch int64 `json:"epoch"`
	// Owner is the unique Gslb allowed to publish the hostname. Only the
	// recorded owner may write externally visible DNS results.
	Owner *HostnameClaimant `json:"owner,omitempty"`
	// Successor is the designated next owner while Phase is Releasing.
	Successor *HostnameClaimant `json:"successor,omitempty"`
	// PreviousOwner records the outgoing owner after a successor took over.
	// It is cleared once the outgoing owner has confirmed the successor
	// publication and completed its own cleanup.
	PreviousOwner *HostnameClaimant `json:"previousOwner,omitempty"`
	// Candidates are the claimants observed during the latest arbitration,
	// ordered by stable (namespace, name) keying.
	Candidates []HostnameClaimant `json:"candidates,omitempty"`
}

