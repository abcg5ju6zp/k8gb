// GslbStatus defines the observed state of Gslb
type GslbStatus struct {
	// Associated Service status
	ServiceHealth map[string]HealthStatus `json:"serviceHealth"`
	// Current Healthy DNS record structure
	HealthyRecords map[string][]string `json:"healthyRecords"`
	// Cluster Geo Tag
	GeoTag string `json:"geoTag"`
	// Comma-separated list of hosts
	Hosts string `json:"hosts,omitempty"`
	// LoadBalancer configuration
	LoadBalancer LoadBalancer `json:"loadBalancer,omitempty"`
	// Servers configuration
	Servers []*Server `json:"servers,omitempty"`
	// ActiveResourceRef identifies the referenced resource whose generation is
	// currently publishing the DNSEndpoint. It is the baseline used to detect
	// ResourceRef switches which require an ownership handoff.
	ActiveResourceRef *ResourceRefIdentity `json:"activeResourceRef,omitempty"`
	// ResourceRefHandoff exists only while ownership of DNSEndpoint hosts is
	// being handed over from one referenced resource to another. It pins the
	// Gslb generation, the old/new referenced object identities, the hostname
	// set, the last usable health inputs and the frozen DNSEndpoint content,
	// so that late reconciliations and controller restarts can never move the
	// pinned generation backwards or expand the hostname scope.
	ResourceRefHandoff *ResourceRefHandoff `json:"resourceRefHandoff,omitempty"`
}

// ResourceRefIdentity identifies a referenced resource serving the GSLB.
// Switch detection compares the coordinates (APIVersion/Kind/Name/Selector);
// the UID is pinned per active or handoff generation to fence off writes
// originating from a deleted, recreated or renamed referenced object.
// +k8s:openapi-gen=true
type ResourceRefIdentity struct {
	// APIVersion of the referenced resource
	APIVersion string `json:"apiVersion,omitempty"`
	// Kind of the referenced resource
	Kind string `json:"kind,omitempty"`
	// Name of the referenced resource (empty in LabelSelector mode)
	Name string `json:"name,omitempty"`
	// Selector is the serialized LabelSelector when the reference selects resources
	Selector string `json:"selector,omitempty"`
	// UID of the referenced object observed for this generation
	UID types.UID `json:"uid,omitempty"`
}

// HostHandoffPhase is the per-hostname ownership handoff phase
type HostHandoffPhase string

const (
	// HostHandoffPendingTakeover means the new reference is not fully resolved
	// and validated yet; the previous owner keeps publishing the last usable result.
	HostHandoffPendingTakeover HostHandoffPhase = "PendingTakeover"
	// HostHandoffTakingOver means the candidate DNSEndpoint was validated and a
	// publish receipt was recorded; the candidate write is in flight or unconfirmed.
	HostHandoffTakingOver HostHandoffPhase = "TakingOver"
	// HostHandoffActive means the new reference was confirmed as the publisher.
	HostHandoffActive HostHandoffPhase = "Active"
)

// HostHandoff is the per-hostname state of a ResourceRef handoff
// +k8s:openapi-gen=true
type HostHandoff struct {
	// Host is the pinned hostname
	Host string `json:"host"`
	// Phase of the ownership handoff for the hostname
	Phase HostHandoffPhase `json:"phase"`
}

// PublishedEndpoint is a frozen DNSEndpoint record used as the last usable
// result during a handoff and as publish-receipt evidence.
// +k8s:openapi-gen=true
type PublishedEndpoint struct {
	// DNSName of the record (including localtargets- prefixed records)
	DNSName string `json:"dnsName"`
	// RecordType of the record
	RecordType string `json:"recordType,omitempty"`
	// RecordTTL of the record in seconds
	RecordTTL int64 `json:"recordTtl,omitempty"`
	// Targets of the record
	Targets []string `json:"targets,omitempty"`
	// Labels of the record
	Labels map[string]string `json:"labels,omitempty"`
}

// PublishReceipt records that a candidate DNSEndpoint for the pinned handoff
// generation was about to be / was written. If the Gslb status update which
// confirms the takeover fails after the DNSEndpoint was written, the receipt
// is used on the next reconciliation to verify the live DNSEndpoint and to
// backfill the status without recomputing (and without expanding hosts).
// +k8s:openapi-gen=true
type PublishReceipt struct {
	// Gslb generation which published the receipt
	Generation int64 `json:"generation"`
	// ToUID is the new referenced object UID the candidate was built from
	ToUID types.UID `json:"toUid,omitempty"`
	// Endpoint is the exact DNSEndpoint content covered by the receipt
	Endpoint []PublishedEndpoint `json:"endpoint,omitempty"`
}

// ResourceRefHandoff is the ownership handoff state established when the
// Gslb's ResourceRef changes between referenced resources.
// +k8s:openapi-gen=true
type ResourceRefHandoff struct {
	// Generation pins the Gslb generation at handoff start. Only the latest
	// generation advances the handoff; concurrent and late reconciliations
	// pinned to an older generation are fenced off before any write.
	Generation int64 `json:"generation"`
	// From identifies the referenced resource which used to publish DNS.
	From ResourceRefIdentity `json:"from"`
	// To identifies the referenced resource which is taking over.
	To ResourceRefIdentity `json:"to"`
	// Hosts pins the hostname set at switch start. Neither the pending,
	// takeover nor receipt backfill path may publish hosts outside this set.
	Hosts []string `json:"hosts"`
	// Health pins the last usable per-host health inputs of the previous owner.
	Health map[string]HealthStatus `json:"health,omitempty"`
	// Servers pins the last usable server configuration of the previous owner.
	Servers []*Server `json:"servers,omitempty"`
	// LastEndpoint is the frozen last usable DNSEndpoint content which keeps
	// being published for hostnames whose takeover has not completed.
	LastEndpoint []PublishedEndpoint `json:"lastEndpoint,omitempty"`
	// HostStates is the per-hostname handoff phase.
	HostStates []HostHandoff `json:"hostStates,omitempty"`
	// Receipt is the publish receipt of the in-flight candidate, if any.
	Receipt *PublishReceipt `json:"publishReceipt,omitempty"`
	// Reason explains why the handoff has not completed yet.
	Reason string `json:"reason,omitempty"`
}

