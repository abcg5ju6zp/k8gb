func setupTestScheme(t *testing.T) *runtime.Scheme {
	s := runtime.NewScheme()
	require.NoError(t, clientgoscheme.AddToScheme(s))
	require.NoError(t, v1beta1io.AddToScheme(s))
	return s
}

func TestRolloutWatchPredicates(t *testing.T) {
	// The anchor and controller-managed ConfigMaps trigger reconciliation.
	cmPred := rolloutAnchorOrGenerationPredicate()
	assert.True(t, cmPred.Create(event.CreateEvent{Object: &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{Name: corednsrollout.AnchorConfigMapName},
	}}))
	assert.True(t, cmPred.Create(event.CreateEvent{Object: &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:   corednsrollout.GenerationConfigMapName("abcdef123456"),
			Labels: map[string]string{corednsrollout.LabelManagedBy: corednsrollout.ManagedByValue},
		},
	}}))
	assert.False(t, cmPred.Create(event.CreateEvent{Object: &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{Name: "unrelated-cm"},
	}}))

	// Production and canary CoreDNS workloads trigger reconciliation.
	workloadPred := coreDNSWorkloadPredicate()
	assert.True(t, workloadPred.Update(event.UpdateEvent{
		ObjectNew: &appsv1.Deployment{ObjectMeta: metav1.ObjectMeta{
			Labels: map[string]string{"app.kubernetes.io/name": "coredns"},
		}},
	}))
	assert.True(t, workloadPred.Update(event.UpdateEvent{
		ObjectNew: &corev1.Service{ObjectMeta: metav1.ObjectMeta{
			Labels: map[string]string{corednsrollout.LabelManagedBy: corednsrollout.ManagedByValue},
		}},
	}))
	assert.False(t, workloadPred.Update(event.UpdateEvent{
		ObjectNew: &appsv1.Deployment{ObjectMeta: metav1.ObjectMeta{Name: "other"}},
	}))

	// Only canary Pods trigger; a canary Pod readiness status update passes.
	podPred := canaryPodPredicate()
	canaryPod := &corev1.Pod{ObjectMeta: metav1.ObjectMeta{
		Name:   "k8gb-coredns-zd-canary-xyz",
		Labels: map[string]string{corednsrollout.LabelRole: corednsrollout.RoleCanary},
	}}
	assert.True(t, podPred.Update(event.UpdateEvent{ObjectOld: canaryPod.DeepCopy(), ObjectNew: canaryPod}))
	assert.False(t, podPred.Create(event.CreateEvent{Object: &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{Name: "coredns-prod-pod", Labels: map[string]string{"app.kubernetes.io/name": "coredns"}},
	}}))
}

func TestRolloutEventEnqueuesAllZoneDelegations(t *testing.T) {
	// TR-10.1: a canary Pod Ready event maps to at least one ZoneDelegation
	// reconciliation request (every ZD is enqueued so the level-triggered
	// state machine re-evaluates).
	ctx := context.Background()
	scheme := setupTestScheme(t)
	zones := []client.Object{
		&v1beta1io.ZoneDelegation{ObjectMeta: metav1.ObjectMeta{Name: "cloud.example.com"}},
		&v1beta1io.ZoneDelegation{ObjectMeta: metav1.ObjectMeta{Name: "cloud2.example.com"}},
	}
	cb := fake.NewClientBuilder().WithScheme(scheme).WithObjects(zones...).Build()
	r := &ZoneDelegationReconciler{Client: cb, Recorder: record.NewFakeRecorder(1)}

	canaryPod := &corev1.Pod{ObjectMeta: metav1.ObjectMeta{
		Name:      "k8gb-coredns-zd-canary-xyz",
		Namespace: "k8gb",
		Labels:    map[string]string{corednsrollout.LabelRole: corednsrollout.RoleCanary},
	}}
	require.True(t, canaryPodPredicate().Create(event.CreateEvent{Object: canaryPod}))

	requests := r.enqueueAllZoneDelegations(ctx, canaryPod)
	assert.Len(t, requests, 2)
	names := map[string]bool{}
	for _, req := range requests {
		names[req.Name] = true
	}
	assert.True(t, names["cloud.example.com"])
	assert.True(t, names["cloud2.example.com"])
}

func TestZoneDelegationSetupBuildsWithRolloutWatches(t *testing.T) {
	// TR-10.1: the controller constructs with the four rollout watch sources
	// against the manager cache without starting (no API calls are made).
	cfg := &rest.Config{Host: "http://127.0.0.1:0"}

	mgr, err := ctrl.NewManager(cfg, ctrl.Options{Scheme: setupTestScheme(t)})
	require.NoError(t, err)
	scheme := mgr.GetScheme()
	cb := fake.NewClientBuilder().WithScheme(scheme).Build()
	r := &ZoneDelegationReconciler{
		Client:       cb,
		Scheme:       scheme,
		Recorder:     record.NewFakeRecorder(1),
		RolloutCache: mgr.GetCache(),
	}
	require.NoError(t, r.SetupWithManager(mgr))

	// Without a rollout cache the baseline ZoneDelegation-only watch builds.
	skipNameValidation := true
	mgrBase, err := ctrl.NewManager(cfg, ctrl.Options{
		Scheme:     setupTestScheme(t),
		Controller: config.Controller{SkipNameValidation: &skipNameValidation},
	})
	require.NoError(t, err)
	base := &ZoneDelegationReconciler{
		Client:   fake.NewClientBuilder().WithScheme(mgrBase.GetScheme()).Build(),
		Scheme:   mgrBase.GetScheme(),
		Recorder: record.NewFakeRecorder(1),
	}
	require.NoError(t, base.SetupWithManager(mgrBase))
}
