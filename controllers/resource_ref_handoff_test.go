func TestGenerationFenceRejectsStaleWriters(t *testing.T) {
	// scenario 1: observed Gslb generation is behind the latest
	latest := switchingGslb()
	latest.Generation = 4
	latest.Status.ResourceRefHandoff = &k8gbv1beta1io.ResourceRefHandoff{Generation: 4}
	r, _ := newHandoffTestReconciler(t, latest)
	stale := &k8gbv1beta1io.Gslb{
		ObjectMeta: metav1.ObjectMeta{Name: "demo", Namespace: "default", Generation: 3},
		Status: k8gbv1beta1io.GslbStatus{
			ResourceRefHandoff: &k8gbv1beta1io.ResourceRefHandoff{Generation: 3},
		},
	}
	err := r.assertLatestGeneration(context.Background(), stale, stale.Status.ResourceRefHandoff)
	require.Error(t, err)
	assert.True(t, errors.Is(err, errStaleHandoffGeneration))

	// scenario 2: handoff completed underneath the in-flight reconciliation
	completed := switchingGslb()
	completed.Generation = 3
	completed.Status.ResourceRefHandoff = nil
	r, _ = newHandoffTestReconciler(t, completed)
	inFlight := &k8gbv1beta1io.ResourceRefHandoff{Generation: 3}
	err = r.assertLatestGeneration(context.Background(),
		&k8gbv1beta1io.Gslb{ObjectMeta: metav1.ObjectMeta{Name: "demo", Namespace: "default", Generation: 3}},
		inFlight)
	require.Error(t, err)
	assert.True(t, errors.Is(err, errStaleHandoffGeneration))

	// scenario 3: stale handoff generation pinned in the in-flight writer
	retargeted := switchingGslb()
	retargeted.Generation = 3
	retargeted.Status.ResourceRefHandoff = &k8gbv1beta1io.ResourceRefHandoff{Generation: 3}
	r, _ = newHandoffTestReconciler(t, retargeted)
	older := &k8gbv1beta1io.ResourceRefHandoff{Generation: 2}
	err = r.assertLatestGeneration(context.Background(),
		&k8gbv1beta1io.Gslb{ObjectMeta: metav1.ObjectMeta{Name: "demo", Namespace: "default", Generation: 3}},
		older)
	require.Error(t, err)
	assert.True(t, errors.Is(err, errStaleHandoffGeneration))

	// scenario 4: active-path reconciliation must not write once a handoff started
	handoffStarted := switchingGslb()
	handoffStarted.Generation = 5
	handoffStarted.Status.ResourceRefHandoff = &k8gbv1beta1io.ResourceRefHandoff{Generation: 5}
	r, _ = newHandoffTestReconciler(t, handoffStarted)
	err = r.assertActiveGeneration(context.Background(),
		&k8gbv1beta1io.Gslb{ObjectMeta: metav1.ObjectMeta{Name: "demo", Namespace: "default", Generation: 5}}, 5)
	require.Error(t, err)
	assert.True(t, errors.Is(err, errStaleHandoffGeneration))
}

