func TestExistingHandoffRetargetsToNewestSwitch(t *testing.T) {
	gslb := switchingGslb()
	gslb.Generation = 4
	gslb.Spec.ResourceRef = httpRouteRef("new-route")
	gslb.Status.ResourceRefHandoff = &k8gbv1beta1io.ResourceRefHandoff{
		Generation: 3,
		From: k8gbv1beta1io.ResourceRefIdentity{
			APIVersion: "networking.k8s.io/v1", Kind: "Ingress", Name: "old-ing", UID: "ingress-uid",
		},
		To:    k8gbv1beta1io.ResourceRefIdentity{APIVersion: "v1", Kind: "Service", Name: "new-svc", UID: "svc-uid"},
		Hosts: []string{"a.example.com", "b.example.com"},
		Health: map[string]k8gbv1beta1io.HealthStatus{
			"a.example.com": k8gbv1beta1io.Healthy,
		},
		Servers:      []*k8gbv1beta1io.Server{{Host: "a.example.com"}},
		LastEndpoint: k8gbendpoint.SnapshotEndpoints(frozenDNSEndpoint("default", "demo").Spec.Endpoints),
		HostStates: []k8gbv1beta1io.HostHandoff{
			{Host: "a.example.com", Phase: k8gbv1beta1io.HostHandoffTakingOver},
			{Host: "b.example.com", Phase: k8gbv1beta1io.HostHandoffPendingTakeover},
		},
		Receipt: &k8gbv1beta1io.PublishReceipt{Generation: 3},
	}
	r, cl := newHandoffTestReconciler(t, gslb)

	handoff, err := r.initOrGetResourceRefHandoff(context.Background(), gslb)
	require.NoError(t, err)
	require.NotNil(t, handoff)

	assert.Equal(t, int64(4), handoff.Generation, "handoff must follow the newest generation only")
	assert.Equal(t, "HTTPRoute", handoff.To.Kind)
	assert.Empty(t, handoff.To.UID)
	assert.Nil(t, handoff.Receipt, "in-flight candidate of the older switch is discarded")
	for _, state := range handoff.HostStates {
		assert.Equal(t, k8gbv1beta1io.HostHandoffPendingTakeover, state.Phase)
	}
	assert.Equal(t, "Ingress", handoff.From.Kind, "old owner stays the same until a takeover completes")
	assert.Equal(t, types.UID("ingress-uid"), handoff.From.UID)
	assert.Equal(t, []string{"a.example.com", "b.example.com"}, handoff.Hosts, "hostnames are never re-pinned on re-target")
	require.Len(t, handoff.LastEndpoint, 4, "frozen last usable result survives re-target")

	persisted := &k8gbv1beta1io.Gslb{}
	require.NoError(t, cl.Get(context.Background(), client.ObjectKeyFromObject(gslb), persisted))
	require.NotNil(t, persisted.Status.ResourceRefHandoff)
	assert.Equal(t, "HTTPRoute", persisted.Status.ResourceRefHandoff.To.Kind)
}

