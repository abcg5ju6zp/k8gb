func TestInitHandoffPinsGenerationUIDsHostsAndFrozenResult(t *testing.T) {
	gslb := switchingGslb()
	r, cl := newHandoffTestReconciler(t, gslb, frozenDNSEndpoint("default", "demo"))

	handoff, err := r.initOrGetResourceRefHandoff(context.Background(), gslb)
	require.NoError(t, err)
	require.NotNil(t, handoff)

	assert.Equal(t, int64(3), handoff.Generation)
	assert.Equal(t, "Ingress", handoff.From.Kind)
	assert.Equal(t, types.UID("ingress-uid"), handoff.From.UID)
	assert.Equal(t, "Service", handoff.To.Kind)
	assert.Equal(t, "new-svc", handoff.To.Name)
	assert.Empty(t, handoff.To.UID, "new UID is only pinned once the referenced object is observed")
	assert.Equal(t, []string{"a.example.com", "b.example.com"}, handoff.Hosts)
	require.Len(t, handoff.HostStates, 2)
	for _, state := range handoff.HostStates {
		assert.Equal(t, k8gbv1beta1io.HostHandoffPendingTakeover, state.Phase)
	}
	require.Len(t, handoff.LastEndpoint, 4)
	assert.Equal(t, k8gbv1beta1io.Healthy, handoff.Health["a.example.com"])
	require.Len(t, handoff.Servers, 2)
	assert.Equal(t, "old-svc-a", handoff.Servers[0].Services[0].Name)

	// handoff must be persisted immediately so concurrent/reordered reconciles observe it
	persisted := &k8gbv1beta1io.Gslb{}
	require.NoError(t, cl.Get(context.Background(), client.ObjectKeyFromObject(gslb), persisted))
	require.NotNil(t, persisted.Status.ResourceRefHandoff)
	assert.Equal(t, int64(3), persisted.Status.ResourceRefHandoff.Generation)
	require.Len(t, persisted.Status.ResourceRefHandoff.LastEndpoint, 4)
	// active identity of the old owner is retained until takeover completes
	require.NotNil(t, persisted.Status.ActiveResourceRef)
	assert.Equal(t, "Ingress", persisted.Status.ActiveResourceRef.Kind)
}

