func TestAdvanceFrozenBaselineKeepsActiveHostOnNewOwnerAfterDiscard(t *testing.T) {
	gslb := switchingGslb()
	h := &k8gbv1beta1io.ResourceRefHandoff{
		Generation:   3,
		From:         *gslb.Status.ActiveResourceRef,
		To:           k8gbv1beta1io.ResourceRefIdentity{APIVersion: "v1", Kind: "Service", Name: "new-svc", UID: "new-svc-uid"},
		Hosts:        []string{"a.example.com", "b.example.com"},
		Health:       cloneHealth(gslb.Status.ServiceHealth),
		Servers:      cloneServers(gslb.Status.Servers),
		LastEndpoint: snapshotEndpointsForTest(t, frozenDNSEndpoint("default", "demo").Spec.Endpoints),
		HostStates: []k8gbv1beta1io.HostHandoff{
			{Host: "a.example.com", Phase: k8gbv1beta1io.HostHandoffActive},
			{Host: "b.example.com", Phase: k8gbv1beta1io.HostHandoffPendingTakeover},
		},
	}
	view := &handoffCandidateView{
		servers: []*k8gbv1beta1io.Server{{
			Host:     "a.example.com",
			Services: []*k8gbv1beta1io.NamespacedName{{Namespace: "default", Name: "new-svc-a"}},
		}},
		health:     map[string]k8gbv1beta1io.HealthStatus{"a.example.com": k8gbv1beta1io.Healthy},
		exposedIPs: []string{"20.0.0.1"},
	}
	published := []*externaldns.Endpoint{
		// a confirmed on the new owner
		{DNSName: "localtargets-a.example.com", RecordType: "A", Targets: []string{"20.0.0.1"}},
		{DNSName: "a.example.com", RecordType: "A", Targets: []string{"20.0.0.1"}},
		// b still on the previous owner frozen result
		{DNSName: "localtargets-b.example.com", RecordType: "A", Targets: []string{"10.0.0.2"}},
		{DNSName: "b.example.com", RecordType: "A", Targets: []string{"10.0.0.2"}},
	}

	advanceFrozenBaseline(h, view, published)

	byName := map[string]k8gbv1beta1io.PublishedEndpoint{}
	for _, p := range h.LastEndpoint {
		byName[p.DNSName] = p
	}
	assert.Equal(t, []string{"20.0.0.1"}, byName["a.example.com"].Targets, "confirmed host baseline moves to new owner")
	assert.Equal(t, []string{"20.0.0.1"}, byName["localtargets-a.example.com"].Targets)
	assert.Equal(t, []string{"10.0.0.2"}, byName["b.example.com"].Targets, "pending host baseline stays on previous owner")
	assert.Equal(t, "new-svc-a", h.Servers[0].Services[0].Name)
	assert.Equal(t, "old-svc-b", h.Servers[1].Services[0].Name)
	assert.Equal(t, k8gbv1beta1io.Healthy, h.Health["a.example.com"])

	// A subsequent failed candidate for b must merge b from the frozen baseline
	// while a must never revert: simulate the discard merge directly
	merged := k8gbendpoint.MergeHandoffEndpoints(h.Hosts, h.LastEndpoint, nil,
		map[string]bool{})
	targets := map[string][]string{}
	for _, e := range merged {
		targets[e.DNSName] = []string(e.Targets)
	}
	assert.Equal(t, []string{"20.0.0.1"}, targets["a.example.com"])
	assert.Equal(t, []string{"10.0.0.2"}, targets["b.example.com"])
}

