const (
	// gslbHostnameFinalizer keeps a deleting Gslb (and its DNSEndpoint) alive
	// until hostname ownership has been handed over and the successor
	// publication confirmed.
	gslbHostnameFinalizer = "k8gb.io/hostname-ownership"

	cleanupCommitAttempts = 3
)

// NewGslbClaimValidator constructs the ClaimValidator used by the ownership
// manager to re-validate candidate references and health during elections.
func NewGslbClaimValidator(c client.Client, r resolver.GslbResolver) ownership.ClaimValidator {
	return &claimValidator{client: c, resolver: r}
}

type claimValidator struct {
	client   client.Client
	resolver resolver.GslbResolver
}

func (v *claimValidator) ValidateClaim(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	host string,
) (ownership.ClaimValidation, error) {
	invalid := ownership.ClaimValidation{}
	fresh := &k8gbv1beta1io.Gslb{}
	err := v.client.Get(ctx, client.ObjectKey{Namespace: gslb.Namespace, Name: gslb.Name}, fresh)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return invalid, nil
		}
		return invalid, err
	}
	if fresh.DeletionTimestamp != nil {
		return invalid, nil
	}
	if err := v.resolver.ResolveGslbSpec(ctx, fresh, v.client); err != nil {
		// A Gslb whose spec cannot be resolved cannot validly publish.
		return invalid, nil
	}
	refResolver, err := refresolver.New(fresh, v.client)
	if err != nil {
		return invalid, nil
	}
	servers, err := refResolver.GetServers()
	if err != nil {
		return invalid, nil
	}
	if !serversContainHost(servers, host) {
		return invalid, nil
	}
	health, err := calculateServiceHealth(ctx, v.client, fresh)
	if err != nil {
		return invalid, err
	}
	return ownership.ClaimValidation{
		Claims:  true,
		Healthy: health[host] == k8gbv1beta1io.Healthy,
	}, nil
}

func serversContainHost(servers []*k8gbv1beta1io.Server, host string) bool {
	for _, server := range servers {
		if server != nil && ownership.NormalizeHostname(server.Host) == host {
			return true
		}
	}
	return false
}

func (r *GslbReconciler) ensureHostnameFinalizer(ctx context.Context, gslb *k8gbv1beta1io.Gslb) error {
	if controllerutil.ContainsFinalizer(gslb, gslbHostnameFinalizer) {
		return nil
	}
	controllerutil.AddFinalizer(gslb, gslbHostnameFinalizer)
	return r.Update(ctx, gslb)
}

// reconcileGslbDeletion hands every owned hostname over to a successor before
// the Gslb (and its DNSEndpoint) is allowed to disappear. All state is read
// from the persisted HostnameOwnership records, so a controller restart simply
// resumes the handoff.
func (r *GslbReconciler) reconcileGslbDeletion(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	result *utils.ReconcileResultHandler,
) (ctrl.Result, error) {
	if !controllerutil.ContainsFinalizer(gslb, gslbHostnameFinalizer) {
		return result.Stop()
	}
	if r.Ownership == nil {
		if err := r.removeHostnameFinalizerCleanupOnly(ctx, gslb); err != nil {
			return result.RequeueError(err)
		}
		return result.Stop()
	}
	done, err := r.Ownership.Finalize(ctx, gslb)
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(fmt.Errorf("finalizing hostname ownership: %w", err))
	}
	if !done {
		r.Logger.Info().
			Str("gslb", gslb.Name).
			Str("namespace", gslb.Namespace).
			Msg("Waiting for successor to publish before releasing hostname ownership")
		return result.Requeue()
	}
	if err := r.removeHostnameFinalizerCleanupOnly(ctx, gslb); err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}
	return result.Stop()
}

// removeHostnameFinalizerCleanupOnly performs just the finalizer removal.
// Conflicts are recovered by re-reading the latest object and resubmitting the
// cleanup commit; no ownership or DNS state is touched.
func (r *GslbReconciler) removeHostnameFinalizerCleanupOnly(ctx context.Context, gslb *k8gbv1beta1io.Gslb) error {
	for attempt := 0; attempt < cleanupCommitAttempts; attempt++ {
		fresh := &k8gbv1beta1io.Gslb{}
		if err := r.Get(ctx, client.ObjectKey{Namespace: gslb.Namespace, Name: gslb.Name}, fresh); err != nil {
			if apierrors.IsNotFound(err) {
				return nil
			}
			return err
		}
		if !controllerutil.ContainsFinalizer(fresh, gslbHostnameFinalizer) {
			return nil
		}
		controllerutil.RemoveFinalizer(fresh, gslbHostnameFinalizer)
		err := r.Update(ctx, fresh)
		if err == nil {
			return nil
		}
		if !apierrors.IsConflict(err) {
			return err
		}
		// Finalizer commit conflicted: only re-submit the cleanup commit.
	}
	return fmt.Errorf("could not remove %s finalizer after %d conflict retries", gslbHostnameFinalizer, cleanupCommitAttempts)
}

// conflictOwnerRefs returns the sorted unique owner references of withheld
// hostnames, for annotating the secondary DNSEndpoint object.
func conflictOwnerRefs(decision *ownership.Decision) []string {
	set := map[string]struct{}{}
	for _, claimant := range decision.Conflicts {
		if claimant.Namespace == "" || claimant.Name == "" {
			continue
		}
		set[ownership.OwnerRef(claimant)] = struct{}{}
	}
	refs := make([]string, 0, len(set))
	for ref := range set {
		refs = append(refs, ref)
	}
	sort.Strings(refs)
	return refs
}

// applyOwnershipConditions surfaces the arbitration outcome as queryable Gslb
// status conditions.
func applyOwnershipConditions(gslb *k8gbv1beta1io.Gslb, decision *ownership.Decision) {
	conflictHosts := make([]string, 0, len(decision.Conflicts))
	for host := range decision.Conflicts {
		conflictHosts = append(conflictHosts, host)
	}
	sort.Strings(conflictHosts)

	if len(conflictHosts) > 0 {
		messages := make([]string, 0, len(conflictHosts))
		for _, host := range conflictHosts {
			messages = append(messages, fmt.Sprintf("%s owned by %s", host, ownership.OwnerRef(decision.Conflicts[host])))
		}
		meta.SetStatusCondition(&gslb.Status.Conditions, metav1.Condition{
			Type:               ownership.ConditionConflict,
			Status:             metav1.ConditionTrue,
			Reason:             ownership.ReasonConflicting,
			Message:            "computed DNS records withheld: " + strings.Join(messages, "; "),
			ObservedGeneration: gslb.Generation,
		})
	} else {
		meta.SetStatusCondition(&gslb.Status.Conditions, metav1.Condition{
			Type:               ownership.ConditionConflict,
			Status:             metav1.ConditionFalse,
			Reason:             ownership.ReasonPublished,
			Message:            "this Gslb is the recorded owner of all its hostnames",
			ObservedGeneration: gslb.Generation,
		})
	}

	handoffHosts := make([]string, 0, len(decision.Handoff))
	for host := range decision.Handoff {
		handoffHosts = append(handoffHosts, host)
	}
	sort.Strings(handoffHosts)
	if len(handoffHosts) > 0 {
		meta.SetStatusCondition(&gslb.Status.Conditions, metav1.Condition{
			Type:               ownership.ConditionHandoff,
			Status:             metav1.ConditionTrue,
			Reason:             ownership.ReasonTakingOver,
			Message:            "taking over hostnames: " + strings.Join(handoffHosts, ", "),
			ObservedGeneration: gslb.Generation,
		})
	} else {
		meta.SetStatusCondition(&gslb.Status.Conditions, metav1.Condition{
			Type:               ownership.ConditionHandoff,
			Status:             metav1.ConditionFalse,
			Reason:             ownership.ReasonIdle,
			Message:            "no hostname handoff in progress",
			ObservedGeneration: gslb.Generation,
		})
	}
}
