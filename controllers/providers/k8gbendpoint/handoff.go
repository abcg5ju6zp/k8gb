// SnapshotEndpoints converts external-dns endpoints into a persistable, frozen
// representation. The snapshot is both the "last usable result" published while
// a ResourceRef handoff is pending and the evidence carried by publish receipts.
func SnapshotEndpoints(endpoints []*externaldns.Endpoint) []k8gbv1beta1io.PublishedEndpoint {
	if len(endpoints) == 0 {
		return nil
	}
	snapshot := make([]k8gbv1beta1io.PublishedEndpoint, 0, len(endpoints))
	for _, e := range endpoints {
		if e == nil {
			continue
		}
		published := k8gbv1beta1io.PublishedEndpoint{
			DNSName:    e.DNSName,
			RecordType: e.RecordType,
			RecordTTL:  int64(e.RecordTTL),
		}
		if len(e.Targets) > 0 {
			published.Targets = slices.Clone(e.Targets)
		}
		if len(e.Labels) > 0 {
			published.Labels = maps.Clone(e.Labels)
		}
		snapshot = append(snapshot, published)
	}
	return snapshot
}

// RestoreEndpoints converts frozen endpoints back into external-dns endpoints.
func RestoreEndpoints(snapshot []k8gbv1beta1io.PublishedEndpoint) []*externaldns.Endpoint {
	if len(snapshot) == 0 {
		return nil
	}
	endpoints := make([]*externaldns.Endpoint, 0, len(snapshot))
	for _, p := range snapshot {
		endpoints = append(endpoints, restoreEndpoint(p))
	}
	return endpoints
}

func restoreEndpoint(p k8gbv1beta1io.PublishedEndpoint) *externaldns.Endpoint {
	e := &externaldns.Endpoint{
		DNSName:    p.DNSName,
		RecordType: p.RecordType,
		RecordTTL:  externaldns.TTL(p.RecordTTL),
	}
	if len(p.Targets) > 0 {
		e.Targets = slices.Clone(p.Targets)
	}
	if len(p.Labels) > 0 {
		e.Labels = maps.Clone(p.Labels)
	}
	return e
}

// EndpointHost returns the hostname an endpoint belongs to, stripping the
// localtargets- prefix. Endpoints with any other unrecognized prefix are
// reported as-is so that callers can clip them against the pinned host set.
func EndpointHost(e *externaldns.Endpoint) string {
	if e == nil {
		return ""
	}
	if host, ok := trimLocalTargetsPrefix(e.DNSName); ok {
		return host
	}
	return e.DNSName
}

func trimLocalTargetsPrefix(dnsName string) (string, bool) {
	if len(dnsName) > len(localTargetsPrefix) && dnsName[:len(localTargetsPrefix)] == localTargetsPrefix {
		return dnsName[len(localTargetsPrefix):], true
	}
	return "", false
}

// HostOfPublishedEndpoint returns the hostname a frozen record belongs to,
// stripping the localtargets- prefix.
func HostOfPublishedEndpoint(p k8gbv1beta1io.PublishedEndpoint) string {
	if host, ok := trimLocalTargetsPrefix(p.DNSName); ok {
		return host
	}
	return p.DNSName
}

// MergeHandoffEndpoints builds the DNSEndpoint content for one handoff
// reconciliation. Hostnames in validatedHosts are served from the freshly
// computed candidate; every other pinned hostname keeps the frozen last usable
// result. The merge is hard-clipped to pinnedHosts: neither the pending path
// nor the takeover path can publish a hostname outside the set pinned at
// switch start, and recomputation can never expand the scope.
func MergeHandoffEndpoints(
	pinnedHosts []string,
	frozen []k8gbv1beta1io.PublishedEndpoint,
	candidate []*externaldns.Endpoint,
	validatedHosts map[string]bool,
) []*externaldns.Endpoint {
	frozenByHost := indexPublishedByHost(frozen)
	candidateByHost := indexEndpointsByHost(candidate)

	merged := make([]*externaldns.Endpoint, 0, len(frozen)+len(candidate))
	seen := make(map[string]bool, len(pinnedHosts))
	for _, host := range pinnedHosts {
		seen[host] = true
		if validatedHosts[host] {
			merged = appendHostEndpoints(merged, host, candidateByHost[host])
			continue
		}
		merged = appendPublishedEndpoints(merged, frozenByHost[host])
	}
	return merged
}

func indexEndpointsByHost(endpoints []*externaldns.Endpoint) map[string][]*externaldns.Endpoint {
	indexed := make(map[string][]*externaldns.Endpoint)
	for _, e := range endpoints {
		if e == nil {
			continue
		}
		host := EndpointHost(e)
		indexed[host] = append(indexed[host], e)
	}
	return indexed
}

func indexPublishedByHost(endpoints []k8gbv1beta1io.PublishedEndpoint) map[string][]k8gbv1beta1io.PublishedEndpoint {
	indexed := make(map[string][]k8gbv1beta1io.PublishedEndpoint)
	for i := range endpoints {
		if host, ok := trimLocalTargetsPrefix(endpoints[i].DNSName); ok {
			indexed[host] = append(indexed[host], endpoints[i])
			continue
		}
		indexed[endpoints[i].DNSName] = append(indexed[endpoints[i].DNSName], endpoints[i])
	}
	return indexed
}

// appendHostEndpoints appends the localtargets record (if present) before the
// host record to keep record ordering stable.
func appendHostEndpoints(merged []*externaldns.Endpoint, host string, records []*externaldns.Endpoint) []*externaldns.Endpoint {
	var hostRecord *externaldns.Endpoint
	for _, e := range records {
		if e.DNSName == host {
			hostRecord = e
			continue
		}
		merged = append(merged, e)
	}
	if hostRecord != nil {
		merged = append(merged, hostRecord)
	}
	return merged
}

func appendPublishedEndpoints(merged []*externaldns.Endpoint, records []k8gbv1beta1io.PublishedEndpoint) []*externaldns.Endpoint {
	var hostRecord *k8gbv1beta1io.PublishedEndpoint
	for i := range records {
		if _, ok := trimLocalTargetsPrefix(records[i].DNSName); ok {
			merged = append(merged, restoreEndpoint(records[i]))
			continue
		}
		record := records[i]
		hostRecord = &record
	}
	if hostRecord != nil {
		merged = append(merged, restoreEndpoint(*hostRecord))
	}
	return merged
}

// VerifyPublishedEndpoint verifies that the live DNSEndpoint matches the
// publish receipt exactly (record names, types, targets and labels). The
// receipt is only used to backfill status when the write it describes is
// actually observable in the API; a rolled-back or partial write never
// confirms the takeover.
func VerifyPublishedEndpoint(live *externaldnsApi.DNSEndpoint, receipt []k8gbv1beta1io.PublishedEndpoint) bool {
	if live == nil {
		return false
	}
	liveByHost := indexEndpointsByHost(live.Spec.Endpoints)
	for _, published := range receipt {
		host := published.DNSName
		if stripped, ok := trimLocalTargetsPrefix(published.DNSName); ok {
			host = stripped
		}
		var match *externaldns.Endpoint
		for _, e := range liveByHost[host] {
			if e.DNSName == published.DNSName {
				match = e
				break
			}
		}
		if match == nil || !endpointsEqual(match, restoreEndpoint(published)) {
			return false
		}
	}
	return true
}

func endpointsEqual(a, b *externaldns.Endpoint) bool {
	if a.DNSName != b.DNSName || a.RecordType != b.RecordType {
		return false
	}
	if !slices.Equal(sortedCopy(a.Targets), sortedCopy(b.Targets)) {
		return false
	}
	return maps.Equal(a.Labels, b.Labels)
}

func sortedCopy(in []string) []string {
	out := slices.Clone(in)
	slices.Sort(out)
	return out
}

// NewHandoffDNSEndpointObject builds the owned DNSEndpoint object carrying the
// merged handoff content, preserving the annotations and labels the
// application endpoint provider publishes with.
func NewHandoffDNSEndpointObject(gslbNamespace, gslbName string, endpoints []*externaldns.Endpoint) *externaldnsApi.DNSEndpoint {
	return &externaldnsApi.DNSEndpoint{
		ObjectMeta: metav1.ObjectMeta{
			Name:        gslbName,
			Namespace:   gslbNamespace,
			Annotations: map[string]string{dnsTypeAnnotation: localDNSType, legacyDNSTypeAnnotation: localDNSType},
			Labels:      map[string]string{dnsTypeAnnotation: localDNSType, legacyDNSTypeAnnotation: localDNSType},
		},
		Spec: externaldnsApi.DNSEndpointSpec{
			Endpoints: endpoints,
		},
	}
}

// ValidatedHostsFromCandidate reports the pinned hostnames for which the
// candidate produced a fully resolved, publishable host A record (non-empty
// targets). Hostnames which only appear as localtargets records, which are
// outside the pinned set, or which resolved without targets do not take over.
func ValidatedHostsFromCandidate(pinnedHosts []string, candidate []*externaldns.Endpoint) (map[string]bool, error) {
	pinned := make(map[string]bool, len(pinnedHosts))
	for _, host := range pinnedHosts {
		pinned[host] = false
	}
	for _, e := range candidate {
		if e == nil || e.RecordType != "A" {
			continue
		}
		host := e.DNSName
		if _, ok := trimLocalTargetsPrefix(host); ok {
			// localtargets records alone do not validate a takeover
			continue
		}
		if _, known := pinned[host]; !known {
			// recomputation can never expand the hostname scope
			return nil, fmt.Errorf("candidate DNSEndpoint resolves hostname %s outside the pinned handoff set %v", host, pinnedHosts)
		}
		if len(e.Targets) > 0 {
			pinned[host] = true
		}
	}
	return pinned, nil
}
