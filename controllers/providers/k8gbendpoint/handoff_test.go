func TestSnapshotRestoreRoundTrip(t *testing.T) {
	endpoints := []*externaldns.Endpoint{
		{
			DNSName:    "localtargets-a.example.com",
			RecordType: "A",
			RecordTTL:  externaldns.TTL(30),
			Targets:    []string{"1.1.1.1"},
		},
		{
			DNSName:    "a.example.com",
			RecordType: "A",
			RecordTTL:  externaldns.TTL(30),
			Targets:    []string{"1.1.1.1", "2.2.2.2"},
			Labels:     externaldns.Labels{"strategy": "roundRobin", "weight-eu-0-5": "1.1.1.1"},
		},
	}
	snapshot := SnapshotEndpoints(endpoints)
	require.Len(t, snapshot, 2)
	assert.Equal(t, "a.example.com", snapshot[1].DNSName)
	assert.Equal(t, int64(30), snapshot[1].RecordTTL)
	assert.Equal(t, []string{"1.1.1.1", "2.2.2.2"}, snapshot[1].Targets)
	assert.Equal(t, "roundRobin", snapshot[1].Labels["strategy"])

	restored := RestoreEndpoints(snapshot)
	require.Len(t, restored, 2)
	assert.Equal(t, externaldns.TTL(30), restored[1].RecordTTL)
	assert.Equal(t, endpoints[1].Targets, restored[1].Targets)
	assert.Equal(t, endpoints[1].Labels, restored[1].Labels)
}

func TestMergeHandoffEndpointsKeepsFrozenForPendingAndCandidateForValidated(t *testing.T) {
	pinned := []string{"a.example.com", "b.example.com"}
	frozen := []publishedFixtureRecord{
		{dnsName: "localtargets-a.example.com", targets: []string{"10.0.0.1"}},
		{dnsName: "a.example.com", targets: []string{"10.0.0.1"}},
		{dnsName: "localtargets-b.example.com", targets: []string{"10.0.0.2"}},
		{dnsName: "b.example.com", targets: []string{"10.0.0.2"}},
	}
	candidate := []*externaldns.Endpoint{
		{
			DNSName:    "localtargets-b.example.com",
			RecordType: "A",
			RecordTTL:  30,
			Targets:    []string{"20.0.0.2"},
		},
		{
			DNSName:    "b.example.com",
			RecordType: "A",
			RecordTTL:  30,
			Targets:    []string{"20.0.0.2"},
			Labels:     externaldns.Labels{"strategy": "roundRobin"},
		},
	}
	merged := MergeHandoffEndpoints(pinned, toPublished(frozen), candidate,
		map[string]bool{"b.example.com": true})

	byName := map[string]*externaldns.Endpoint{}
	for _, e := range merged {
		byName[e.DNSName] = e
	}
	require.Contains(t, byName, "localtargets-a.example.com")
	require.Contains(t, byName, "a.example.com")
	require.Contains(t, byName, "localtargets-b.example.com")
	require.Contains(t, byName, "b.example.com")

	// pending host keeps the previous owner result untouched
	assert.Equal(t, []string{"10.0.0.1"}, []string(byName["a.example.com"].Targets))
	assert.Equal(t, []string{"10.0.0.1"}, []string(byName["localtargets-a.example.com"].Targets))
	// validated host serves the candidate result
	assert.Equal(t, []string{"20.0.0.2"}, []string(byName["b.example.com"].Targets))
	assert.Equal(t, []string{"20.0.0.2"}, []string(byName["localtargets-b.example.com"].Targets))
	assert.Equal(t, "roundRobin", byName["b.example.com"].Labels["strategy"])

	// ordering: localtargets precedes the host A record per host, pinned hosts in order
	assert.Equal(t, "localtargets-a.example.com", merged[0].DNSName)
	assert.Equal(t, "a.example.com", merged[1].DNSName)
	assert.Equal(t, "localtargets-b.example.com", merged[2].DNSName)
	assert.Equal(t, "b.example.com", merged[3].DNSName)
}

func TestMergeHandoffEndpointsNeverPublishesOutsidePinnedSet(t *testing.T) {
	pinned := []string{"a.example.com"}
	frozen := []publishedFixtureRecord{
		{dnsName: "localtargets-a.example.com", targets: []string{"10.0.0.1"}},
		{dnsName: "a.example.com", targets: []string{"10.0.0.1"}},
	}
	// candidate resolved an extra host the old owner never published and lost b
	candidate := []*externaldns.Endpoint{
		{DNSName: "localtargets-a.example.com", RecordType: "A", Targets: []string{"20.0.0.1"}},
		{DNSName: "a.example.com", RecordType: "A", Targets: []string{"20.0.0.1"}},
		{DNSName: "localtargets-extra.example.com", RecordType: "A", Targets: []string{"9.9.9.9"}},
		{DNSName: "extra.example.com", RecordType: "A", Targets: []string{"9.9.9.9"}},
	}
	merged := MergeHandoffEndpoints(pinned, toPublished(frozen), candidate,
		map[string]bool{"a.example.com": true})
	for _, e := range merged {
		assert.NotContains(t, e.DNSName, "extra.example.com",
			"handoff merge must never expand the pinned hostname set")
	}
}

func TestValidatedHostsFromCandidate(t *testing.T) {
	pinned := []string{"a.example.com", "b.example.com", "c.example.com"}
	candidate := []*externaldns.Endpoint{
		// localtargets alone must not validate the host
		{DNSName: "localtargets-a.example.com", RecordType: "A", Targets: []string{"1.1.1.1"}},
		{DNSName: "b.example.com", RecordType: "A", Targets: []string{"2.2.2.2"}},
		{DNSName: "c.example.com", RecordType: "A"}, // empty targets, not validated
	}
	validated, err := ValidatedHostsFromCandidate(pinned, candidate)
	require.NoError(t, err)
	assert.False(t, validated["a.example.com"])
	assert.True(t, validated["b.example.com"])
	assert.False(t, validated["c.example.com"])

	// a recomputed hostname outside the pinned set is rejected, never expanded
	outOfScope := make([]*externaldns.Endpoint, 0, len(candidate)+1)
	outOfScope = append(outOfScope, candidate...)
	outOfScope = append(outOfScope,
		&externaldns.Endpoint{DNSName: "new.example.com", RecordType: "A", Targets: []string{"3.3.3.3"}})
	_, err = ValidatedHostsFromCandidate(pinned, outOfScope)
	require.Error(t, err)
}

func TestVerifyPublishedEndpoint(t *testing.T) {
	receipt := toPublished([]publishedFixtureRecord{
		{dnsName: "localtargets-a.example.com", ttl: 30, targets: []string{"10.0.0.1"}},
		{dnsName: "a.example.com", ttl: 30, targets: []string{"10.0.0.1", "10.0.0.2"},
			labels: map[string]string{"strategy": "roundRobin"}},
	})

	live := &externaldnsApi.DNSEndpoint{
		ObjectMeta: metav1.ObjectMeta{Name: "gslb", Namespace: "default"},
		Spec:       externaldnsApi.DNSEndpointSpec{Endpoints: RestoreEndpoints(receipt)},
	}
	assert.True(t, VerifyPublishedEndpoint(live, receipt), "exact receipt content must confirm")

	// target drift (e.g. stale reconciliation wrote old targets back) must not confirm
	drifted := live.DeepCopy()
	drifted.Spec.Endpoints[1].Targets = []string{"66.66.66.66"}
	assert.False(t, VerifyPublishedEndpoint(drifted, receipt))

	// label drift must not confirm
	labelDrift := live.DeepCopy()
	labelDrift.Spec.Endpoints[1].Labels = map[string]string{"strategy": "failover"}
	assert.False(t, VerifyPublishedEndpoint(labelDrift, receipt))

	// missing record must not confirm
	missing := live.DeepCopy()
	missing.Spec.Endpoints = missing.Spec.Endpoints[:1]
	assert.False(t, VerifyPublishedEndpoint(missing, receipt))

	assert.False(t, VerifyPublishedEndpoint(nil, receipt))
}

type publishedFixtureRecord struct {
	dnsName string
	ttl     int64
	targets []string
	labels  map[string]string
}

func toPublished(fixtures []publishedFixtureRecord) []k8gbv1beta1io.PublishedEndpoint {
	out := make([]k8gbv1beta1io.PublishedEndpoint, 0, len(fixtures))
	for _, f := range fixtures {
		out = append(out, k8gbv1beta1io.PublishedEndpoint{
			DNSName:    f.dnsName,
			RecordType: "A",
			RecordTTL:  f.ttl,
			Targets:    f.targets,
			Labels:     f.labels,
		})
	}
	return out
}
