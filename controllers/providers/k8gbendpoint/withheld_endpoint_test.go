import (
	"testing"

	k8gbv1beta1io "github.com/k8gb-io/k8gb/api/v1beta1io"
	"github.com/stretchr/testify/assert"
	externaldns "sigs.k8s.io/external-dns/endpoint"
)

func TestNewWithheldEndpointIsNotSelectedByDNSFilters(t *testing.T) {
	gslb := &k8gbv1beta1io.Gslb{}
	gslb.Name = "demo"
	gslb.Namespace = "team-a"

	d := &ApplicationDNSEndpoint{gslb: gslb}
	ep := d.NewWithheldEndpoint([]*externaldns.Endpoint{
		{DNSName: "app.cloud.example.com", RecordType: "A", Targets: externaldns.Targets{"10.0.0.1"}},
	}, []string{"team-b/other"})

	assert.Equal(t, "demo-withheld", ep.Name)
	assert.Equal(t, "team-a", ep.Namespace)
	// neither CoreDNS (local) nor embedded external-dns (extdns) label filters match
	assert.Equal(t, withheldDNSType, ep.Labels[dnsTypeAnnotation])
	assert.Equal(t, withheldDNSType, ep.Labels[legacyDNSTypeAnnotation])
	assert.NotEqual(t, localDNSType, ep.Labels[dnsTypeAnnotation])
	assert.NotEqual(t, externalDNSTypeCommon, ep.Labels[dnsTypeAnnotation])
	assert.Equal(t, "team-b/other", ep.Annotations[withheldOwnersAnnotation])
	requireLen := len(ep.Spec.Endpoints)
	assert.Equal(t, 1, requireLen)
}

func TestWithheldEndpointNameMatchesOwnershipConvention(t *testing.T) {
	gslb := &k8gbv1beta1io.Gslb{}
	gslb.Name = "demo"
	d := &ApplicationDNSEndpoint{gslb: gslb}
	assert.Equal(t, "demo-withheld", d.WithheldEndpointName())
	assert.LessOrEqual(t, len(d.WithheldEndpointName()), 63)
}
