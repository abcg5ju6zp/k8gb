import (
	"crypto/sha256"
	"encoding/hex"
	"strings"

	k8gbv1beta1io "github.com/k8gb-io/k8gb/api/v1beta1io"
	externaldns "sigs.k8s.io/external-dns/endpoint"
)

const (
	// localTargetsPrefix mirrors the prefix used by the DNSEndpoint builder for
	// per-cluster localtargets-<host> glue records.
	localTargetsPrefix = "localtargets-"
	// WithheldDNSType marks DNSEndpoint objects whose computed records must not
	// be picked up by CoreDNS/external-dns label filters (k8gb.io/dnstype=local).
	WithheldDNSType = "withheld"
	// WithheldEndpointSuffix is appended to a Gslb name to derive the name of
	// the DNSEndpoint holding records the Gslb computed but must not publish.
	WithheldEndpointSuffix = "-withheld"
)

// NormalizeHostname returns the canonical hostname used as ownership key.
// Comparison is case-insensitive and a single trailing dot is ignored, so
// "App.Example.com." and "app.example.com" denote the same ownership.
func NormalizeHostname(host string) string {
	return strings.ToLower(strings.TrimSuffix(strings.TrimSpace(host), "."))
}

// LeaseName returns the metadata.name of the HostnameOwnership object for host.
// The normalized hostname is already a valid DNS subdomain; wildcard labels are
// translated to keep the object name RFC 1123 compliant.
func LeaseName(host string) string {
	normalized := NormalizeHostname(host)
	if strings.HasPrefix(normalized, "*.") {
		return "wildcard-" + strings.TrimPrefix(normalized, "*.")
	}
	return normalized
}

// EndpointHost maps a DNSEndpoint record DNS name back to the governed host.
func EndpointHost(dnsName string) string {
	return NormalizeHostname(strings.TrimPrefix(dnsName, localTargetsPrefix))
}

// WithheldEndpointName derives the name of the withheld DNSEndpoint object for
// a Gslb, keeping within the 63 character DNS label limit.
func WithheldEndpointName(gslbName string) string {
	name := gslbName + WithheldEndpointSuffix
	if len(name) <= 63 {
		return name
	}
	sum := sha256.Sum256([]byte(gslbName))
	hash := hex.EncodeToString(sum[:])[:8]
	keep := 63 - len(WithheldEndpointSuffix) - len(hash) - 1
	if keep < 1 {
		keep = 1
	}
	if keep > len(gslbName) {
		keep = len(gslbName)
	}
	return gslbName[:keep] + "-" + hash + WithheldEndpointSuffix
}

// ClaimedHosts returns the normalized hosts declared by a Gslb based on its
// resolved servers.
func ClaimedHosts(gslb *k8gbv1beta1io.Gslb) map[string]bool {
	hosts := make(map[string]bool)
	for _, server := range gslb.Status.Servers {
		if server == nil || server.Host == "" {
			continue
		}
		hosts[NormalizeHostname(server.Host)] = true
	}
	return hosts
}

// HostDigests pairs a host A record from a computed DNSEndpoint with the
// digest of its content. Only the A record carrying the hostname itself is a
// publication record; localtargets glue records follow the same ownership but
// carry no digest of their own.
func HostDigests(eps []*externaldns.Endpoint) map[string]string {
	digests := make(map[string]string)
	for _, ep := range eps {
		if ep == nil {
			continue
		}
		host := EndpointHost(ep.DNSName)
		if strings.HasPrefix(ep.DNSName, localTargetsPrefix) {
			continue
		}
		digests[host] = DigestEndpoint(ep)
	}
	return digests
}
