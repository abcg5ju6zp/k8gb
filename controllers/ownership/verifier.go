import (
	"context"

	"github.com/k8gb-io/k8gb/controllers/utils"
)

// PublishVerifier re-checks the externally observable DNS publication fact.
// Every implementation must treat uncertain results (timeouts, errors, empty
// answers) as "not confirmed": ownership cleanup is only safe on a positive
// confirmation.
type PublishVerifier interface {
	// VerifiesExternally reports whether the verifier can observe external DNS.
	// When false, callers fall back to the persisted DNSEndpoint publication fact.
	VerifiesExternally() bool
	PublishConfirmed(ctx context.Context, host string, expectedTargets []string) bool
}

// DNSVerifier confirms publication by resolving the hostname through the
// configured edge/parent zone nameservers and checking that every expected
// target is present in the returned A record set.
type DNSVerifier struct {
	queryService utils.DNSQueryService
	nameservers  utils.DNSList
}

func NewDNSVerifier(queryService utils.DNSQueryService, nameservers utils.DNSList) *DNSVerifier {
	return &DNSVerifier{queryService: queryService, nameservers: nameservers}
}

func (v *DNSVerifier) VerifiesExternally() bool {
	return v != nil && len(v.nameservers) > 0
}

func (v *DNSVerifier) PublishConfirmed(_ context.Context, host string, expectedTargets []string) bool {
	if !v.VerifiesExternally() || v.queryService == nil || len(expectedTargets) == 0 {
		return false
	}
	result := v.queryService.Query(host, v.nameservers)
	if result.Err != nil || result.Msg == nil {
		return false
	}
	observed := v.queryService.ExtractARecords(result.Msg)
	if len(observed) == 0 {
		return false
	}
	observedSet := make(map[string]struct{}, len(observed))
	for _, ip := range observed {
		observedSet[ip] = struct{}{}
	}
	for _, expected := range expectedTargets {
		if _, ok := observedSet[expected]; !ok {
			return false
		}
	}
	return true
}
