import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"sort"
	"strings"

	externaldnsApi "sigs.k8s.io/external-dns/apis/v1alpha1"
	externaldns "sigs.k8s.io/external-dns/endpoint"
)

// digestContent is the canonical representation of a DNS record whose hash is
// recorded as the claimant target digest.
type digestContent struct {
	RecordType string   `json:"recordType"`
	DNSName    string   `json:"dnsName"`
	TTL        int64    `json:"ttl"`
	Targets    []string `json:"targets"`
}

// DigestEndpoint returns a stable digest of an external-dns endpoint record.
// The digest covers record type, name, TTL and the sorted target set, so equal
// publications hash equally regardless of target ordering.
func DigestEndpoint(e *externaldns.Endpoint) string {
	if e == nil {
		return ""
	}
	targets := append([]string{}, e.Targets...)
	sort.Strings(targets)
	content := digestContent{
		RecordType: e.RecordType,
		DNSName:    strings.ToLower(e.DNSName),
		TTL:        int64(e.RecordTTL),
		Targets:    targets,
	}
	payload, err := json.Marshal(content)
	if err != nil {
		// json.Marshal of this struct cannot realistically fail
		return ""
	}
	sum := sha256.Sum256(payload)
	return hex.EncodeToString(sum[:])[:16]
}

// PartitionEndpoints splits computed DNSEndpoint records into records the
// Gslb is allowed to publish and records it must withhold because another
// Gslb owns the hostname.
func PartitionEndpoints(
	endpoints []*externaldns.Endpoint,
	owners map[string]bool,
) (published []*externaldns.Endpoint, withheld []*externaldns.Endpoint) {
	for _, ep := range endpoints {
		if ep == nil {
			continue
		}
		host := EndpointHost(ep.DNSName)
		if owners[host] {
			published = append(published, ep)
			continue
		}
		withheld = append(withheld, ep)
	}
	return published, withheld
}

// HostTargetsFromPublished extracts the A record targets of host from a
// persisted DNSEndpoint and reports whether such a record exists.
func HostTargetsFromPublished(ep *externaldnsApi.DNSEndpoint, host string) ([]string, bool) {
	if ep == nil {
		return nil, false
	}
	for _, record := range ep.Spec.Endpoints {
		if record == nil {
			continue
		}
		if strings.HasPrefix(record.DNSName, localTargetsPrefix) {
			continue
		}
		if EndpointHost(record.DNSName) == host {
			return append([]string{}, record.Targets...), true
		}
	}
	return nil, false
}
