// Condition types reported on Gslb status.
const (
	// ConditionConflict is True when the Gslb claims hostnames owned by
	// another Gslb; its computed records are withheld from external DNS.
	ConditionConflict = "HostnameOwnershipConflict"
	// ConditionHandoff is True while the Gslb is taking over a hostname from
	// a releasing owner.
	ConditionHandoff = "HostnameHandoff"

	reasonPublished   = "Published"
	reasonConflicting = "ConflictingClaim"
	reasonTakingOver  = "TakingOver"
	reasonIdle        = "Idle"

	// arbitrationAttempts bounds in-loop optimistic-concurrency retries.
	arbitrationAttempts = 3
)

// ClaimValidation is the freshly re-validated state of one claimant.
type ClaimValidation struct {
	// Claims reports that the Gslb still references the hostname.
	Claims bool
	// Healthy reports the observed service health for the hostname.
	Healthy bool
}

// ClaimValidator re-resolves a Gslb's references and health for a hostname.
// It is implemented by the controllers package to avoid import cycles.
type ClaimValidator interface {
	ValidateClaim(ctx context.Context, gslb *k8gbv1beta1io.Gslb, host string) (ClaimValidation, error)
}

// Decision is the per-Gslb outcome of hostname ownership arbitration.
type Decision struct {
	// Owners lists normalized hostnames this Gslb is allowed to publish.
	Owners map[string]bool
	// Conflicts lists normalized hostnames withheld because another Gslb owns
	// them, together with the recorded owner.
	Conflicts map[string]k8gbv1beta1io.HostnameClaimant
	// Handoff lists normalized hostnames this Gslb just took (or is taking)
	// over from a releasing owner.
	Handoff map[string]bool
}

func newDecision() *Decision {
	return &Decision{
		Owners:    map[string]bool{},
		Conflicts: map[string]k8gbv1beta1io.HostnameClaimant{},
		Handoff:   map[string]bool{},
	}
}

// AllowAllDecision returns a decision that publishes every claimed host. It
// preserves the legacy behavior when ownership arbitration is not enabled.
func AllowAllDecision(hosts map[string]bool) *Decision {
	d := newDecision()
	for host := range hosts {
		d.Owners[host] = true
	}
	return d
}

// PublishedHosts returns the host records the Gslb is allowed to publish.
func (d *Decision) PublishedHosts() map[string]bool { return d.Owners }

// Manager arbitrates persistent per-hostname ownership between Gslbs.
type Manager struct {
	client    client.Client
	logger    *zerolog.Logger
	validator ClaimValidator
	verifier  PublishVerifier
}

func NewManager(c client.Client, logger *zerolog.Logger, validator ClaimValidator, verifier PublishVerifier) *Manager {
	return &Manager{client: c, logger: logger, validator: validator, verifier: verifier}
}

// ReconcileHosts arbitrates ownership for every hostname the Gslb declares.
// digests maps normalized hostnames to the digest of the Gslb's computed
// A record. The returned decision tells the caller which computed records may
// be published and which must be withheld.
func (m *Manager) ReconcileHosts(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	digests map[string]string,
) (*Decision, error) {
	decision := newDecision()
	hosts := make([]string, 0, len(digests))
	for host := range digests {
		hosts = append(hosts, host)
	}
	sort.Strings(hosts)
	for _, host := range hosts {
		if err := m.reconcileHost(ctx, gslb, host, digests[host], decision); err != nil {
			return decision, err
		}
	}
	return decision, nil
}

func (m *Manager) reconcileHost(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	host, digest string,
	decision *Decision,
) error {
	var lastOwner *k8gbv1beta1io.HostnameClaimant
	for attempt := 0; attempt < arbitrationAttempts; attempt++ {
		lease := &k8gbv1beta1io.HostnameOwnership{}
		err := m.client.Get(ctx, client.ObjectKey{Name: LeaseName(host)}, lease)
		if apierrors.IsNotFound(err) {
			fresh := newLease(host, gslb, digest)
			if createErr := m.client.Create(ctx, fresh); createErr != nil {
				if apierrors.IsAlreadyExists(createErr) {
					continue // another claimant won the race, re-arbitrate
				}
				// Ownership write failed: do not assume ownership, keep the
				// currently persisted owner untouched and retry later.
				return createErr
			}
			decision.Owners[host] = true
			return nil
		}
		if err != nil {
			return err
		}
		if lease.Spec.Owner != nil {
			lastOwner = lease.Spec.Owner.DeepCopy()
		}

		retry, err := m.arbitrate(ctx, gslb, host, digest, lease, decision)
		if err != nil {
			return err
		}
		if !retry {
			return nil
		}
	}
	// Optimistic-concurrency contention could not be settled in-loop: keep
	// serving only when the persisted record clearly identifies this Gslb as
	// owner, otherwise withhold this cycle and requeue.
	if lastOwner != nil && lastOwner.UID == gslb.UID {
		decision.Owners[host] = true
	} else {
		m.logger.Warn().
			Str("hostname", host).
			Str("gslb", fmt.Sprintf("%s/%s", gslb.Namespace, gslb.Name)).
			Msg("Ownership arbitration contention; withholding publication this cycle")
		if lastOwner != nil {
			decision.Conflicts[host] = *lastOwner
		} else {
			decision.Conflicts[host] = k8gbv1beta1io.HostnameClaimant{}
		}
	}
	return nil
}

// arbitrate applies the ownership state machine to one freshly read lease.
// The retry flag is true when the lease was changed concurrently and the
// caller must re-read and arbitrate again using the new ownership version.
func (m *Manager) arbitrate(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	host, digest string,
	lease *k8gbv1beta1io.HostnameOwnership,
	decision *Decision,
) (bool, error) {
	switch {
	case lease.Spec.Owner != nil && lease.Spec.Owner.UID == gslb.UID:
		return m.arbitrateOwner(ctx, gslb, host, digest, lease, decision)
	case lease.Spec.Phase == k8gbv1beta1io.OwnershipPhaseReleasing &&
		lease.Spec.Successor != nil && lease.Spec.Successor.UID == gslb.UID:
		return m.arbitrateSuccessor(ctx, gslb, host, digest, lease, decision)
	default:
		return m.arbitrateOtherOwner(ctx, gslb, host, lease, decision)
	}
}

// arbitrateOwner handles a lease whose recorded owner is the reconciling Gslb.
func (m *Manager) arbitrateOwner(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	host, digest string,
	lease *k8gbv1beta1io.HostnameOwnership,
	decision *Decision,
) (bool, error) {
	if lease.Spec.Phase == k8gbv1beta1io.OwnershipPhaseReleasing {
		valid, err := m.successorStillValid(ctx, host, lease.Spec.Successor)
		if err != nil {
			return false, err
		}
		if !valid {
			// Original owner recovered, or the designated successor vanished
			// before taking over: cancel the release under a new ownership
			// version.
			lease.Spec.Phase = k8gbv1beta1io.OwnershipPhaseActive
			lease.Spec.Successor = nil
			lease.Spec.Epoch++
			if err := m.update(ctx, lease); err != nil {
				return m.handleWriteConflict(err)
			}
		}
	}
	if lease.Spec.PreviousOwner != nil {
		stale, err := m.previousOwnerMarkerStale(ctx, lease.Spec.PreviousOwner, host)
		if err != nil {
			return false, err
		}
		if stale {
			lease.Spec.PreviousOwner = nil
			if err := m.update(ctx, lease); err != nil {
				return m.handleWriteConflict(err)
			}
		}
	}
	// Refresh recorded claimant facts (generation/strategy/target digest)
	// without changing the ownership version.
	if self := claimantFor(gslb, digest); claimantChanged(lease.Spec.Owner, self) {
		lease.Spec.Owner = self
		if err := m.update(ctx, lease); err != nil {
			return m.handleWriteConflict(err)
		}
	}
	decision.Owners[host] = true
	return false, nil
}

// arbitrateSuccessor handles a lease in which the reconciling Gslb is the
// designated successor of a releasing owner.
func (m *Manager) arbitrateSuccessor(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	host, digest string,
	lease *k8gbv1beta1io.HostnameOwnership,
	decision *Decision,
) (bool, error) {
	validation, err := m.validator.ValidateClaim(ctx, gslb, host)
	if err != nil {
		return false, err
	}
	if !validation.Claims || !validation.Healthy {
		// References or health no longer support the takeover; wait for the
		// releasing owner to re-elect another successor.
		decision.Conflicts[host] = *lease.Spec.Owner
		return false, nil
	}
	candidates, _, err := m.electCandidates(ctx, host, gslb, lease.Spec.Owner.UID)
	if err != nil {
		return false, err
	}
	lease.Spec.Phase = k8gbv1beta1io.OwnershipPhaseActive
	lease.Spec.PreviousOwner = lease.Spec.Owner.DeepCopy()
	lease.Spec.Owner = claimantFor(gslb, digest)
	lease.Spec.Successor = nil
	lease.Spec.Candidates = candidates
	lease.Spec.Epoch++
	if err := m.update(ctx, lease); err != nil {
		return m.handleWriteConflict(err)
	}
	decision.Owners[host] = true
	decision.Handoff[host] = true
	return false, nil
}

// arbitrateOtherOwner handles a lease owned by a different Gslb: the computed
// records are withheld, and a released owner triggers the election of a
// successor through a new ownership version.
func (m *Manager) arbitrateOtherOwner(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	host string,
	lease *k8gbv1beta1io.HostnameOwnership,
	decision *Decision,
) (bool, error) {
	currentOwner := lease.Spec.Owner
	if currentOwner == nil {
		// Transient record without owner: do not publish; requeue.
		return false, nil
	}
	retry, err := m.clearStalePreviousOwner(ctx, host, lease)
	if err != nil || retry {
		return retry, err
	}
	released, err := m.ownerReleased(ctx, currentOwner, host)
	if err != nil {
		return false, err
	}
	if released && lease.Spec.Phase == k8gbv1beta1io.OwnershipPhaseActive {
		retry, err := m.startSuccessorElection(ctx, gslb, host, currentOwner, lease)
		if err != nil || retry {
			return retry, err
		}
	}
	// The owner stays authoritative this cycle; the computed records of this
	// Gslb are withheld and surfaced via a queryable status condition.
	decision.Conflicts[host] = *currentOwner
	return false, nil
}

// clearStalePreviousOwner forgets a previous-owner marker left by an owner
// that changed hostname while alive. A deleting previous owner is retained
// until it confirms successor publication during finalization.
func (m *Manager) clearStalePreviousOwner(
	ctx context.Context,
	host string,
	lease *k8gbv1beta1io.HostnameOwnership,
) (bool, error) {
	if lease.Spec.Phase != k8gbv1beta1io.OwnershipPhaseActive || lease.Spec.PreviousOwner == nil {
		return false, nil
	}
	stale, err := m.previousOwnerMarkerStale(ctx, lease.Spec.PreviousOwner, host)
	if err != nil || !stale {
		return false, err
	}
	lease.Spec.PreviousOwner = nil
	if err := m.update(ctx, lease); err != nil {
		return m.handleWriteConflict(err)
	}
	return true, nil
}

// startSuccessorElection re-validates the live claimants of a released
// hostname and either marks a successor under a new ownership version or
// removes the orphaned lease when no claimant remains.
func (m *Manager) startSuccessorElection(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	host string,
	currentOwner *k8gbv1beta1io.HostnameClaimant,
	lease *k8gbv1beta1io.HostnameOwnership,
) (bool, error) {
	candidates, successor, err := m.electCandidates(ctx, host, gslb, currentOwner.UID)
	if err != nil {
		return false, err
	}
	if successor == nil {
		if err := m.client.Delete(ctx, lease); err != nil && !apierrors.IsNotFound(err) {
			if apierrors.IsConflict(err) {
				return true, nil
			}
			return false, err
		}
		return true, nil
	}
	lease.Spec.Phase = k8gbv1beta1io.OwnershipPhaseReleasing
	lease.Spec.Successor = successor
	lease.Spec.Candidates = candidates
	lease.Spec.Epoch++
	if err := m.update(ctx, lease); err != nil {
		return m.handleWriteConflict(err)
	}
	return false, nil
}

// Finalize drives ownership release for a deleting Gslb. It returns true when
// every formerly owned hostname has either no remaining claimants (lease
// removed) or a successor that has published and been confirmed, meaning the
// Gslb finalizer may safely be removed.
func (m *Manager) Finalize(ctx context.Context, gslb *k8gbv1beta1io.Gslb) (bool, error) {
	leases := &k8gbv1beta1io.HostnameOwnershipList{}
	if err := m.client.List(ctx, leases); err != nil {
		return false, err
	}
	pending := 0
	for i := range leases.Items {
		lease := &leases.Items[i]
		handled, err := m.finalizeLease(ctx, gslb, lease)
		if err != nil {
			return false, err
		}
		if !handled {
			pending++
		}
	}
	return pending == 0, nil
}

func (m *Manager) finalizeLease(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	lease *k8gbv1beta1io.HostnameOwnership,
) (bool, error) {
	// A deleting Gslb that was designated successor withdraws so the owner can
	// re-elect someone else.
	if lease.Spec.Successor != nil && lease.Spec.Successor.UID == gslb.UID {
		lease.Spec.Successor = nil
		if err := m.update(ctx, lease); err != nil {
			if apierrors.IsConflict(err) {
				return false, nil
			}
			return false, err
		}
		return false, nil
	}

	// Successor already took over: confirm publication before allowing the
	// old endpoint to be garbage collected.
	if lease.Spec.PreviousOwner != nil && lease.Spec.PreviousOwner.UID == gslb.UID &&
		lease.Spec.Owner != nil && lease.Spec.Owner.UID != gslb.UID {
		confirmed, err := m.successorPublishConfirmed(ctx, lease)
		if err != nil {
			return false, err
		}
		if !confirmed {
			return false, nil
		}
		lease.Spec.PreviousOwner = nil
		if err := m.update(ctx, lease); err != nil {
			if apierrors.IsConflict(err) {
				return false, nil
			}
			return false, err
		}
		return true, nil
	}

	if lease.Spec.Owner == nil || lease.Spec.Owner.UID != gslb.UID {
		// Lease is unrelated to this Gslb.
		return true, nil
	}

	candidates, successor, err := m.electCandidates(ctx, lease.Spec.Hostname, gslb, gslb.UID)
	if err != nil {
		return false, err
	}
	if successor == nil {
		// Nobody else claims the hostname; release ownership entirely. The
		// Gslb DNSEndpoint will be garbage collected together with the Gslb.
		if err := m.client.Delete(ctx, lease); err != nil && !apierrors.IsNotFound(err) {
			if apierrors.IsConflict(err) {
				return false, nil
			}
			return false, err
		}
		return true, nil
	}

	if lease.Spec.Phase == k8gbv1beta1io.OwnershipPhaseActive ||
		lease.Spec.Successor == nil || lease.Spec.Successor.UID != successor.UID {
		// Begin or correct the handoff under a new ownership version.
		lease.Spec.Phase = k8gbv1beta1io.OwnershipPhaseReleasing
		lease.Spec.Successor = successor
		lease.Spec.Candidates = candidates
		lease.Spec.Epoch++
		if err := m.update(ctx, lease); err != nil {
			if apierrors.IsConflict(err) {
				return false, nil
			}
			return false, err
		}
	}
	// Handoff initiated; keep the old DNSEndpoint (and finalizer) in place
	// until the successor takes over and publication is confirmed.
	return false, nil
}

// successorPublishConfirmed re-checks the publication fact instead of trusting
// any earlier save result: the successor DNSEndpoint must carry the recorded
// target digest and those targets must be observable in external DNS.
func (m *Manager) successorPublishConfirmed(ctx context.Context, lease *k8gbv1beta1io.HostnameOwnership) (bool, error) {
	owner := lease.Spec.Owner
	endpoint := &externaldnsApi.DNSEndpoint{}
	err := m.client.Get(ctx, client.ObjectKey{Namespace: owner.Namespace, Name: owner.Name}, endpoint)
	if err != nil {
		if apierrors.IsNotFound(err) {
			return false, nil
		}
		return false, err
	}
	targets, found := HostTargetsFromPublished(endpoint, lease.Spec.Hostname)
	if !found || len(targets) == 0 {
		return false, nil
	}
	if owner.TargetsDigest != "" {
		var record *externaldns.Endpoint
		for _, e := range endpoint.Spec.Endpoints {
			if e != nil && EndpointHost(e.DNSName) == lease.Spec.Hostname &&
				!isLocalTargetsRecord(e.DNSName) {
				record = e
				break
			}
		}
		if record == nil || DigestEndpoint(record) != owner.TargetsDigest {
			return false, nil
		}
	}
	// Without external observation (e.g. edge DNS servers not configured) the
	// persisted successor DNSEndpoint with matching digest is the publication
	// fact. Otherwise the external DNS answer must contain every target.
	if m.verifier == nil || !m.verifier.VerifiesExternally() {
		return true, nil
	}
	return m.verifier.PublishConfirmed(ctx, lease.Spec.Hostname, targets), nil
}

// previousOwnerMarkerStale reports whether a recorded previous owner may be
// forgotten: the object is gone, or it is alive (not deleting) and no longer
// declares the hostname. A deleting previous owner is never stale here because
// it still needs the marker to confirm the handoff.
func (m *Manager) previousOwnerMarkerStale(
	ctx context.Context,
	previous *k8gbv1beta1io.HostnameClaimant,
	host string,
) (bool, error) {
	current := &k8gbv1beta1io.Gslb{}
	err := m.client.Get(ctx, client.ObjectKey{Namespace: previous.Namespace, Name: previous.Name}, current)
	if apierrors.IsNotFound(err) {
		return true, nil
	}
	if err != nil {
		return false, err
	}
	if current.DeletionTimestamp != nil {
		return false, nil
	}
	if len(current.Status.Servers) == 0 {
		return false, nil
	}
	return !ClaimedHosts(current)[host], nil
}

// ownerReleased reports whether the recorded owner can no longer serve the
// hostname: object gone, being deleted, or it no longer declares the hostname
// (hostname change). An owner with unresolved status is treated as serving.
func (m *Manager) ownerReleased(ctx context.Context, owner *k8gbv1beta1io.HostnameClaimant, host string) (bool, error) {
	current := &k8gbv1beta1io.Gslb{}
	err := m.client.Get(ctx, client.ObjectKey{Namespace: owner.Namespace, Name: owner.Name}, current)
	if apierrors.IsNotFound(err) {
		return true, nil
	}
	if err != nil {
		return false, err
	}
	if current.DeletionTimestamp != nil {
		return true, nil
	}
	if len(current.Status.Servers) == 0 {
		// Status not populated yet (e.g. owner bootstrapping): never steal.
		return false, nil
	}
	return !ClaimedHosts(current)[host], nil
}

// successorStillValid re-validates a designated successor's references and
// health. A nil or vanished successor is invalid; validation errors on other
// objects conservatively report "still valid" to avoid flapping handoffs.
func (m *Manager) successorStillValid(ctx context.Context, host string, successor *k8gbv1beta1io.HostnameClaimant) (bool, error) {
	if successor == nil {
		return false, nil
	}
	current := &k8gbv1beta1io.Gslb{}
	err := m.client.Get(ctx, client.ObjectKey{Namespace: successor.Namespace, Name: successor.Name}, current)
	if apierrors.IsNotFound(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if current.DeletionTimestamp != nil {
		return false, nil
	}
	validation, err := m.validator.ValidateClaim(ctx, current, host)
	if err != nil {
		return true, nil
	}
	return validation.Claims && validation.Healthy, nil
}

// electCandidates lists and re-validates every live claimant of host in stable
// (namespace, name) order. Healthy claimants are preferred over unhealthy ones
// when choosing the successor; gslb is the in-memory reconciled Gslb whose
// just-computed status must be trusted for its own entry.
func (m *Manager) electCandidates(
	ctx context.Context,
	host string,
	gslb *k8gbv1beta1io.Gslb,
	excludeUID types.UID,
) ([]k8gbv1beta1io.HostnameClaimant, *k8gbv1beta1io.HostnameClaimant, error) {
	list := &k8gbv1beta1io.GslbList{}
	if err := m.client.List(ctx, list); err != nil {
		return nil, nil, err
	}
	sort.SliceStable(list.Items, func(i, j int) bool {
		if list.Items[i].Namespace != list.Items[j].Namespace {
			return list.Items[i].Namespace < list.Items[j].Namespace
		}
		return list.Items[i].Name < list.Items[j].Name
	})

	candidates := make([]k8gbv1beta1io.HostnameClaimant, 0)
	var firstValid, firstHealthy *k8gbv1beta1io.HostnameClaimant
	for i := range list.Items {
		candidate := &list.Items[i]
		if candidate.UID == excludeUID || candidate.DeletionTimestamp != nil {
			continue
		}
		var validation ClaimValidation
		switch {
		case candidate.UID == gslb.UID:
			validation = ClaimValidation{
				Claims:  ClaimedHosts(gslb)[host],
				Healthy: gslb.Status.ServiceHealth[host] == k8gbv1beta1io.Healthy,
			}
		case !ClaimedHosts(candidate)[host]:
			continue
		default:
			v, err := m.validator.ValidateClaim(ctx, candidate, host)
			if err != nil {
				return nil, nil, err
			}
			validation = v
		}
		if !validation.Claims {
			continue
		}
		claim := claimantFor(candidate, "")
		candidates = append(candidates, *claim)
		if firstValid == nil {
			firstValid = claim
		}
		if validation.Healthy && firstHealthy == nil {
			firstHealthy = claim
		}
	}
	successor := firstHealthy
	if successor == nil {
		successor = firstValid
	}
	return candidates, successor, nil
}

func (m *Manager) handleWriteConflict(err error) (retry bool, out error) {
	if apierrors.IsConflict(err) {
		return true, nil
	}
	return false, err
}

func (m *Manager) update(ctx context.Context, lease *k8gbv1beta1io.HostnameOwnership) error {
	return m.client.Update(ctx, lease)
}

func newLease(host string, gslb *k8gbv1beta1io.Gslb, digest string) *k8gbv1beta1io.HostnameOwnership {
	owner := claimantFor(gslb, digest)
	return &k8gbv1beta1io.HostnameOwnership{
		ObjectMeta: metav1.ObjectMeta{
			Name: LeaseName(host),
		},
		Spec: k8gbv1beta1io.HostnameOwnershipSpec{
			Hostname:   host,
			Phase:      k8gbv1beta1io.OwnershipPhaseActive,
			Epoch:      1,
			Owner:      owner,
			Candidates: []k8gbv1beta1io.HostnameClaimant{*owner},
		},
	}
}

func claimantFor(gslb *k8gbv1beta1io.Gslb, digest string) *k8gbv1beta1io.HostnameClaimant {
	return &k8gbv1beta1io.HostnameClaimant{
		Name:          gslb.Name,
		Namespace:     gslb.Namespace,
		UID:           gslb.UID,
		Generation:    gslb.Generation,
		Strategy:      gslb.Spec.Strategy.Type,
		PrimaryGeoTag: gslb.Spec.Strategy.PrimaryGeoTag,
		TargetsDigest: digest,
	}
}

func claimantChanged(current, desired *k8gbv1beta1io.HostnameClaimant) bool {
	if current == nil {
		return true
	}
	return current.Generation != desired.Generation ||
		current.Strategy != desired.Strategy ||
		current.PrimaryGeoTag != desired.PrimaryGeoTag ||
		current.TargetsDigest != desired.TargetsDigest
}

func isLocalTargetsRecord(dnsName string) bool {
	return len(dnsName) > len(localTargetsPrefix) && dnsName[:len(localTargetsPrefix)] == localTargetsPrefix
}

// OwnerRef returns a human-readable owner reference for status messages.
func OwnerRef(c k8gbv1beta1io.HostnameClaimant) string {
	return fmt.Sprintf("%s/%s", c.Namespace, c.Name)
}

