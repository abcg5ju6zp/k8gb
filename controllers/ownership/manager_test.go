func TestFinalizeWaitsForSuccessorThenConfirmsPublication(t *testing.T) {
	a := gslbFixture("a", "ns-a", "uid-a", []string{host}, true)
	a.DeletionTimestamp = ptrNow()
	a.Finalizers = []string{"k8gb.io/hostname-ownership"}
	b := gslbFixture("b", "ns-b", "uid-b", []string{host}, true)
	lease := &k8gbv1beta1io.HostnameOwnership{
		ObjectMeta: metav1.ObjectMeta{Name: LeaseName(host)},
		Spec: k8gbv1beta1io.HostnameOwnershipSpec{
			Hostname: host,
			Phase:    k8gbv1beta1io.OwnershipPhaseActive,
			Epoch:    1,
			Owner:    claimantFor(gslbFixture("a", "ns-a", "uid-a", nil, true), "old"),
		},
	}
	c := fake.NewClientBuilder().WithScheme(newTestScheme(t)).WithObjects(a, b, lease).Build()
	v := &fakeValidator{validations: map[types.UID]ClaimValidation{
		"uid-b": {Claims: true, Healthy: true},
	}}
	verifier := &fakeVerifier{enabled: true, confirmed: false}
	m := NewManager(c, nil, v, verifier)

	// first finalize: handoff initiated, old owner must wait
	done, err := m.Finalize(context.Background(), a)
	require.NoError(t, err)
	assert.False(t, done)
	l := getLease(t, c)
	assert.Equal(t, k8gbv1beta1io.OwnershipPhaseReleasing, l.Spec.Phase)
	require.NotNil(t, l.Spec.Successor)
	assert.Equal(t, types.UID("uid-b"), l.Spec.Successor.UID)
	assert.Equal(t, int64(2), l.Spec.Epoch)

	// successor B reconciles and takes over
	targets := []string{"10.0.0.9"}
	digest := DigestEndpoint(endpointTargets(targets...))
	decision, err := m.ReconcileHosts(context.Background(), b, map[string]string{host: digest})
	require.NoError(t, err)
	assert.True(t, decision.Owners[host])

	// successor's DNSEndpoint exists but external publication is not confirmed yet
	bEndpoint := &externaldnsApi.DNSEndpoint{
		ObjectMeta: metav1.ObjectMeta{Name: b.Name, Namespace: b.Namespace},
		Spec: externaldnsApi.DNSEndpointSpec{Endpoints: []*externaldns.Endpoint{
			endpointTargets(targets...),
		}},
	}
	require.NoError(t, c.Create(context.Background(), bEndpoint))

	done, err = m.Finalize(context.Background(), a)
	require.NoError(t, err)
	require.False(t, done, "old targets must not be cleaned before publication is verified")
	assert.Equal(t, 1, verifier.calls)

	// once publication is observable, finalization completes and previousOwner clears
	verifier.confirmed = true
	done, err = m.Finalize(context.Background(), a)
	require.NoError(t, err)
	assert.True(t, done)
	assert.Equal(t, host, verifier.lastHost)
	assert.Equal(t, targets, verifier.lastWant)
	l = getLease(t, c)
	assert.Nil(t, l.Spec.PreviousOwner)
	assert.Equal(t, types.UID("uid-b"), l.Spec.Owner.UID)
}

