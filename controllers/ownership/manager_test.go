func gslbFixture(name, namespace, uid string, hosts []string, healthy bool) *k8gbv1beta1io.Gslb {
	servers := make([]*k8gbv1beta1io.Server, 0, len(hosts))
	health := map[string]k8gbv1beta1io.HealthStatus{}
	for _, h := range hosts {
		servers = append(servers, &k8gbv1beta1io.Server{Host: h})
		if healthy {
			health[h] = k8gbv1beta1io.Healthy
		} else {
			health[h] = k8gbv1beta1io.Unhealthy
		}
	}
	return &k8gbv1beta1io.Gslb{
		ObjectMeta: metav1.ObjectMeta{
			Name:       name,
			Namespace:  namespace,
			UID:        types.UID(uid),
			Generation: 1,
		},
		Spec: k8gbv1beta1io.GslbSpec{
			Strategy: k8gbv1beta1io.Strategy{Type: "roundRobin"},
		},
		Status: k8gbv1beta1io.GslbStatus{
			Servers:       servers,
			ServiceHealth: health,
		},
	}
}

