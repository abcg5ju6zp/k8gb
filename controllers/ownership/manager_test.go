type fakeVerifier struct {
	enabled   bool
	confirmed bool
	calls     int
	lastHost  string
	lastWant  []string
}

func (f *fakeVerifier) VerifiesExternally() bool { return f.enabled }

func (f *fakeVerifier) PublishConfirmed(_ context.Context, host string, want []string) bool {
	f.calls++
	f.lastHost = host
	f.lastWant = append([]string{}, want...)
	return f.confirmed
}

