func TestConflictorWithholdsAndDoesNotRewriteLease(t *testing.T) {
	a := gslbFixture("a", "ns-a", "uid-a", []string{host}, true)
	c := fake.NewClientBuilder().WithScheme(newTestScheme(t)).WithObjects(a).Build()
	m := NewManager(c, nil,
		&fakeValidator{validations: map[types.UID]ClaimValidation{
			"uid-a": {Claims: true, Healthy: true},
			"uid-b": {Claims: true, Healthy: true},
		}}, &fakeVerifier{})

	// owner A
	_, err := m.ReconcileHosts(context.Background(), a, digestsFor(a))
	require.NoError(t, err)
	leaseBefore := getLease(t, c)
	rv := leaseBefore.ResourceVersion

	// conflicting B
	b := gslbFixture("b", "ns-b", "uid-b", []string{host}, true)
	decision, err := m.ReconcileHosts(context.Background(), b, digestsFor(b))
	require.NoError(t, err)
	assert.False(t, decision.Owners[host])
	owner, conflict := decision.Conflicts[host]
	require.True(t, conflict)
	assert.Equal(t, "ns-a/a", OwnerRef(owner))
	assert.Empty(t, decision.Handoff)

	// lease must not be rewritten by the conflictor
	leaseAfter := getLease(t, c)
	assert.Equal(t, rv, leaseAfter.ResourceVersion)
	assert.Equal(t, types.UID("uid-a"), leaseAfter.Spec.Owner.UID)
}

