func TestOrphanOwnerTriggersElectionAndSuccessorTakeover(t *testing.T) {
	// owner A exists in the lease but its Gslb object is gone
	lease := &k8gbv1beta1io.HostnameOwnership{
		ObjectMeta: metav1.ObjectMeta{Name: LeaseName(host)},
		Spec: k8gbv1beta1io.HostnameOwnershipSpec{
			Hostname: host,
			Phase:    k8gbv1beta1io.OwnershipPhaseActive,
			Epoch:    1,
			Owner:    claimantFor(gslbFixture("a", "ns-a", "uid-a", []string{host}, true), ""),
		},
	}
	b := gslbFixture("b", "ns-b", "uid-b", []string{host}, true)
	c := fake.NewClientBuilder().WithScheme(newTestScheme(t)).WithObjects(lease, b).Build()
	v := &fakeValidator{validations: map[types.UID]ClaimValidation{
		"uid-b": {Claims: true, Healthy: true},
	}}
	m := NewManager(c, nil, v, &fakeVerifier{})

	// first B pass catalyzes the release but does not publish yet
	decision, err := m.ReconcileHosts(context.Background(), b, digestsFor(b))
	require.NoError(t, err)
	assert.False(t, decision.Owners[host])
	releasing := getLease(t, c)
	assert.Equal(t, k8gbv1beta1io.OwnershipPhaseReleasing, releasing.Spec.Phase)
	require.NotNil(t, releasing.Spec.Successor)
	assert.Equal(t, types.UID("uid-b"), releasing.Spec.Successor.UID)
	assert.Equal(t, int64(2), releasing.Spec.Epoch)

	// second pass performs the version-arbitrated takeover
	decision, err = m.ReconcileHosts(context.Background(), b, digestsFor(b))
	require.NoError(t, err)
	assert.True(t, decision.Owners[host])
	assert.True(t, decision.Handoff[host])
	active := getLease(t, c)
	assert.Equal(t, k8gbv1beta1io.OwnershipPhaseActive, active.Spec.Phase)
	assert.Equal(t, types.UID("uid-b"), active.Spec.Owner.UID)
	require.NotNil(t, active.Spec.PreviousOwner)
	assert.Equal(t, types.UID("uid-a"), active.Spec.PreviousOwner.UID)
	assert.Nil(t, active.Spec.Successor)
	assert.Equal(t, int64(3), active.Spec.Epoch)
}

