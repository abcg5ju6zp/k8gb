import (
	"context"
	"time"

	appsv1 "k8s.io/api/apps/v1"
	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/client"
)

// Clock abstracts time so timeout behavior is deterministically testable.
type Clock interface {
	Now() time.Time
}

// SystemClock is the production Clock.
type SystemClock struct{}

// Now returns the current wall clock time.
func (SystemClock) Now() time.Time { return time.Now() }

// WaitResult classifies a single non-blocking readiness/rollout observation.
type WaitResult int

const (
	// WaitInProgress means the workload is still rolling out or not yet observed.
	WaitInProgress WaitResult = iota
	// WaitReady means the canary Deployment serves its single replica and probes pass.
	WaitReady
	// WaitComplete means the production Deployment finished the rollout without unavailable replicas.
	WaitComplete
	// WaitTimedOut means the configured deadline elapsed before readiness/completion.
	WaitTimedOut
)

// Rollouts observes canary and production Deployment rollout states. It never
// blocks: callers poll through reconciliation requeues and watch events.
type Rollouts struct {
	client         client.Client
	namespace      string
	clock          Clock
	canaryTimeout  time.Duration
	rolloutTimeout time.Duration
}

// NewRollouts constructs the rollout observer. Timeouts come from operator
// configuration and are guaranteed to be positive during config validation.
func NewRollouts(c client.Client, namespace string, clock Clock, canaryTimeout, rolloutTimeout time.Duration) *Rollouts {
	if clock == nil {
		clock = SystemClock{}
	}
	return &Rollouts{
		client:         c,
		namespace:      namespace,
		clock:          clock,
		canaryTimeout:  canaryTimeout,
		rolloutTimeout: rolloutTimeout,
	}
}

// WaitCanary observes the fixed canary Deployment. A missing Deployment (still
// being created) and not-yet-ready status both report progress; readiness is
// derived from Deployment status which already reflects the existing
// readiness/liveness probe results.
func (r *Rollouts) WaitCanary(ctx context.Context, since time.Time) (WaitResult, error) {
	depl := &appsv1.Deployment{}
	err := r.client.Get(ctx, types.NamespacedName{Name: CanaryDeploymentName, Namespace: r.namespace}, depl)
	if apierrors.IsNotFound(err) {
		return WaitInProgress, nil
	}
	if err != nil {
		return WaitInProgress, err
	}
	if CanaryReady(depl) {
		return WaitReady, nil
	}
	if !since.IsZero() && r.clock.Now().Sub(since) >= r.canaryTimeout {
		return WaitTimedOut, nil
	}
	return WaitInProgress, nil
}

// WaitProduction observes the production Deployment rolling to the generation
// that was just patched into its pod template.
func (r *Rollouts) WaitProduction(ctx context.Context, name string, since time.Time) (WaitResult, error) {
	depl := &appsv1.Deployment{}
	err := r.client.Get(ctx, types.NamespacedName{Name: name, Namespace: r.namespace}, depl)
	if apierrors.IsNotFound(err) {
		return WaitInProgress, nil
	}
	if err != nil {
		return WaitInProgress, err
	}
	if RolloutComplete(depl) {
		return WaitComplete, nil
	}
	if !since.IsZero() && r.clock.Now().Sub(since) >= r.rolloutTimeout {
		return WaitTimedOut, nil
	}
	return WaitInProgress, nil
}

// CanaryReady reports whether the single canary replica has been updated, is
// ready and available, and no replica is unavailable.
func CanaryReady(depl *appsv1.Deployment) bool {
	if depl == nil || depl.Status.ObservedGeneration < depl.Generation {
		return false
	}
	const desired int32 = 1
	return depl.Status.UpdatedReplicas >= desired &&
		depl.Status.ReadyReplicas >= desired &&
		depl.Status.AvailableReplicas >= desired &&
		depl.Status.UnavailableReplicas == 0
}

// RolloutComplete reports whether the production Deployment observed its
// latest generation and every desired replica is updated, ready and available
// with no unavailable condition present.
func RolloutComplete(depl *appsv1.Deployment) bool {
	if depl == nil || depl.Status.ObservedGeneration < depl.Generation {
		return false
	}
	desired := int32(1)
	if depl.Spec.Replicas != nil {
		desired = *depl.Spec.Replicas
	}
	if depl.Status.UpdatedReplicas != desired ||
		depl.Status.ReadyReplicas < desired ||
		depl.Status.AvailableReplicas != desired ||
		depl.Status.UnavailableReplicas != 0 {
		return false
	}
	for _, condition := range depl.Status.Conditions {
		if condition.Type == appsv1.DeploymentAvailable && condition.Status == corev1.ConditionFalse {
			return false
		}
		if condition.Type == appsv1.DeploymentReplicaFailure && condition.Status == corev1.ConditionTrue {
			return false
		}
	}
	return true
}
