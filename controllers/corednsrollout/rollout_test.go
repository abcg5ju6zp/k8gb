func canaryDeployment(status appsv1.DeploymentStatus, gen int64) *appsv1.Deployment {
	one := int32(1)
	return &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{
			Name:       CanaryDeploymentName,
			Namespace:  testNamespace,
			Generation: gen,
		},
		Spec:   appsv1.DeploymentSpec{Replicas: &one},
		Status: status,
	}
}

func TestCanaryReadyStatuses(t *testing.T) {
	// TR-6.3: readiness is derived from observed generation and the
	// updated/ready/available replica counters that already reflect probes.
	ready := appsv1.DeploymentStatus{
		ObservedGeneration:  3,
		Replicas:            1,
		UpdatedReplicas:     1,
		ReadyReplicas:       1,
		AvailableReplicas:   1,
		UnavailableReplicas: 0,
	}
	cases := []struct {
		name   string
		gen    int64
		status appsv1.DeploymentStatus
		ready  bool
	}{
		{name: "all targets met", gen: 3, status: ready, ready: true},
		{name: "observed generation lags", gen: 3, status: func() appsv1.DeploymentStatus {
			s := ready
			s.ObservedGeneration = 2
			return s
		}(), ready: false},
		{name: "pod not updated yet", gen: 3, status: func() appsv1.DeploymentStatus {
			s := ready
			s.UpdatedReplicas = 0
			s.ReadyReplicas = 1
			s.AvailableReplicas = 1
			return s
		}(), ready: false},
		{name: "pod not ready (probe failing)", gen: 3, status: func() appsv1.DeploymentStatus {
			s := ready
			s.ReadyReplicas = 0
			s.AvailableReplicas = 0
			s.UnavailableReplicas = 1
			return s
		}(), ready: false},
		{name: "unavailable replica remains", gen: 3, status: func() appsv1.DeploymentStatus {
			s := ready
			s.UnavailableReplicas = 1
			return s
		}(), ready: false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.ready, CanaryReady(canaryDeployment(tc.status, tc.gen)))
		})
	}
	assert.False(t, CanaryReady(nil))
}

func TestRolloutCompleteStatuses(t *testing.T) {
	// TR-6.3: production completion requires observed generation, every
	// desired replica updated/available and no blocking condition.
	two := int32(2)
	complete := appsv1.DeploymentStatus{
		ObservedGeneration: 5,
		Replicas:           2,
		UpdatedReplicas:    2,
		ReadyReplicas:      2,
		AvailableReplicas:  2,
		Conditions: []appsv1.DeploymentCondition{{
			Type:   appsv1.DeploymentAvailable,
			Status: corev1.ConditionTrue,
		}},
	}
	production := func(status appsv1.DeploymentStatus, gen int64) *appsv1.Deployment {
		return &appsv1.Deployment{
			ObjectMeta: metav1.ObjectMeta{Name: "coredns", Namespace: testNamespace, Generation: gen},
			Spec:       appsv1.DeploymentSpec{Replicas: &two},
			Status:     status,
		}
	}

	require.True(t, RolloutComplete(production(complete, 5)))

	lagging := complete
	lagging.ObservedGeneration = 4
	assert.False(t, RolloutComplete(production(lagging, 5)), "observed generation lag")

	partial := complete
	partial.UpdatedReplicas = 1
	partial.AvailableReplicas = 1
	partial.Replicas = 2
	assert.False(t, RolloutComplete(production(partial, 5)), "only one replica rolled")

	notReady := complete
	notReady.ReadyReplicas = 1
	assert.False(t, RolloutComplete(production(notReady, 5)), "one replica not ready")

	unavailable := complete
	unavailable.Conditions = append(unavailable.Conditions, appsv1.DeploymentCondition{
		Type:   appsv1.DeploymentReplicaFailure,
		Status: corev1.ConditionTrue,
	})
	assert.False(t, RolloutComplete(production(unavailable, 5)), "replica failure condition present")

	availableFalse := complete
	availableFalse.Conditions = []appsv1.DeploymentCondition{{
		Type:   appsv1.DeploymentAvailable,
		Status: corev1.ConditionFalse,
	}}
	assert.False(t, RolloutComplete(production(availableFalse, 5)), "available condition false")
}

func TestWaitCanary(t *testing.T) {
	// TR-6.1: not found/not ready report progress without probing; deadline
	// exhaustion reports timeout; readiness reports ready.
	ctx := context.Background()
	start := time.Date(2026, 10, 10, 8, 0, 0, 0, time.UTC)

	// canary resource not created yet
	r := rolloutsFor(t, start)
	res, err := r.WaitCanary(ctx, start)
	require.NoError(t, err)
	assert.Equal(t, WaitInProgress, res)

	// canary exists but pod is not ready, well within timeout
	notReady := appsv1.DeploymentStatus{ObservedGeneration: 1, UpdatedReplicas: 1, Replicas: 1}
	r = rolloutsFor(t, start.Add(30*time.Second), canaryDeployment(notReady, 1))
	res, err = r.WaitCanary(ctx, start)
	require.NoError(t, err)
	assert.Equal(t, WaitInProgress, res)

	// still not ready at/after the timeout
	r = rolloutsFor(t, start.Add(testCanaryTimeout), canaryDeployment(notReady, 1))
	res, err = r.WaitCanary(ctx, start)
	require.NoError(t, err)
	assert.Equal(t, WaitTimedOut, res)

	// a zero start time (state reconstructed without a deadline) never times out
	r = rolloutsFor(t, start.Add(10*time.Hour), canaryDeployment(notReady, 1))
	res, err = r.WaitCanary(ctx, time.Time{})
	require.NoError(t, err)
	assert.Equal(t, WaitInProgress, res)

	// ready beats timeout: ready state at the same instant reports ready
	readyStatus := appsv1.DeploymentStatus{
		ObservedGeneration: 1, Replicas: 1, UpdatedReplicas: 1,
		ReadyReplicas: 1, AvailableReplicas: 1,
	}
	r = rolloutsFor(t, start.Add(testCanaryTimeout), canaryDeployment(readyStatus, 1))
	res, err = r.WaitCanary(ctx, start)
	require.NoError(t, err)
	assert.Equal(t, WaitReady, res)
}

func TestWaitProduction(t *testing.T) {
	// TR-6.2: production rollout reports complete/timed-out/in-progress; the
	// caller applies the restoration patch on timeout and keeps active
	// unchanged (covered end-to-end in coordinator tests).
	ctx := context.Background()
	start := time.Date(2026, 10, 10, 9, 0, 0, 0, time.UTC)
	two := int32(2)

	rolling := &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: "coredns", Namespace: testNamespace, Generation: 6},
		Spec:       appsv1.DeploymentSpec{Replicas: &two},
		Status:     appsv1.DeploymentStatus{ObservedGeneration: 6, Replicas: 2, UpdatedReplicas: 1, AvailableReplicas: 1},
	}
	r := rolloutsFor(t, start.Add(30*time.Second), rolling)
	res, err := r.WaitProduction(ctx, "coredns", start)
	require.NoError(t, err)
	assert.Equal(t, WaitInProgress, res)

	r = rolloutsFor(t, start.Add(testRolloutTimeout), rolling)
	res, err = r.WaitProduction(ctx, "coredns", start)
	require.NoError(t, err)
	assert.Equal(t, WaitTimedOut, res)

	done := rolling.DeepCopy()
	done.Status = appsv1.DeploymentStatus{
		ObservedGeneration: 6, Replicas: 2, UpdatedReplicas: 2, ReadyReplicas: 2, AvailableReplicas: 2,
		Conditions: []appsv1.DeploymentCondition{{Type: appsv1.DeploymentAvailable, Status: corev1.ConditionTrue}},
	}
	r = rolloutsFor(t, start.Add(testRolloutTimeout), done)
	res, err = r.WaitProduction(ctx, "coredns", start)
	require.NoError(t, err)
	assert.Equal(t, WaitComplete, res)

	// missing production deployment is treated as progress, not an error.
	r = rolloutsFor(t, start)
	res, err = r.WaitProduction(ctx, "coredns", start)
	require.NoError(t, err)
	assert.Equal(t, WaitInProgress, res)
}

func TestCanaryTimeoutScalesZeroAndQuarantines(t *testing.T) {
	// TR-6.1: on canary timeout the canary is scaled to zero and marked
	// quarantined while production carries the active generation; the
	// production Deployment/Service receive no promotion patches.
	ctx := context.Background()
	start := time.Date(2026, 10, 10, 8, 0, 0, 0, time.UTC)

	active := desiredZones("cloud.example.com")
	prodBg, prodSvc := productionFixture()
	prodBg.Spec.Template.Spec.Volumes[0].ConfigMap.Name = AnchorConfigMapName
	anchor := newAnchor(active.Data)
	anchor.Annotations[AnnActiveGeneration] = active.Fingerprint
	anchor.Annotations[AnnCandidateGeneration] = "candidate123"
	anchor.Annotations[AnnCandidatePhase] = string(PhaseCandidateRolling)
	genCM := &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:      GenerationConfigMapName("candidate123"),
			Namespace: testNamespace,
			Labels:    map[string]string{LabelManagedBy: ManagedByValue, LabelRole: RoleGeneration},
		},
	}
	notReady := appsv1.DeploymentStatus{ObservedGeneration: 1, Replicas: 1, UpdatedReplicas: 1}
	canary := canaryDeployment(notReady, 1)
	canary.Spec.Template.Spec.Volumes = []corev1.Volume{{
		Name: "dynamic-zones",
		VolumeSource: corev1.VolumeSource{ConfigMap: &corev1.ConfigMapVolumeSource{
			LocalObjectReference: corev1.LocalObjectReference{Name: GenerationConfigMapName("candidate123")},
		}},
	}}

	cb := fake.NewClientBuilder().WithScheme(testScheme(t)).
		WithObjects(anchor, genCM, prodBg, prodSvc, canary).Build()
	store := NewStore(cb, testNamespace)
	workloads := NewWorkloads(cb, testNamespace, testScheme(t), store, nil)
	roll := NewRollouts(cb, testNamespace, fakeClock{now: start.Add(testCanaryTimeout)},
		testCanaryTimeout, testRolloutTimeout)

	wl, err := workloads.Discover(ctx)
	require.NoError(t, err)
	snap := wl.Capture()

	res, err := roll.WaitCanary(ctx, start)
	require.NoError(t, err)
	require.Equal(t, WaitTimedOut, res)

	require.NoError(t, workloads.ScaleCanary(ctx, 0))
	diag := FailureDiagnostic{
		Hash: "candidate123", Phase: PhaseCandidateRolling, Reason: ReasonCanaryNotReady,
		Detail: "canary did not become ready within 120s", Timestamp: start.Add(testCanaryTimeout),
	}
	require.NoError(t, store.QuarantineCandidate(ctx, diag))

	gotCanary := &appsv1.Deployment{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: CanaryDeploymentName}, gotCanary))
	require.NotNil(t, gotCanary.Spec.Replicas)
	assert.Equal(t, int32(0), *gotCanary.Spec.Replicas)

	gotGen := &corev1.ConfigMap{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: GenerationConfigMapName("candidate123")}, gotGen))
	assert.Equal(t, ReasonCanaryNotReady, gotGen.Labels[LabelQuarantine])

	// Production untouched: still points at the anchor volume and the stable
	// Service has no generation selector.
	gotProd := &appsv1.Deployment{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotProd))
	assert.Equal(t, AnchorConfigMapName, gotProd.Spec.Template.Spec.Volumes[0].ConfigMap.Name)
	assert.NotContains(t, gotProd.Spec.Template.Labels, LabelGeneration)
	gotSvc := &corev1.Service{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotSvc))
	assert.Equal(t, snap.ServiceSelector, gotSvc.Spec.Selector)
}
