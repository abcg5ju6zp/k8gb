func zoneDelegation(zone string) v1beta1io.ZoneDelegation {
	return v1beta1io.ZoneDelegation{
		ObjectMeta: metav1.ObjectMeta{Name: zone},
		Spec: v1beta1io.ZoneDelegationSpec{
			LoadBalancedZone: zone,
			ParentZone:       "example.com",
		},
	}
}

func deletingZoneDelegation(zone string) v1beta1io.ZoneDelegation {
	zd := zoneDelegation(zone)
	now := metav1.NewTime(time.Now())
	zd.DeletionTimestamp = &now
	return zd
}

func TestNormalizeDeterministic(t *testing.T) {
	// TR-2.1: same set in any order renders identical data and fingerprint.
	zonesA := &v1beta1io.ZoneDelegationList{Items: []v1beta1io.ZoneDelegation{
		zoneDelegation("cloud.example.com"),
		zoneDelegation("cloud2.example.com"),
	}}
	zonesB := &v1beta1io.ZoneDelegationList{Items: []v1beta1io.ZoneDelegation{
		zoneDelegation("cloud2.example.com"),
		zoneDelegation("cloud.example.com"),
	}}

	desiredA := Normalize(zonesA)
	desiredB := Normalize(zonesB)

	assert.Equal(t, desiredA.Data, desiredB.Data)
	assert.Equal(t, desiredA.Fingerprint, desiredB.Fingerprint)
	assert.Len(t, desiredA.Data, 2)
	assert.Len(t, desiredA.Fingerprint, fingerprintLength)

	// TR-2.1: a one byte difference produces a different fingerprint.
	zonesDifferent := &v1beta1io.ZoneDelegationList{Items: []v1beta1io.ZoneDelegation{
		zoneDelegation("clou0.example.com"),
		zoneDelegation("cloud2.example.com"),
	}}
	assert.NotEqual(t, desiredA.Fingerprint, Normalize(zonesDifferent).Fingerprint)
}

func TestNormalizeRenderedBytes(t *testing.T) {
	// TR-2.1: rendered key/value are byte identical to the legacy zones package output.
	zone := "cloud.example.com"
	desired := Normalize(&v1beta1io.ZoneDelegationList{Items: []v1beta1io.ZoneDelegation{
		zoneDelegation(zone),
	}})
	expectedKey := "cloud-example-com.conf"
	expectedValue := "cloud.example.com:5353 {\n  import k8gbplugins\n}\n"
	assert.Contains(t, desired.Data, expectedKey)
	assert.Equal(t, expectedValue, desired.Data[expectedKey])
}

func TestNormalizeEmpty(t *testing.T) {
	desired := Normalize(&v1beta1io.ZoneDelegationList{})
	assert.Empty(t, desired.Data)
	assert.NotEmpty(t, desired.Fingerprint)
	assert.Equal(t, desired.Fingerprint, Normalize(nil).Fingerprint)
}

func TestNormalizeSkipsDeleting(t *testing.T) {
	// TR-2.3: zone delegations being deleted do not enter desired data.
	zones := &v1beta1io.ZoneDelegationList{Items: []v1beta1io.ZoneDelegation{
		zoneDelegation("cloud.example.com"),
		deletingZoneDelegation("cloud2.example.com"),
	}}
	desired := Normalize(zones)
	assert.Len(t, desired.Data, 1)
	assert.Contains(t, desired.Data, "cloud-example-com.conf")
	assert.NotContains(t, desired.Data, "cloud2-example-com.conf")

	onlyDeleting := Normalize(&v1beta1io.ZoneDelegationList{Items: []v1beta1io.ZoneDelegation{
		deletingZoneDelegation("cloud2.example.com"),
	}})
	assert.Empty(t, onlyDeleting.Data)
}

func TestGenerationConfigMapName(t *testing.T) {
	// TR-2.2: generation ConfigMap names are DNS-1123 compliant and within limits.
	desired := Normalize(&v1beta1io.ZoneDelegationList{Items: []v1beta1io.ZoneDelegation{
		zoneDelegation("cloud.example.com"),
	}})
	name := GenerationConfigMapName(desired.Fingerprint)
	assert.LessOrEqual(t, len(name), 253)
	assert.Empty(t, validation.IsDNS1123Subdomain(name))
	assert.Equal(t, GenerationConfigMapPrefix+desired.Fingerprint, name)
}
