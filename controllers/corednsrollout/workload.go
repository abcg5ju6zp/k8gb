// ChecksumAnnotation is stamped on production/canary pod templates with the
// generation fingerprint they serve.
const ChecksumAnnotation = "k8gb.io/zd-checksum"

// Discovery failure reasons; they are matched by callers to fall back to the
// legacy direct-anchor write path.
const (
	DiscoveryNoService          = "NoStableCoreDNSService"
	DiscoveryMultipleServices   = "MultipleStableCoreDNSServices"
	DiscoveryNoDeployment       = "NoProductionCoreDNSDeployment"
	DiscoveryMultipleDeployment = "MultipleProductionCoreDNSDeployments"
	DiscoveryMissingVolume      = "MissingDynamicZonesVolume"
)

// DiscoveryError marks workload topology conditions under which the generation
// rollout cannot run and legacy behavior must be used.
type DiscoveryError struct {
	Reason string
	Detail string
}

func (e *DiscoveryError) Error() string {
	return fmt.Sprintf("coreDNS workload discovery failed (%s): %s", e.Reason, e.Detail)
}

// IsDiscoveryError reports whether err is a DiscoveryError.
func IsDiscoveryError(err error) bool {
	var target *DiscoveryError
	return AsDiscoveryError(err, &target)
}

// AsDiscoveryError exposes errors.As for DiscoveryError.
func AsDiscoveryError(err error, target **DiscoveryError) bool {
	if err == nil {
		return false
	}
	if de, ok := err.(*DiscoveryError); ok {
		*target = de
		return true
	}
	return false
}

// StableWorkload is the discovered production CoreDNS topology.
type StableWorkload struct {
	Service    *corev1.Service
	Deployment *appsv1.Deployment
	scheme     *runtime.Scheme
}

// WorkloadSnapshot captures the exact production values mutated by a promotion,
// enabling an inverse restoration patch.
type WorkloadSnapshot struct {
	// VolumeConfigMapName is the dynamic-zones source before promotion.
	VolumeConfigMapName string
	// GenerationLabel is the pre-promotion value of the pod template label
	// (empty when absent).
	GenerationLabel string
	// HasGenerationLabel records whether the label key existed.
	HasGenerationLabel bool
	// ChecksumAnnotation is the pre-promotion template checksum (empty/absent).
	ChecksumAnnotation string
	// HasChecksum records whether the annotation key existed.
	HasChecksum bool
	// ServiceSelector is the stable Service selector before promotion.
	ServiceSelector map[string]string
}

// Workloads discovers production CoreDNS workloads and builds/patches canary
// and promotion objects.
type Workloads struct {
	client    client.Client
	namespace string
	scheme    *runtime.Scheme
	store     *Store
	log       *zerolog.Logger
}

func NewWorkloads(c client.Client, namespace string, scheme *runtime.Scheme, store *Store, log *zerolog.Logger) *Workloads {
	return &Workloads{client: c, namespace: namespace, scheme: scheme, store: store, log: log}
}

// Discover returns the unique stable CoreDNS Service and the unique production
// Deployment whose pods back it. 0 or N of either yields a DiscoveryError.
func (w *Workloads) Discover(ctx context.Context) (*StableWorkload, error) {
	services := &corev1.ServiceList{}
	if err := w.client.List(ctx, services,
		client.InNamespace(w.namespace),
		client.MatchingLabelsSelector{Selector: labels.SelectorFromSet(labels.Set{"app.kubernetes.io/name": "coredns"})}); err != nil {
		return nil, err
	}
	var stable *corev1.Service
	for i := range services.Items {
		svc := &services.Items[i]
		if svc.Labels["app.kubernetes.io/component"] == "metrics" {
			continue
		}
		if stable != nil {
			return nil, &DiscoveryError{Reason: DiscoveryMultipleServices,
				Detail: fmt.Sprintf("more than one non-metrics CoreDNS Service found in namespace %s", w.namespace)}
		}
		stable = svc
	}
	if stable == nil {
		return nil, &DiscoveryError{Reason: DiscoveryNoService,
			Detail: fmt.Sprintf("no non-metrics CoreDNS Service found in namespace %s", w.namespace)}
	}

	svcSelector := labels.SelectorFromSet(labels.Set(stable.Spec.Selector))
	deployments := &appsv1.DeploymentList{}
	if err := w.client.List(ctx, deployments, client.InNamespace(w.namespace)); err != nil {
		return nil, err
	}
	var production *appsv1.Deployment
	for i := range deployments.Items {
		depl := &deployments.Items[i]
		// The canary clones the production template labels and therefore
		// matches the stable Service selector too; it is never a backing
		// production Deployment.
		if depl.Name == CanaryDeploymentName || depl.Labels[LabelRole] == RoleCanary {
			continue
		}
		if svcSelector.Matches(labels.Set(depl.Spec.Template.Labels)) {
			if production != nil {
				return nil, &DiscoveryError{Reason: DiscoveryMultipleDeployment,
					Detail: fmt.Sprintf("multiple Deployments back Service %s", stable.Name)}
			}
			production = depl
		}
	}
	if production == nil {
		return nil, &DiscoveryError{Reason: DiscoveryNoDeployment,
			Detail: fmt.Sprintf("no Deployment backs CoreDNS Service %s", stable.Name)}
	}
	if dynamicZonesVolume(production) == nil {
		return nil, &DiscoveryError{Reason: DiscoveryMissingVolume,
			Detail: fmt.Sprintf("Deployment %s has no %q configMap volume", production.Name, DynamicZonesVolumeName)}
	}
	return &StableWorkload{Service: stable, Deployment: production, scheme: w.scheme}, nil
}

// Capture records the pre-promotion production state for inverse restoration.
func (wl *StableWorkload) Capture() *WorkloadSnapshot {
	snap := &WorkloadSnapshot{
		ServiceSelector: cloneStringMap(wl.Service.Spec.Selector),
	}
	tpl := wl.Deployment.Spec.Template
	if vol := dynamicZonesVolume(wl.Deployment); vol != nil && vol.ConfigMap != nil {
		snap.VolumeConfigMapName = vol.ConfigMap.Name
	}
	if gen, ok := tpl.Labels[LabelGeneration]; ok {
		snap.GenerationLabel = gen
		snap.HasGenerationLabel = true
	}
	if checksum, ok := tpl.Annotations[ChecksumAnnotation]; ok {
		snap.ChecksumAnnotation = checksum
		snap.HasChecksum = true
	}
	return snap
}

// BuildCanary constructs the single-replica canary Deployment and the
// ClusterIP canary Service for a candidate fingerprint. Only whitelist fields
// of the production pod template are changed.
func (wl *StableWorkload) BuildCanary(fingerprint string, owner metav1.Object) (*appsv1.Deployment, *corev1.Service, error) {
	canary := wl.Deployment.DeepCopy()
	canary.TypeMeta = metav1.TypeMeta{}
	canary.ObjectMeta = metav1.ObjectMeta{
		Name:      CanaryDeploymentName,
		Namespace: wl.Deployment.Namespace,
		Labels:    cloneStringMap(wl.Deployment.Labels),
	}
	if canary.Labels == nil {
		canary.Labels = map[string]string{}
	}
	canary.Labels[LabelManagedBy] = ManagedByValue
	canary.Labels[LabelRole] = RoleCanary
	canary.Labels[LabelGeneration] = fingerprint
	canary.Status = appsv1.DeploymentStatus{}
	canary.Spec.Replicas = int32Ptr(1)
	canary.Spec.Selector = &metav1.LabelSelector{MatchLabels: map[string]string{
		LabelGeneration: fingerprint,
		LabelRole:       RoleCanary,
	}}

	tpl := &canary.Spec.Template
	tpl.ObjectMeta = metav1.ObjectMeta{
		Labels:      cloneStringMap(wl.Deployment.Spec.Template.Labels),
		Annotations: cloneStringMap(wl.Deployment.Spec.Template.Annotations),
	}
	tpl.Labels[LabelGeneration] = fingerprint
	tpl.Labels[LabelRole] = RoleCanary
	if tpl.Annotations == nil {
		tpl.Annotations = map[string]string{}
	}
	tpl.Annotations[ChecksumAnnotation] = fingerprint

	vol := dynamicZonesVolumeFromSpec(&canary.Spec.Template.Spec)
	if vol == nil || vol.ConfigMap == nil {
		return nil, nil, &DiscoveryError{Reason: DiscoveryMissingVolume,
			Detail: "production pod template has no dynamic-zones configMap volume"}
	}
	vol.ConfigMap.Name = GenerationConfigMapName(fingerprint)

	if owner != nil {
		if err := controllerutil.SetControllerReference(owner, canary, wl.scheme); err != nil {
			return nil, nil, err
		}
	}

	canaryPorts := cloneServicePorts(wl.Service.Spec.Ports)
	var familyPolicy *corev1.IPFamilyPolicy
	if wl.Service.Spec.IPFamilyPolicy != nil {
		policy := *wl.Service.Spec.IPFamilyPolicy
		familyPolicy = &policy
	}
	svc := &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{
			Name:      CanaryServiceName,
			Namespace: wl.Service.Namespace,
			Labels: map[string]string{
				LabelManagedBy:  ManagedByValue,
				LabelRole:       RoleCanary,
				LabelGeneration: fingerprint,
			},
		},
		Spec: corev1.ServiceSpec{
			Type:           corev1.ServiceTypeClusterIP,
			Selector:       map[string]string{LabelGeneration: fingerprint, LabelRole: RoleCanary},
			Ports:          canaryPorts,
			IPFamilyPolicy: familyPolicy,
			IPFamilies:     append([]corev1.IPFamily(nil), wl.Service.Spec.IPFamilies...),
		},
	}
	if owner != nil {
		if err := controllerutil.SetControllerReference(owner, svc, wl.scheme); err != nil {
			return nil, nil, err
		}
	}
	return canary, svc, nil
}

// ApplyPromotion mutates deep copies of the production Deployment and stable
// Service to serve the candidate generation. Only the three whitelisted pod
// template fields and the Service selector generation label change.
func (wl *StableWorkload) ApplyPromotion(fingerprint string) (*appsv1.Deployment, *corev1.Service) {
	depl := wl.Deployment.DeepCopy()
	svc := wl.Service.DeepCopy()

	vol := dynamicZonesVolumeFromSpec(&depl.Spec.Template.Spec)
	if vol != nil && vol.ConfigMap != nil {
		vol.ConfigMap.Name = GenerationConfigMapName(fingerprint)
	}
	if depl.Spec.Template.Labels == nil {
		depl.Spec.Template.Labels = map[string]string{}
	}
	depl.Spec.Template.Labels[LabelGeneration] = fingerprint
	if depl.Spec.Template.Annotations == nil {
		depl.Spec.Template.Annotations = map[string]string{}
	}
	depl.Spec.Template.Annotations[ChecksumAnnotation] = fingerprint

	if svc.Spec.Selector == nil {
		svc.Spec.Selector = map[string]string{}
	}
	svc.Spec.Selector[LabelGeneration] = fingerprint
	return depl, svc
}

// ApplyRestoration mutates deep copies back to the captured snapshot. It is
// the exact inverse of ApplyPromotion for the captured fields.
func (wl *StableWorkload) ApplyRestoration(snap *WorkloadSnapshot) (*appsv1.Deployment, *corev1.Service) {
	depl := wl.Deployment.DeepCopy()
	svc := wl.Service.DeepCopy()

	vol := dynamicZonesVolumeFromSpec(&depl.Spec.Template.Spec)
	if vol != nil && vol.ConfigMap != nil {
		vol.ConfigMap.Name = snap.VolumeConfigMapName
	}
	if snap.HasGenerationLabel {
		depl.Spec.Template.Labels[LabelGeneration] = snap.GenerationLabel
	} else {
		delete(depl.Spec.Template.Labels, LabelGeneration)
	}
	if snap.HasChecksum {
		depl.Spec.Template.Annotations[ChecksumAnnotation] = snap.ChecksumAnnotation
	} else {
		delete(depl.Spec.Template.Annotations, ChecksumAnnotation)
	}
	svc.Spec.Selector = cloneStringMap(snap.ServiceSelector)
	return depl, svc
}

// RFC 6902 JSON patch operation names.
const (
	jsonOpReplace = "replace"
	jsonOpAdd     = "add"
	jsonOpRemove  = "remove"
)

// jsonPatchOp is a single RFC 6902 JSON patch operation.
type jsonPatchOp struct {
	Op    string      `json:"op"`
	Path  string      `json:"path"`
	Value interface{} `json:"value,omitempty"`
}

// PatchDeploymentPromotion applies the minimal three-field patch to the live
// production Deployment (dynamic-zones ConfigMap name, generation label,
// checksum annotation). The stable Service selector is intentionally not
// touched: it is switched later, only after the production rollout completes
// and serving capacity has been verified.
func (w *Workloads) PatchDeploymentPromotion(ctx context.Context, wl *StableWorkload, fingerprint string) error {
	ops, err := w.deploymentPromotionOps(ctx, wl, fingerprint)
	if err != nil {
		return err
	}
	return w.client.Patch(ctx, &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: wl.Deployment.Name, Namespace: w.namespace},
	}, client.RawPatch(types.JSONPatchType, mustMarshalOps(ops)))
}

// PatchServicePromotion switches the stable Service selector to the candidate
// generation. It must run only after the production rollout completes.
func (w *Workloads) PatchServicePromotion(ctx context.Context, wl *StableWorkload, fingerprint string) error {
	ops, err := w.servicePromotionOps(ctx, wl, fingerprint)
	if err != nil {
		return err
	}
	return w.client.Patch(ctx, &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{Name: wl.Service.Name, Namespace: w.namespace},
	}, client.RawPatch(types.JSONPatchType, mustMarshalOps(ops)))
}

// PatchDeploymentRestoration reverts the three production Deployment fields to
// the captured snapshot. It is used when a production rollout times out or
// when the Service switch fails after it.
func (w *Workloads) PatchDeploymentRestoration(ctx context.Context, wl *StableWorkload, snap *WorkloadSnapshot) error {
	ops, err := w.deploymentRestorationOps(ctx, wl, snap)
	if err != nil {
		return err
	}
	return w.client.Patch(ctx, &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: wl.Deployment.Name, Namespace: w.namespace},
	}, client.RawPatch(types.JSONPatchType, mustMarshalOps(ops)))
}

// PatchServiceRestoration restores the stable Service selector captured before
// promotion, removing the generation label when it was absent originally.
func (w *Workloads) PatchServiceRestoration(ctx context.Context, wl *StableWorkload, snap *WorkloadSnapshot) error {
	ops, err := w.serviceRestorationOps(ctx, wl, snap)
	if err != nil {
		return err
	}
	return w.client.Patch(ctx, &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{Name: wl.Service.Name, Namespace: w.namespace},
	}, client.RawPatch(types.JSONPatchType, mustMarshalOps(ops)))
}

func (w *Workloads) deploymentPromotionOps(ctx context.Context, wl *StableWorkload, fingerprint string) ([]jsonPatchOp, error) {
	live := &appsv1.Deployment{}
	if err := w.client.Get(ctx, types.NamespacedName{Name: wl.Deployment.Name, Namespace: wl.Deployment.Namespace}, live); err != nil {
		return nil, err
	}
	idx := dynamicZonesVolumeIndex(live)
	if idx < 0 {
		return nil, &DiscoveryError{Reason: DiscoveryMissingVolume,
			Detail: fmt.Sprintf("Deployment %s lost its %q volume", live.Name, DynamicZonesVolumeName)}
	}
	ops := []jsonPatchOp{{
		Op:    jsonOpReplace,
		Path:  fmt.Sprintf("/spec/template/spec/volumes/%d/configMap/name", idx),
		Value: GenerationConfigMapName(fingerprint),
	}}
	ops = append(ops, mapPatchOps("/spec/template/metadata/labels", live.Spec.Template.Labels,
		LabelGeneration, fingerprint)...)
	ops = append(ops, mapPatchOps("/spec/template/metadata/annotations", live.Spec.Template.Annotations,
		ChecksumAnnotation, fingerprint)...)
	return ops, nil
}

func (w *Workloads) servicePromotionOps(ctx context.Context, wl *StableWorkload, fingerprint string) ([]jsonPatchOp, error) {
	liveSvc := &corev1.Service{}
	if err := w.client.Get(ctx, types.NamespacedName{Name: wl.Service.Name, Namespace: wl.Service.Namespace}, liveSvc); err != nil {
		return nil, err
	}
	return mapPatchOps("/spec/selector", liveSvc.Spec.Selector, LabelGeneration, fingerprint), nil
}

func (w *Workloads) deploymentRestorationOps(ctx context.Context, wl *StableWorkload, snap *WorkloadSnapshot) ([]jsonPatchOp, error) {
	live := &appsv1.Deployment{}
	if err := w.client.Get(ctx, types.NamespacedName{Name: wl.Deployment.Name, Namespace: wl.Deployment.Namespace}, live); err != nil {
		return nil, err
	}
	idx := dynamicZonesVolumeIndex(live)
	if idx < 0 {
		return nil, &DiscoveryError{Reason: DiscoveryMissingVolume,
			Detail: fmt.Sprintf("Deployment %s lost its %q volume", live.Name, DynamicZonesVolumeName)}
	}
	ops := []jsonPatchOp{{
		Op:    jsonOpReplace,
		Path:  fmt.Sprintf("/spec/template/spec/volumes/%d/configMap/name", idx),
		Value: snap.VolumeConfigMapName,
	}}
	ops = append(ops, restoreMapOps("/spec/template/metadata/labels", live.Spec.Template.Labels,
		LabelGeneration, snap.GenerationLabel, snap.HasGenerationLabel)...)
	ops = append(ops, restoreMapOps("/spec/template/metadata/annotations", live.Spec.Template.Annotations,
		ChecksumAnnotation, snap.ChecksumAnnotation, snap.HasChecksum)...)
	return ops, nil
}

func (w *Workloads) serviceRestorationOps(ctx context.Context, wl *StableWorkload, snap *WorkloadSnapshot) ([]jsonPatchOp, error) {
	liveSvc := &corev1.Service{}
	if err := w.client.Get(ctx, types.NamespacedName{Name: wl.Service.Name, Namespace: wl.Service.Namespace}, liveSvc); err != nil {
		return nil, err
	}
	original, hadKey := snap.ServiceSelector[LabelGeneration]
	return restoreMapOps("/spec/selector", liveSvc.Spec.Selector, LabelGeneration, original, hadKey), nil
}

// ScaleCanary sets the canary Deployment replica count. It is used to scale a
// timed-out canary to zero while keeping it for quarantine diagnostics.
func (w *Workloads) ScaleCanary(ctx context.Context, replicas int32) error {
	ops := []jsonPatchOp{{Op: jsonOpReplace, Path: "/spec/replicas", Value: replicas}}
	return w.client.Patch(ctx, &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: CanaryDeploymentName, Namespace: w.namespace},
	}, client.RawPatch(types.JSONPatchType, mustMarshalOps(ops)))
}

// mapPatchOps adds or replaces a single key in a JSON object map.
func mapPatchOps(basePath string, m map[string]string, key, value string) []jsonPatchOp {
	escaped := escapeJSONPointer(key)
	if _, ok := m[key]; ok {
		return []jsonPatchOp{{Op: jsonOpReplace, Path: basePath + "/" + escaped, Value: value}}
	}
	return []jsonPatchOp{{Op: jsonOpAdd, Path: basePath + "/" + escaped, Value: value}}
}

// restoreMapOps restores a single map key to its captured value or removes it
// when it was absent before promotion.
func restoreMapOps(basePath string, live map[string]string, key, original string, hadKey bool) []jsonPatchOp {
	escaped := escapeJSONPointer(key)
	if hadKey {
		return []jsonPatchOp{{Op: jsonOpReplace, Path: basePath + "/" + escaped, Value: original}}
	}
	if _, ok := live[key]; ok {
		return []jsonPatchOp{{Op: jsonOpRemove, Path: basePath + "/" + escaped}}
	}
	return nil
}

func escapeJSONPointer(token string) string {
	token = strings.ReplaceAll(token, "~", "~0")
	return strings.ReplaceAll(token, "/", "~1")
}

func dynamicZonesVolumeIndex(depl *appsv1.Deployment) int {
	for i := range depl.Spec.Template.Spec.Volumes {
		if depl.Spec.Template.Spec.Volumes[i].Name == DynamicZonesVolumeName {
			return i
		}
	}
	return -1
}

func mustMarshalOps(ops []jsonPatchOp) []byte {
	raw, err := json.Marshal(ops)
	if err != nil {
		panic(err)
	}
	return raw
}

// EnsureCanary creates or replaces the canary Deployment/Service for the
// candidate. An existing canary for the same fingerprint is left untouched.
func (w *Workloads) EnsureCanary(ctx context.Context, wl *StableWorkload, desired Desired) error {
	anchor, err := w.store.GetAnchor(ctx)
	if err != nil {
		return err
	}
	canary, svc, err := wl.BuildCanary(desired.Fingerprint, anchor)
	if err != nil {
		return err
	}
	if err := w.upsertDeployment(ctx, canary); err != nil {
		return err
	}
	return w.upsertService(ctx, svc)
}

// RemoveCanary deletes canary resources; NotFound is success. Existence is
// checked first so steady-state reconciliation issues no write attempts when
// no canary exists.
func (w *Workloads) RemoveCanary(ctx context.Context) error {
	canary := &appsv1.Deployment{}
	if err := w.client.Get(ctx, types.NamespacedName{Name: CanaryDeploymentName, Namespace: w.namespace}, canary); err == nil {
		if err := w.client.Delete(ctx, canary); err != nil && !apierrors.IsNotFound(err) {
			return err
		}
	} else if !apierrors.IsNotFound(err) {
		return err
	}
	svc := &corev1.Service{}
	if err := w.client.Get(ctx, types.NamespacedName{Name: CanaryServiceName, Namespace: w.namespace}, svc); err == nil {
		if err := w.client.Delete(ctx, svc); err != nil && !apierrors.IsNotFound(err) {
			return err
		}
	} else if !apierrors.IsNotFound(err) {
		return err
	}
	return nil
}

func (w *Workloads) upsertDeployment(ctx context.Context, desired *appsv1.Deployment) error {
	current := &appsv1.Deployment{}
	err := w.client.Get(ctx, types.NamespacedName{Name: desired.Name, Namespace: desired.Namespace}, current)
	if apierrors.IsNotFound(err) {
		return w.client.Create(ctx, desired)
	}
	if err != nil {
		return err
	}
	if current.Spec.Template.Labels[LabelGeneration] == desired.Spec.Template.Labels[LabelGeneration] {
		return nil
	}
	updated := current.DeepCopy()
	updated.Spec = desired.Spec
	if updated.Labels == nil {
		updated.Labels = map[string]string{}
	}
	for k, v := range desired.Labels {
		updated.Labels[k] = v
	}
	if updated.Annotations == nil {
		updated.Annotations = map[string]string{}
	}
	for k, v := range desired.Annotations {
		updated.Annotations[k] = v
	}
	updated.OwnerReferences = desired.OwnerReferences
	return w.client.Update(ctx, updated)
}

func (w *Workloads) upsertService(ctx context.Context, desired *corev1.Service) error {
	current := &corev1.Service{}
	err := w.client.Get(ctx, types.NamespacedName{Name: desired.Name, Namespace: desired.Namespace}, current)
	if apierrors.IsNotFound(err) {
		return w.client.Create(ctx, desired)
	}
	if err != nil {
		return err
	}
	if current.Spec.Selector[LabelGeneration] == desired.Spec.Selector[LabelGeneration] {
		return nil
	}
	updated := current.DeepCopy()
	updated.Spec.Selector = desired.Spec.Selector
	updated.Spec.Ports = desired.Spec.Ports
	updated.Spec.IPFamilies = desired.Spec.IPFamilies
	updated.Spec.IPFamilyPolicy = desired.Spec.IPFamilyPolicy
	updated.Labels = desired.Labels
	updated.OwnerReferences = desired.OwnerReferences
	return w.client.Update(ctx, updated)
}

// dynamicZonesVolume returns the dynamic-zones volume of a Deployment.
func dynamicZonesVolume(depl *appsv1.Deployment) *corev1.Volume {
	return dynamicZonesVolumeFromSpec(&depl.Spec.Template.Spec)
}

func dynamicZonesVolumeFromSpec(spec *corev1.PodSpec) *corev1.Volume {
	for i := range spec.Volumes {
		if spec.Volumes[i].Name == DynamicZonesVolumeName {
			return &spec.Volumes[i]
		}
	}
	return nil
}

func cloneServicePorts(in []corev1.ServicePort) []corev1.ServicePort {
	out := make([]corev1.ServicePort, 0, len(in))
	for _, p := range in {
		cloned := p
		cloned.NodePort = 0
		out = append(out, cloned)
	}
	return out
}

func cloneStringMap(in map[string]string) map[string]string {
	if in == nil {
		return nil
	}
	out := make(map[string]string, len(in))
	for k, v := range in {
		out[k] = v
	}
	return out
}

func int32Ptr(v int32) *int32 {
	return &v
}
