// Decision is the reconciler-facing outcome of a generation reconciliation.
type Decision string

const (
	// DecisionActive means the desired generation is active; external
	// delegation publication is allowed.
	DecisionActive Decision = "Active"
	// DecisionProgressing means a candidate is advancing; the caller must
	// requeue after RequeueAfter and must not publish anything externally.
	DecisionProgressing Decision = "Progressing"
	// DecisionFailed means a candidate failed and was isolated; the caller
	// must apply its recovery requeue semantics and record an Event.
	DecisionFailed Decision = "Failed"
)

// GenerationDecision carries the decision and its requeue timing.
type GenerationDecision struct {
	Decision     Decision
	RequeueAfter time.Duration
	Reason       string
}

// GlueNSNameFunc returns this cluster's authoritative glue NS name for a zone.
type GlueNSNameFunc func(zone v1beta1io.ZoneDelegation) string

// ExposedIPsFunc returns the cluster's currently exposed IP addresses
// (IPv4/IPv6 mixed; the coordinator splits them by family).
type ExposedIPsFunc func(ctx context.Context) ([]string, error)

// Settings holds rollout configuration derived from operator config.
type Settings struct {
	Namespace                string
	Enabled                  bool
	CanaryReadyTimeout       time.Duration
	ProductionRolloutTimeout time.Duration
	QuarantineGenerations    int
}

// Coordinator is the level-triggered generation state machine. It is driven
// only by the ZoneDelegation reconciler and drives every cluster mutation
// through Store/Workloads so the last-known-good generation can never be
// overwritten.
type Coordinator struct {
	client     client.Client
	scheme     *runtime.Scheme
	store      *Store
	clock      Clock
	settings   Settings
	glueNSName GlueNSNameFunc
	exposedIPs ExposedIPsFunc
	querier    DNSQuerier
	recorder   record.EventRecorder
	log        *zerolog.Logger
}

// NewCoordinator wires the coordinator with narrow injected boundaries.
func NewCoordinator(
	c client.Client,
	scheme *runtime.Scheme,
	settings Settings,
	glueNSName GlueNSNameFunc,
	exposedIPs ExposedIPsFunc,
	querier DNSQuerier,
	recorder record.EventRecorder,
	log *zerolog.Logger,
) *Coordinator {
	if querier == nil {
		querier = NewMiekgQuerier()
	}
	return &Coordinator{
		client:     c,
		scheme:     scheme,
		store:      NewStore(c, settings.Namespace),
		clock:      SystemClock{},
		settings:   settings,
		glueNSName: glueNSName,
		exposedIPs: exposedIPs,
		querier:    querier,
		recorder:   recorder,
		log:        log,
	}
}

// withClock overrides the clock; tests use it to drive time deterministically.
func (c *Coordinator) withClock(clock Clock) *Coordinator {
	c.clock = clock
	return c
}

func (c *Coordinator) workloads() *Workloads {
	return NewWorkloads(c.client, c.settings.Namespace, c.scheme, c.store, c.log)
}

func (c *Coordinator) rollouts() *Rollouts {
	return NewRollouts(c.client, c.settings.Namespace, c.clock,
		c.settings.CanaryReadyTimeout, c.settings.ProductionRolloutTimeout)
}

func activeDecision() GenerationDecision {
	return GenerationDecision{Decision: DecisionActive}
}

func progressingDecision(reason string) GenerationDecision {
	return GenerationDecision{Decision: DecisionProgressing, RequeueAfter: RequeueInterval, Reason: reason}
}

func failedDecision(reason string) GenerationDecision {
	return GenerationDecision{Decision: DecisionFailed, Reason: reason}
}

func (c *Coordinator) event(kind, reason, message string) {
	if c.recorder != nil {
		c.recorder.Event(&corev1.ConfigMap{ObjectMeta: metav1.ObjectMeta{Name: AnchorConfigMapName, Namespace: c.settings.Namespace}},
			kind, reason, message)
	}
}

// EnsureGeneration reconciles the desired configuration to an active
// generation. Repeated calls while nothing changes perform no writes.
func (c *Coordinator) EnsureGeneration(ctx context.Context, zones *v1beta1io.ZoneDelegationList) (GenerationDecision, error) {
	desired := Normalize(zones)
	if err := Validate(desired.Data); err != nil {
		diag := FailureDiagnostic{
			Hash: desired.Fingerprint, Phase: PhaseActive, Reason: ReasonValidationFailed,
			Detail: err.Error(), Timestamp: c.clock.Now(),
		}
		if rerr := c.store.RecordFailure(ctx, diag); rerr != nil {
			return GenerationDecision{}, rerr
		}
		return failedDecision(err.Error()), nil
	}

	if !c.settings.Enabled {
		if err := c.store.WriteAnchorDataLegacy(ctx, desired.Data); err != nil {
			return GenerationDecision{}, err
		}
		return activeDecision(), nil
	}

	state, err := c.store.AdoptIfNeeded(ctx, desired)
	if err != nil {
		return GenerationDecision{}, err
	}

	wl, err := c.workloads().Discover(ctx)
	if err != nil {
		if !IsDiscoveryError(err) {
			return GenerationDecision{}, err
		}
		// FR-16: topology discovery failure falls back to the legacy direct
		// anchor write so configuration keeps converging.
		if lerr := c.store.WriteAnchorDataLegacy(ctx, desired.Data); lerr != nil {
			return GenerationDecision{}, lerr
		}
		c.warn().Err(err).Msg("CoreDNS workload discovery failed; falling back to legacy anchor write")
		c.event(corev1.EventTypeWarning, "CoreDNSRolloutLegacyFallback", err.Error())
		return activeDecision(), nil
	}

	anchor, err := c.store.GetAnchor(ctx)
	if err != nil {
		return GenerationDecision{}, err
	}
	state = State(anchor)

	// No-op short circuit: the active generation already serves the desired
	// content and nothing is in flight.
	if state.Active == desired.Fingerprint && state.Candidate == "" {
		if err := c.workloads().RemoveCanary(ctx); err != nil {
			return GenerationDecision{}, err
		}
		if err := c.garbageCollect(ctx, wl, state); err != nil {
			return GenerationDecision{}, err
		}
		return activeDecision(), nil
	}

	// A candidate for exactly the desired content that was quarantined is a
	// terminal failure for this content: stay Failed until content changes.
	if state.Phase == PhaseQuarantined && state.Candidate == desired.Fingerprint {
		detail := "candidate generation quarantined"
		if state.LastFailure != nil {
			detail = fmt.Sprintf("candidate quarantined (%s): %s", state.LastFailure.Reason, state.LastFailure.Detail)
		}
		return failedDecision(detail), nil
	}

	// FR-13: a candidate for different content must never be promoted. Tear it
	// down (restoring a crashed promotion first) and converge on the newest
	// fingerprint only.
	if state.Candidate != "" && state.Candidate != desired.Fingerprint {
		if err := c.supersede(ctx, wl, state); err != nil {
			return GenerationDecision{}, err
		}
		anchor, err = c.store.GetAnchor(ctx)
		if err != nil {
			return GenerationDecision{}, err
		}
		state = State(anchor)
	}

	if state.Candidate == "" {
		if _, err := c.store.EnsureGenerationCM(ctx, desired); err != nil {
			diag := FailureDiagnostic{
				Hash: desired.Fingerprint, Phase: PhaseCandidateRolling,
				Reason: ReasonCandidateWriteFailed, Detail: err.Error(), Timestamp: c.clock.Now(),
			}
			if derr := c.store.DiscardCandidate(ctx, diag); derr != nil {
				return GenerationDecision{}, derr
			}
			c.event(corev1.EventTypeWarning, ReasonCandidateWriteFailed, err.Error())
			return failedDecision("candidate ConfigMap write failed: " + err.Error()), nil
		}
		if err := c.store.SetCandidate(ctx, desired.Fingerprint, PhaseCandidateRolling, c.clock.Now()); err != nil {
			return GenerationDecision{}, err
		}
		state.Candidate = desired.Fingerprint
		state.Phase = PhaseCandidateRolling
		state.CandidateSince = c.clock.Now()
		c.info().Str("candidate", desired.Fingerprint).Msg("new CoreDNS generation candidate established")
	}

	switch state.Phase {
	case PhaseCandidateRolling:
		return c.rollCanary(ctx, wl, desired, state, zones)
	case PhaseCandidateProbing:
		return c.probeCandidate(ctx, wl, desired, state, zones)
	case PhasePromoting:
		return c.promote(ctx, wl, desired, state)
	default:
		return progressingDecision("waiting for candidate rollout"), nil
	}
}

// rollCanary ensures the canary workload exists and waits for readiness.
func (c *Coordinator) rollCanary(
	ctx context.Context, wl *StableWorkload, desired Desired,
	state *GenerationState, zones *v1beta1io.ZoneDelegationList,
) (GenerationDecision, error) {
	if err := c.workloads().EnsureCanary(ctx, wl, desired); err != nil {
		return GenerationDecision{}, err
	}
	res, err := c.rollouts().WaitCanary(ctx, state.CandidateSince)
	if err != nil {
		return GenerationDecision{}, err
	}
	switch res {
	case WaitReady:
		if err := c.store.SetPhase(ctx, PhaseCandidateProbing, c.clock.Now()); err != nil {
			return GenerationDecision{}, err
		}
		state.Phase = PhaseCandidateProbing
		return c.probeCandidate(ctx, wl, desired, state, zones)
	case WaitTimedOut:
		return c.quarantine(ctx, desired.Fingerprint, FailureDiagnostic{
			Phase: PhaseCandidateRolling, Reason: ReasonCanaryNotReady,
			Detail: fmt.Sprintf("canary did not become ready within %s", c.settings.CanaryReadyTimeout),
		})
	default:
		return progressingDecision("waiting for canary readiness"), nil
	}
}

// probeCandidate runs authoritative NS/A/AAAA verification through the canary Service.
func (c *Coordinator) probeCandidate(
	ctx context.Context, wl *StableWorkload, desired Desired,
	state *GenerationState, zones *v1beta1io.ZoneDelegationList,
) (GenerationDecision, error) {
	targets, err := c.probeTargets(ctx, zones)
	if err != nil {
		return GenerationDecision{}, err
	}
	server := CanaryServerAddress(c.settings.Namespace, wl.Service.Spec.Ports)
	report := NewProber(c.querier, server).Probe(targets)
	if !report.Pass {
		failed := firstFailedProbe(report.Results)
		zone, summary := failed.Zone, failed.Summary
		return c.quarantine(ctx, desired.Fingerprint, FailureDiagnostic{
			Phase: PhaseCandidateProbing, Reason: ReasonProbeFailed, Zone: zone, Detail: summary,
		})
	}
	snap := wl.Capture()
	now := c.clock.Now()
	if err := c.workloads().PatchDeploymentPromotion(ctx, wl, desired.Fingerprint); err != nil {
		return GenerationDecision{}, err
	}
	if err := c.store.EnterPromotion(ctx, *snap, now); err != nil {
		return GenerationDecision{}, err
	}
	state.Phase = PhasePromoting
	state.PromotionSince = now
	state.PromotionSnapshot = snap
	c.info().Str("candidate", desired.Fingerprint).Msg("candidate verified; promoting production Deployment")
	return c.promote(ctx, wl, desired, state)
}

// promote waits for the production rollout, verifies serving capacity,
// switches the stable Service selector and finally activates the generation.
func (c *Coordinator) promote(ctx context.Context, wl *StableWorkload, desired Desired, state *GenerationState) (GenerationDecision, error) {
	snap := state.PromotionSnapshot
	if snap == nil {
		// Defensive: Promoting without a persisted snapshot cannot be safely
		// rolled back; re-enter promotion from a fresh capture.
		fresh := wl.Capture()
		snap = fresh
	}

	res, err := c.rollouts().WaitProduction(ctx, wl.Deployment.Name, state.PromotionSince)
	if err != nil {
		return GenerationDecision{}, err
	}
	switch res {
	case WaitInProgress:
		return progressingDecision("waiting for production rollout"), nil
	case WaitTimedOut:
		return c.rollbackPromotion(ctx, wl, desired.Fingerprint, snap, FailureDiagnostic{
			Phase: PhasePromoting, Reason: ReasonRolloutTimeout,
			Detail: fmt.Sprintf("production rollout did not complete within %s", c.settings.ProductionRolloutTimeout),
		})
	}

	// Canary is no longer needed: production pods now serve the candidate
	// content. Removing it before the selector switch guarantees the stable
	// Service can only select production pods.
	if err := c.workloads().RemoveCanary(ctx); err != nil {
		return GenerationDecision{}, err
	}

	before, err := c.servingAddresses(ctx, wl.Service.Spec.Selector)
	if err != nil {
		return GenerationDecision{}, err
	}
	if before.total() == 0 {
		// Cache lag or transient absence of ready pods; retry shortly.
		return progressingDecision("no ready endpoints before selector switch"), nil
	}
	if err := c.workloads().PatchServicePromotion(ctx, wl, desired.Fingerprint); err != nil {
		return GenerationDecision{}, err
	}
	newSelector := map[string]string(labels.Merge(labels.Set(wl.Service.Spec.Selector),
		labels.Set{LabelGeneration: desired.Fingerprint}))
	after, err := c.servingAddresses(ctx, newSelector)
	if err != nil {
		return GenerationDecision{}, err
	}
	if !after.covers(before) {
		if rerr := c.workloads().PatchServiceRestoration(ctx, wl, snap); rerr != nil {
			return GenerationDecision{}, rerr
		}
		return c.rollbackPromotion(ctx, wl, desired.Fingerprint, snap, FailureDiagnostic{
			Phase: PhasePromoting, Reason: ReasonSwitchFailed,
			Detail: fmt.Sprintf("endpoint set shrank after selector switch: before=%s after=%s", before, after),
		})
	}

	if err := c.store.PromoteActive(ctx, desired); err != nil {
		if rerr := c.workloads().PatchServiceRestoration(ctx, wl, snap); rerr != nil {
			return GenerationDecision{}, rerr
		}
		if rerr := c.workloads().PatchDeploymentRestoration(ctx, wl, snap); rerr != nil {
			return GenerationDecision{}, rerr
		}
		return c.rollbackPromotion(ctx, wl, desired.Fingerprint, snap, FailureDiagnostic{
			Phase: PhasePromoting, Reason: ReasonSwitchFailed, Detail: "anchor activation failed: " + err.Error(),
		})
	}
	if err := c.store.ClearPromotion(ctx); err != nil {
		return GenerationDecision{}, err
	}

	refreshed, err := c.store.GetAnchor(ctx)
	if err != nil {
		return GenerationDecision{}, err
	}
	if err := c.garbageCollect(ctx, wl, State(refreshed)); err != nil {
		return GenerationDecision{}, err
	}
	c.info().Str("active", desired.Fingerprint).Msg("CoreDNS generation promoted and active")
	c.event(corev1.EventTypeNormal, "CoreDNSGenerationActive",
		fmt.Sprintf("generation %s is now active", desired.Fingerprint))
	return activeDecision(), nil
}

// rollbackPromotion restores the three deployment fields (and selector when
// needed by the caller path), quarantines the candidate and reports Failed.
func (c *Coordinator) rollbackPromotion(
	ctx context.Context, wl *StableWorkload, fingerprint string,
	snap *WorkloadSnapshot, diag FailureDiagnostic,
) (GenerationDecision, error) {
	diag.Hash = fingerprint
	diag.Timestamp = c.clock.Now()
	if err := c.workloads().PatchDeploymentRestoration(ctx, wl, snap); err != nil && !apierrors.IsNotFound(err) {
		return GenerationDecision{}, err
	}
	return c.quarantine(ctx, fingerprint, diag)
}

// quarantine isolates a failed candidate: the canary is scaled to zero, the
// generation ConfigMap labeled with the reason and a diagnostic is recorded.
// The active generation and its data remain byte-identical.
func (c *Coordinator) quarantine(ctx context.Context, fingerprint string, diag FailureDiagnostic) (GenerationDecision, error) {
	diag.Hash = fingerprint
	if diag.Timestamp.IsZero() {
		diag.Timestamp = c.clock.Now()
	}
	if err := c.workloads().ScaleCanary(ctx, 0); err != nil && !apierrors.IsNotFound(err) {
		return GenerationDecision{}, err
	}
	if err := c.store.QuarantineCandidate(ctx, diag); err != nil {
		return GenerationDecision{}, err
	}
	if err := c.store.ClearPromotion(ctx); err != nil {
		return GenerationDecision{}, err
	}
	c.warn().
		Str("candidate", fingerprint).
		Str("reason", diag.Reason).
		Str("zone", diag.Zone).
		Msg("CoreDNS candidate generation quarantined")
	c.event(corev1.EventTypeWarning, "CoreDNSCandidateQuarantined",
		fmt.Sprintf("%s: %s", diag.Reason, diag.Detail))
	return failedDecision(fmt.Sprintf("%s: %s", diag.Reason, diag.Detail)), nil
}

// supersede tears down a candidate for stale content, restoring a crashed
// promotion from its persisted snapshot when present. Only the newest desired
// fingerprint may be promoted afterwards.
func (c *Coordinator) supersede(ctx context.Context, wl *StableWorkload, state *GenerationState) error {
	c.info().
		Str("oldCandidate", state.Candidate).
		Msg("superseding stale CoreDNS candidate")
	if state.Phase == PhasePromoting && state.PromotionSnapshot != nil {
		if err := c.workloads().PatchServiceRestoration(ctx, wl, state.PromotionSnapshot); err != nil && !apierrors.IsNotFound(err) {
			return err
		}
		if err := c.workloads().PatchDeploymentRestoration(ctx, wl, state.PromotionSnapshot); err != nil && !apierrors.IsNotFound(err) {
			return err
		}
	}
	if err := c.workloads().RemoveCanary(ctx); err != nil {
		return err
	}
	if state.Phase != PhaseQuarantined && state.Candidate != state.Active {
		if err := c.store.DeleteGenerationCM(ctx, GenerationConfigMapName(state.Candidate), state.Active); err != nil {
			return err
		}
	}
	return c.store.ClearCandidate(ctx)
}

// probeTargets builds verification targets for every non-deleting zone in the
// reconciled set supplied by the ZoneDelegation reconciler.
func (c *Coordinator) probeTargets(ctx context.Context, zoneDelegations *v1beta1io.ZoneDelegationList) ([]ZoneProbeTarget, error) {
	ips, err := c.exposedIPs(ctx)
	if err != nil {
		return nil, err
	}
	v4, v6 := splitIPFamilies(ips)
	targets := make([]ZoneProbeTarget, 0, len(zoneDelegations.Items))
	for _, z := range zoneDelegations.Items {
		if z.IsInDeletion() {
			continue
		}
		targets = append(targets, ZoneProbeTarget{
			Zone:       z.Spec.LoadBalancedZone,
			GlueNSName: c.glueNSName(z),
			IPv4:       append([]string(nil), v4...),
			IPv6:       append([]string(nil), v6...),
		})
	}
	sort.Slice(targets, func(i, j int) bool { return targets[i].Zone < targets[j].Zone })
	return targets, nil
}

// addressSets groups ready endpoint IP counts by IP family.
type addressSets struct {
	v4 []string
	v6 []string
}

func (a addressSets) total() int { return len(a.v4) + len(a.v6) }

func (a addressSets) String() string {
	return fmt.Sprintf("v4=%v v6=%v", a.v4, a.v6)
}

// covers reports that every family keeps at least as many distinct ready
// addresses after the switch as before it.
func (a addressSets) covers(before addressSets) bool {
	return len(set(a.v4)) >= len(set(before.v4)) && len(set(a.v6)) >= len(set(before.v6))
}

// servingAddresses lists ready Pod IPs matching the given Service selector,
// split by family. Pods are the RBAC-available projection of Service
// Endpoints (ready Pods are exactly what populate EndpointSubsets).
func (c *Coordinator) servingAddresses(ctx context.Context, selector map[string]string) (addressSets, error) {
	pods := &corev1.PodList{}
	if err := c.client.List(ctx, pods,
		client.InNamespace(c.settings.Namespace),
		client.MatchingLabelsSelector{Selector: labels.SelectorFromSet(labels.Set(selector))}); err != nil {
		return addressSets{}, err
	}
	var out addressSets
	for i := range pods.Items {
		pod := &pods.Items[i]
		if !podReady(pod) {
			continue
		}
		for _, ip := range pod.Status.PodIPs {
			parsed := net.ParseIP(ip.IP)
			if parsed == nil {
				continue
			}
			if parsed.To4() != nil {
				out.v4 = append(out.v4, ip.IP)
			} else {
				out.v6 = append(out.v6, ip.IP)
			}
		}
	}
	out.v4 = sorted(set(out.v4))
	out.v6 = sorted(set(out.v6))
	return out, nil
}

// garbageCollect deletes unreferenced generation ConfigMaps. Active,
// referenced and the most recent N quarantined generations are retained;
// ConfigMaps without controller labels are never touched.
func (c *Coordinator) garbageCollect(ctx context.Context, wl *StableWorkload, state *GenerationState) error {
	list, err := c.store.ListGenerationCMs(ctx)
	if err != nil {
		return err
	}
	referenced, err := c.referencedGenerations(ctx, wl, state)
	if err != nil {
		return err
	}

	quarantined := make([]corev1.ConfigMap, 0)
	for i := range list.Items {
		if _, isQuarantined := list.Items[i].Labels[LabelQuarantine]; isQuarantined {
			quarantined = append(quarantined, list.Items[i])
		}
	}
	sort.Slice(quarantined, func(i, j int) bool {
		return quarantined[i].Annotations[AnnQuarantinedAt] > quarantined[j].Annotations[AnnQuarantinedAt]
	})
	retainQuarantined := make(map[string]bool)
	for i := 0; i < c.settings.QuarantineGenerations && i < len(quarantined); i++ {
		retainQuarantined[quarantined[i].Name] = true
	}

	for i := range list.Items {
		cm := &list.Items[i]
		fingerprint := cm.Labels[LabelGeneration]
		if fingerprint != "" && referenced[fingerprint] {
			continue
		}
		if _, isQuarantined := cm.Labels[LabelQuarantine]; isQuarantined && retainQuarantined[cm.Name] {
			continue
		}
		if err := c.store.DeleteGenerationCM(ctx, cm.Name, state.Active); err != nil {
			// GC is best effort: log and keep converging.
			c.warn().Err(err).Str("configmap", cm.Name).Msg("generation ConfigMap garbage collection failed")
		} else {
			c.info().Str("configmap", cm.Name).Msg("garbage collected unreferenced generation ConfigMap")
		}
	}
	return nil
}

// referencedGenerations computes fingerprints still referenced by the
// production Deployment, the stable Service selector, the canary workload or
// the anchor state. Such generations keep serving and must not be deleted.
func (c *Coordinator) referencedGenerations(ctx context.Context, wl *StableWorkload, state *GenerationState) (map[string]bool, error) {
	referenced := map[string]bool{}
	if state.Active != "" {
		referenced[state.Active] = true
	}
	if state.Candidate != "" {
		referenced[state.Candidate] = true
	}
	if fp := wl.Deployment.Spec.Template.Labels[LabelGeneration]; fp != "" {
		referenced[fp] = true
	}
	if vol := dynamicZonesVolume(wl.Deployment); vol != nil && vol.ConfigMap != nil {
		if fp := strings.TrimPrefix(vol.ConfigMap.Name, GenerationConfigMapPrefix); fp != vol.ConfigMap.Name {
			referenced[fp] = true
		}
	}
	if fp := wl.Service.Spec.Selector[LabelGeneration]; fp != "" {
		referenced[fp] = true
	}
	canary := &appsv1.Deployment{}
	if err := c.client.Get(ctx, client.ObjectKey{Namespace: c.settings.Namespace, Name: CanaryDeploymentName}, canary); err != nil {
		if !apierrors.IsNotFound(err) {
			return nil, err
		}
	} else if fp := canary.Spec.Template.Labels[LabelGeneration]; fp != "" {
		referenced[fp] = true
	}
	return referenced, nil
}

