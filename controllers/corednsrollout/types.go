// Phase is the rollout phase of a candidate generation.
type Phase string

const (
	// PhaseActive means no candidate is in flight and the active generation serves traffic.
	PhaseActive Phase = "Active"
	// PhaseCandidateRolling means the canary workload is being rolled out and waiting for readiness.
	PhaseCandidateRolling Phase = "CandidateRolling"
	// PhaseCandidateProbing means the canary is ready and undergoing authoritative DNS probes.
	PhaseCandidateProbing Phase = "CandidateProbing"
	// PhasePromoting means the production Deployment/Service is being switched to the candidate.
	PhasePromoting Phase = "Promoting"
	// PhaseQuarantined means the candidate failed validation/readiness/probing and is isolated.
	PhaseQuarantined Phase = "Quarantined"
)

// Failure reason categories used in diagnostics and quarantine labels.
const (
	ReasonCandidateWriteFailed = "ConfigMapWriteFailed"
	ReasonCanaryNotReady       = "CanaryNotReady"
	ReasonRolloutTimeout       = "RolloutTimeout"
	ReasonProbeFailed          = "ProbeFailed"
	ReasonValidationFailed     = "ValidationFailed"
	ReasonSwitchFailed         = "ServiceSwitchFailed"
)

// GenerationState is the rollout state reconstructed from anchor annotations.
type GenerationState struct {
	// Active is the fingerprint of the generation serving production traffic.
	Active string `json:"active"`
	// Candidate is the fingerprint of the in-flight (or last quarantined) candidate.
	Candidate string `json:"candidate,omitempty"`
	// Phase is the current candidate phase.
	Phase Phase `json:"phase"`
	// CandidateSince is when the candidate canary rollout started.
	CandidateSince time.Time `json:"-"`
	// PromotionSince is when the production promotion rollout started.
	PromotionSince time.Time `json:"-"`
	// PromotionSnapshot is the captured pre-promotion production state used
	// to roll back a crashed or timed-out promotion.
	PromotionSnapshot *WorkloadSnapshot `json:"-"`
	// LastFailure is the most recent structured failure diagnostic.
	LastFailure *FailureDiagnostic `json:"lastFailure,omitempty"`
}

// FailureDiagnostic describes a failed rollout attempt without mutating any
// generation data.
type FailureDiagnostic struct {
	// Hash is the candidate fingerprint the failure refers to.
	Hash string `json:"hash"`
	// Phase is the phase in which the failure occurred.
	Phase Phase `json:"phase"`
	// Reason is one of the Reason* categories.
	Reason string `json:"reason"`
	// Zone optionally names the affected zone (empty for global failures).
	Zone string `json:"zone,omitempty"`
	// Detail carries a human readable summary, including DNS probe results.
	Detail string `json:"detail,omitempty"`
	// Timestamp records when the failure was observed.
	Timestamp time.Time `json:"timestamp"`
}

// Desired is the normalized, fingerprinted desired CoreDNS configuration.
type Desired struct {
	// Data is the deterministic ConfigMap data (zone.conf -> Corefile snippet).
	Data map[string]string `json:"data"`
	// Fingerprint is the truncated SHA-256 of the canonical data encoding.
	Fingerprint string `json:"fingerprint"`
}

// GenerationConfigMapName returns the immutable generation ConfigMap name for a fingerprint.
func GenerationConfigMapName(fingerprint string) string {
	return GenerationConfigMapPrefix + fingerprint
}

