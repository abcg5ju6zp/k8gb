// managedPluginLine is the only plugin line allowed inside a managed zone
// server block.
const managedPluginLine = "import k8gbplugins"

var (
	// headerRe matches a CoreDNS server block header: "<zone>:<port> {".
	headerRe = regexp.MustCompile(`^(\S+):(\d+)\s*\{\s*(?:#.*)?$`)
	// zoneLabelRe matches an RFC 1123 DNS label (lowercase letters, digits, dash).
	zoneLabelRe = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$`)
)

// ValidationError describes why a normalized zone file is invalid.
type ValidationError struct {
	// File is the ConfigMap data key (zone.conf).
	File string
	// Zone is the zone token extracted from (or implied by) the file.
	Zone string
	// Reason is the concrete validation failure.
	Reason string
}

func (e *ValidationError) Error() string {
	if e.Zone != "" {
		return fmt.Sprintf("invalid CoreDNS zone config %q (zone %s): %s", e.File, e.Zone, e.Reason)
	}
	return fmt.Sprintf("invalid CoreDNS zone config %q: %s", e.File, e.Reason)
}

// Validate statically validates normalized ConfigMap data: every zone file
// must consist of exactly one well-formed server block for a valid unique zone
// on a valid port and must contain only managed plugin lines. It is a pure
// function and never reaches out to the cluster.
func Validate(data map[string]string) error {
	seenZones := make(map[string]string)
	keys := make([]string, 0, len(data))
	for k := range data {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, key := range keys {
		content := data[key]
		zone, err := validateZoneFile(key, content)
		if err != nil {
			return err
		}
		if previous, dup := seenZones[zone]; dup {
			return &ValidationError{File: key, Zone: zone,
				Reason: fmt.Sprintf("duplicate zone server block, already defined in %q", previous)}
		}
		seenZones[zone] = key
	}
	return nil
}

func validateZoneFile(file, content string) (string, *ValidationError) {
	zone := ""
	openBraces := 0
	closeSeen := false
	headerSeen := false
	sawManagedPlugin := false

	for lineNo, raw := range strings.Split(content, "\n") {
		line := strings.TrimSpace(stripComment(raw))
		if line == "" {
			continue
		}
		if closeSeen {
			return zone, ve(file, zone, lineNo+1, "content after server block closing brace")
		}
		switch {
		case strings.HasPrefix(line, "}"):
			if line != "}" {
				return zone, ve(file, zone, lineNo+1, "closing brace must be the only token on its line")
			}
			if openBraces == 0 {
				return zone, ve(file, zone, lineNo+1, "unmatched closing brace")
			}
			openBraces--
			closeSeen = true
		case openBraces == 0:
			match := headerRe.FindStringSubmatch(line)
			if match == nil {
				return zone, ve(file, zone, lineNo+1,
					"expected server block header of the form \"<zone>:<port> {\"")
			}
			headerSeen = true
			zone = strings.TrimSuffix(match[1], ".")
			if err := validateZoneToken(zone); err != nil {
				return zone, ve(file, zone, lineNo+1, err.Error())
			}
			if expected := configName(zone); file != expected {
				return zone, ve(file, zone, lineNo+1,
					fmt.Sprintf("file name does not match zone token, expected %q", expected))
			}
			port, err := strconv.Atoi(match[2])
			if err != nil || port < 1 || port > 65535 {
				return zone, ve(file, zone, lineNo+1,
					fmt.Sprintf("invalid port %q, must be between 1 and 65535", match[2]))
			}
			openBraces++
		default:
			if strings.ContainsAny(line, "{}") {
				return zone, ve(file, zone, lineNo+1, "nested blocks are not allowed in managed zone config")
			}
			if line != managedPluginLine {
				return zone, ve(file, zone, lineNo+1,
					fmt.Sprintf("only the %q plugin line is allowed, got %q", managedPluginLine, line))
			}
			sawManagedPlugin = true
		}
	}

	if !headerSeen || zone == "" {
		return zone, ve(file, zone, 0, "empty or missing server block header")
	}
	if openBraces != 0 || !closeSeen {
		return zone, ve(file, zone, 0, "unbalanced braces, server block is not closed")
	}
	if !sawManagedPlugin {
		return zone, ve(file, zone, 0, fmt.Sprintf("server block must contain %q", managedPluginLine))
	}
	return zone, nil
}

func validateZoneToken(zone string) error {
	if zone == "" {
		return fmt.Errorf("empty zone token")
	}
	if err := utils.ValidateRFC1035(zone); err != nil {
		return err
	}
	if _, ok := dns.IsDomainName(zone); !ok {
		return fmt.Errorf("%q is not a valid DNS domain name", zone)
	}
	for _, label := range strings.Split(zone, ".") {
		if !zoneLabelRe.MatchString(label) {
			return fmt.Errorf("invalid zone label %q in %q", label, zone)
		}
	}
	return nil
}

// stripComment removes an inline Corefile comment (everything from an unquoted #).
// Managed zone content never contains quoted '#', so simple trimming is sufficient.
func stripComment(line string) string {
	if idx := strings.IndexByte(line, '#'); idx >= 0 {
		return line[:idx]
	}
	return line
}

func ve(file, zone string, line int, reason string) *ValidationError {
	if line > 0 {
		reason = fmt.Sprintf("line %d: %s", line, reason)
	}
	return &ValidationError{File: file, Zone: zone, Reason: reason}
}
