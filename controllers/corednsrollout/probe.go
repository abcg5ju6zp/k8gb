// probeTimeout bounds a single DNS exchange of the production querier.
const probeTimeout = 2 * time.Second

// DNSQuerier is the narrow boundary for authoritative DNS verification.
// The production implementation exchanges over UDP against the canary
// Service ClusterIP DNS name; tests provide programmable fakes.
type DNSQuerier interface {
	Exchange(msg *dns.Msg, server string) (*dns.Msg, error)
}

// MiekgQuerier is the production DNSQuerier backed by miekg/dns.
type MiekgQuerier struct {
	udp *dns.Client
}

// NewMiekgQuerier constructs a UDP querier with the standard probe timeout.
func NewMiekgQuerier() *MiekgQuerier {
	return &MiekgQuerier{udp: &dns.Client{Net: "udp", Timeout: probeTimeout}}
}

// Exchange sends msg to server and returns the response.
func (q *MiekgQuerier) Exchange(msg *dns.Msg, server string) (*dns.Msg, error) {
	in, _, err := q.udp.Exchange(msg, server)
	return in, err
}

// ZoneProbeTarget describes one affected zone to verify through the canary
// Service. IPv6 is empty when the stable Service exposes no IPv6 addresses;
// an AAAA NODATA answer is then expected.
type ZoneProbeTarget struct {
	// Zone is the delegated load balanced zone (without trailing dot).
	Zone string
	// GlueNSName is this cluster's expected glue NS name.
	GlueNSName string
	// IPv4 is the current ipresolver exposed IPv4 set for the cluster.
	IPv4 []string
	// IPv6 is the current ipresolver exposed IPv6 set (may be empty).
	IPv6 []string
}

// QueryOutcome is the structured result of a single NS/A/AAAA query, carrying
// enough detail for anchor failure diagnostics.
type QueryOutcome struct {
	// Kind is "NS", "A" or "AAAA".
	Kind string
	// Rcode is the symbolic response code (e.g. NOERROR, SERVFAIL); empty on transport failure.
	Rcode string
	// Authoritative reports the AA flag.
	Authoritative bool
	// Expected is the required value set (NS names or IP addresses).
	Expected []string
	// Actual is the observed answer set.
	Actual []string
	// Timeout marks a transport timeout.
	Timeout bool
	// TransportError carries any non-timeout exchange error.
	TransportError string
	// Pass reports whether the outcome satisfies the requirement.
	Pass bool
}

// ProbeResult aggregates the three queries for one zone.
type ProbeResult struct {
	Zone    string
	NS      QueryOutcome
	A       QueryOutcome
	AAAA    QueryOutcome
	Pass    bool
	Summary string
}

// ProbeReport is the full verification result over every affected zone.
type ProbeReport struct {
	Results []ProbeResult
	// Pass is true only when every zone passes every applicable query.
	Pass bool
}

// Prober runs the authoritative verification against a fixed DNS server
// (the canary Service ClusterIP DNS name and mapped port).
type Prober struct {
	querier DNSQuerier
	server  string
}

// NewProber constructs a Prober. server must be host:port of the canary Service.
func NewProber(querier DNSQuerier, server string) *Prober {
	return &Prober{querier: querier, server: server}
}

// CanaryServerAddress derives the canary Service DNS server endpoint from the
// namespace and the cloned stable Service ports: the UDP service port (e.g.
// 53 mapping to container port 5353) is used, falling back to the first port.
func CanaryServerAddress(namespace string, ports []corev1.ServicePort) string {
	port := 0
	for _, p := range ports {
		if p.Protocol == corev1.ProtocolUDP {
			port = int(p.Port)
			break
		}
	}
	if port == 0 && len(ports) > 0 {
		port = int(ports[0].Port)
	}
	return fmt.Sprintf("%s.%s.svc:%d", CanaryServiceName, namespace, port)
}

// Probe executes the NS/A/AAAA verification for every target.
func (p *Prober) Probe(targets []ZoneProbeTarget) *ProbeReport {
	report := &ProbeReport{Pass: true}
	for _, target := range targets {
		result := ProbeResult{Zone: target.Zone}
		result.NS = p.probeNS(target)
		result.A = p.probeA(target)
		result.AAAA = p.probeAAAA(target)
		result.Pass = result.NS.Pass && result.A.Pass && result.AAAA.Pass
		result.Summary = summarize(result)
		if !result.Pass {
			report.Pass = false
		}
		report.Results = append(report.Results, result)
	}
	return report
}

func (p *Prober) probeNS(t ZoneProbeTarget) QueryOutcome {
	out := QueryOutcome{Kind: "NS", Expected: []string{dns.Fqdn(t.GlueNSName)}}
	msg := newQuery(dns.Fqdn(t.Zone), dns.TypeNS)
	resp, err := p.querier.Exchange(msg, p.server)
	if !out.fromExchange(resp, err) {
		return out
	}
	if !out.requireNOERRORAA(resp) {
		return out
	}
	var names []string
	for _, rr := range resp.Answer {
		if ns, ok := rr.(*dns.NS); ok {
			names = append(names, ns.Ns)
		}
	}
	out.Actual = sorted(names)
	out.Pass = containsFold(out.Actual, dns.Fqdn(t.GlueNSName))
	return out
}

func (p *Prober) probeA(t ZoneProbeTarget) QueryOutcome {
	out := QueryOutcome{Kind: "A", Expected: sorted(t.IPv4)}
	msg := newQuery(dns.Fqdn(t.GlueNSName), dns.TypeA)
	resp, err := p.querier.Exchange(msg, p.server)
	if !out.fromExchange(resp, err) {
		return out
	}
	if !out.requireNOERROR(resp) {
		return out
	}
	out.Actual = sorted(extractAddresses(resp, 4))
	out.Pass = equalSets(out.Expected, out.Actual)
	return out
}

func (p *Prober) probeAAAA(t ZoneProbeTarget) QueryOutcome {
	msg := newQuery(dns.Fqdn(t.GlueNSName), dns.TypeAAAA)
	resp, err := p.querier.Exchange(msg, p.server)
	out := QueryOutcome{Kind: "AAAA", Expected: sorted(t.IPv6)}
	if !out.fromExchange(resp, err) {
		return out
	}
	if !out.requireNOERROR(resp) {
		return out
	}
	out.Actual = sorted(extractAddresses(resp, 6))
	if len(t.IPv6) == 0 {
		// No IPv6 exposure: authoritative NODATA (NOERROR, no AAAA) passes.
		out.Pass = len(out.Actual) == 0
		return out
	}
	out.Pass = equalSets(out.Expected, out.Actual)
	return out
}

func newQuery(qname string, qtype uint16) *dns.Msg {
	msg := new(dns.Msg)
	msg.SetQuestion(qname, qtype)
	msg.RecursionDesired = false
	msg.SetEdns0(4096, true)
	return msg
}

// fromExchange records transport-level outcome; it returns false when the
// exchange failed so callers stop evaluating the response.
func (o *QueryOutcome) fromExchange(resp *dns.Msg, err error) bool {
	if err != nil {
		var netErr net.Error
		if errors.As(err, &netErr) && netErr.Timeout() {
			o.Timeout = true
		} else {
			o.TransportError = err.Error()
		}
		return false
	}
	if resp == nil {
		o.TransportError = "empty DNS response"
		return false
	}
	o.Rcode = dns.RcodeToString[resp.Rcode]
	o.Authoritative = resp.Authoritative
	return true
}

func (o *QueryOutcome) requireNOERROR(resp *dns.Msg) bool {
	if resp.Rcode != dns.RcodeSuccess {
		o.Pass = false
		return false
	}
	return true
}

func (o *QueryOutcome) requireNOERRORAA(resp *dns.Msg) bool {
	if !o.requireNOERROR(resp) {
		return false
	}
	if !resp.Authoritative {
		o.Pass = false
		return false
	}
	return true
}

func extractAddresses(resp *dns.Msg, family int) []string {
	var ips []string
	for _, rr := range resp.Answer {
		switch family {
		case 4:
			if a, ok := rr.(*dns.A); ok {
				ips = append(ips, a.A.String())
			}
		case 6:
			if aaaa, ok := rr.(*dns.AAAA); ok {
				ips = append(ips, aaaa.AAAA.String())
			}
		}
	}
	return ips
}

func summarize(r ProbeResult) string {
	parts := make([]string, 0, 3)
	for _, q := range []QueryOutcome{r.NS, r.A, r.AAAA} {
		parts = append(parts, fmt.Sprintf("%s(pass=%t rcode=%s aa=%t expected=%v actual=%v%s%s)",
			q.Kind, q.Pass, dash(q.Rcode), q.Authoritative, q.Expected, q.Actual,
			timeoutSuffix(q.Timeout), errSuffix(q.TransportError)))
	}
	return strings.Join(parts, "; ")
}

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func timeoutSuffix(timeout bool) string {
	if timeout {
		return " timeout"
	}
	return ""
}

func errSuffix(err string) string {
	if err != "" {
		return " error=" + err
	}
	return ""
}

func sorted(in []string) []string {
	if in == nil {
		return nil
	}
	out := append([]string(nil), in...)
	sort.Strings(out)
	return out
}

func equalSets(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// containsFold reports whether sorted set s contains v using ASCII
// case-insensitive comparison (DNS names are case-insensitive).
func containsFold(s []string, v string) bool {
	for _, item := range s {
		if strings.EqualFold(item, v) {
			return true
		}
	}
	return false
}
