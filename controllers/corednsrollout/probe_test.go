const (
	testZone    = "cloud.example.com"
	testGlueNS  = "gslb-ns-eu-cloud.example.com"
	testServer  = "k8gb-coredns-zd-canary.k8gb.svc:53"
	testOtherNS = "gslb-ns-us-cloud.example.com"
)

type scriptedQuerier map[uint16]func(*dns.Msg) (*dns.Msg, error)

func (q scriptedQuerier) Exchange(msg *dns.Msg, _ string) (*dns.Msg, error) {
	if fn, ok := q[msg.Question[0].Qtype]; ok {
		return fn(msg)
	}
	return nil, nil
}

type timeoutError struct{}

func (timeoutError) Error() string   { return "i/o timeout" }
func (timeoutError) Timeout() bool   { return true }
func (timeoutError) Temporary() bool { return true }

type genericError struct{}

func (genericError) Error() string   { return "connection refused" }
func (genericError) Timeout() bool   { return false }
func (genericError) Temporary() bool { return true }

var _ net.Error = timeoutError{}
var _ net.Error = genericError{}

func reply(req *dns.Msg, rcode int, aa bool, answers ...dns.RR) *dns.Msg {
	m := new(dns.Msg)
	m.SetReply(req)
	m.Rcode = rcode
	m.Authoritative = aa
	m.Answer = append(m.Answer, answers...)
	return m
}

func nsRR(zone, nameserver string) dns.RR {
	return &dns.NS{
		Hdr: dns.RR_Header{Name: dns.Fqdn(zone), Rrtype: dns.TypeNS, Class: dns.ClassINET, Ttl: 30},
		Ns:  dns.Fqdn(nameserver),
	}
}

func aRR(name, ip string) dns.RR {
	return &dns.A{
		Hdr: dns.RR_Header{Name: dns.Fqdn(name), Rrtype: dns.TypeA, Class: dns.ClassINET, Ttl: 30},
		A:   net.ParseIP(ip),
	}
}

func aaaaRR(ip string) dns.RR {
	return &dns.AAAA{
		Hdr:  dns.RR_Header{Name: dns.Fqdn(testGlueNS), Rrtype: dns.TypeAAAA, Class: dns.ClassINET, Ttl: 30},
		AAAA: net.ParseIP(ip),
	}
}

func dualStackTarget() ZoneProbeTarget {
	return ZoneProbeTarget{
		Zone:       testZone,
		GlueNSName: testGlueNS,
		IPv4:       []string{"10.0.0.1", "10.0.0.2"},
		IPv6:       []string{"fd00::1"},
	}
}

func singleStackTarget() ZoneProbeTarget {
	t := dualStackTarget()
	t.IPv6 = nil
	return t
}

func proberFor(q scriptedQuerier) *Prober {
	return NewProber(q, testServer)
}

func findResult(t *testing.T, report *ProbeReport) ProbeResult {
	t.Helper()
	require.Len(t, report.Results, 1)
	return report.Results[0]
}

func TestProbeHappyPathDualStack(t *testing.T) {
	// TR-7.1: NS (NOERROR+AA, contains local glue among peers), A set equal,
	// AAAA set equal (answer order shuffled) all pass.
	q := scriptedQuerier{
		dns.TypeNS: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true,
				nsRR(testZone, testOtherNS), nsRR(testZone, testGlueNS)), nil
		},
		dns.TypeA: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true,
				aRR(testGlueNS, "10.0.0.2"), aRR(testGlueNS, "10.0.0.1")), nil
		},
		dns.TypeAAAA: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true, aaaaRR("fd00::1")), nil
		},
	}
	report := proberFor(q).Probe([]ZoneProbeTarget{dualStackTarget()})
	assert.True(t, report.Pass)
	r := findResult(t, report)
	assert.True(t, r.NS.Pass)
	assert.True(t, r.A.Pass)
	assert.True(t, r.AAAA.Pass)
	assert.Equal(t, "NOERROR", r.NS.Rcode)
	assert.True(t, r.NS.Authoritative)
	assert.Equal(t, []string{"10.0.0.1", "10.0.0.2"}, r.A.Actual)
	assert.Equal(t, []string{"fd00::1"}, r.AAAA.Actual)
}

func TestProbeHappyPathSingleStackAAAANoData(t *testing.T) {
	// TR-7.1/TR-7.3: no IPv6 exposure -> NOERROR empty AAAA (NODATA) passes.
	q := scriptedQuerier{
		dns.TypeNS: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true, nsRR(testZone, testGlueNS)), nil
		},
		dns.TypeA: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true,
				aRR(testGlueNS, "10.0.0.1"), aRR(testGlueNS, "10.0.0.2")), nil
		},
		dns.TypeAAAA: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true), nil
		},
	}
	report := proberFor(q).Probe([]ZoneProbeTarget{singleStackTarget()})
	assert.True(t, report.Pass, findResult(t, report).Summary)
}

func TestProbeFailureModes(t *testing.T) {
	// TR-7.2: every failure class is rejected with a structured summary.
	happyNS := func(req *dns.Msg) (*dns.Msg, error) {
		return reply(req, dns.RcodeSuccess, true, nsRR(testZone, testGlueNS)), nil
	}
	happyA := func(req *dns.Msg) (*dns.Msg, error) {
		return reply(req, dns.RcodeSuccess, true,
			aRR(testGlueNS, "10.0.0.1"), aRR(testGlueNS, "10.0.0.2")), nil
	}
	happyAAAA := func(req *dns.Msg) (*dns.Msg, error) {
		return reply(req, dns.RcodeSuccess, true, aaaaRR("fd00::1")), nil
	}

	cases := []struct {
		name      string
		target    ZoneProbeTarget
		query     uint16
		script    func(*dns.Msg) (*dns.Msg, error)
		kind      string
		checkFunc func(t *testing.T, o QueryOutcome)
	}{
		{
			name: "NS SERVFAIL", query: dns.TypeNS, kind: "NS",
			script: func(req *dns.Msg) (*dns.Msg, error) { return reply(req, dns.RcodeServerFailure, false), nil },
			checkFunc: func(t *testing.T, o QueryOutcome) {
				assert.Equal(t, "SERVFAIL", o.Rcode)
			},
		},
		{
			name: "NS REFUSED", query: dns.TypeNS, kind: "NS",
			script: func(req *dns.Msg) (*dns.Msg, error) { return reply(req, dns.RcodeRefused, false), nil },
			checkFunc: func(t *testing.T, o QueryOutcome) {
				assert.Equal(t, "REFUSED", o.Rcode)
			},
		},
		{
			name: "NS timeout", query: dns.TypeNS, kind: "NS",
			script: func(_ *dns.Msg) (*dns.Msg, error) { return nil, timeoutError{} },
			checkFunc: func(t *testing.T, o QueryOutcome) {
				assert.True(t, o.Timeout)
				assert.Empty(t, o.Rcode)
			},
		},
		{
			name: "NS transport error", query: dns.TypeNS, kind: "NS",
			script: func(_ *dns.Msg) (*dns.Msg, error) { return nil, genericError{} },
			checkFunc: func(t *testing.T, o QueryOutcome) {
				assert.Contains(t, o.TransportError, "connection refused")
			},
		},
		{
			name: "NS answer is not authoritative", query: dns.TypeNS, kind: "NS",
			script: func(req *dns.Msg) (*dns.Msg, error) {
				return reply(req, dns.RcodeSuccess, false, nsRR(testZone, testGlueNS)), nil
			},
			checkFunc: func(t *testing.T, o QueryOutcome) {
				assert.False(t, o.Authoritative)
			},
		},
		{
			name: "NS set missing local glue", query: dns.TypeNS, kind: "NS",
			script: func(req *dns.Msg) (*dns.Msg, error) {
				return reply(req, dns.RcodeSuccess, true, nsRR(testZone, testOtherNS)), nil
			},
			checkFunc: func(t *testing.T, o QueryOutcome) {
				assert.NotEmpty(t, o.Actual)
			},
		},
		{
			name: "A set has extra IP", query: dns.TypeA, kind: "A", target: dualStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) {
				return reply(req, dns.RcodeSuccess, true,
					aRR(testGlueNS, "10.0.0.1"), aRR(testGlueNS, "10.0.0.2"), aRR(testGlueNS, "10.0.0.9")), nil
			},
		},
		{
			name: "A set missing IP", query: dns.TypeA, kind: "A", target: dualStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) {
				return reply(req, dns.RcodeSuccess, true, aRR(testGlueNS, "10.0.0.1")), nil
			},
		},
		{
			name: "A set wrong IP", query: dns.TypeA, kind: "A", target: dualStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) {
				return reply(req, dns.RcodeSuccess, true,
					aRR(testGlueNS, "10.0.0.1"), aRR(testGlueNS, "10.0.0.9")), nil
			},
		},
		{
			name: "AAAA missing when v6 exposed", query: dns.TypeAAAA, kind: "AAAA", target: dualStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) { return reply(req, dns.RcodeSuccess, true), nil },
		},
		{
			name: "AAAA wrong when v6 exposed", query: dns.TypeAAAA, kind: "AAAA", target: dualStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) {
				return reply(req, dns.RcodeSuccess, true, aaaaRR("fd00::9")), nil
			},
		},
		{
			name: "AAAA error rcode without v6 exposure", query: dns.TypeAAAA, kind: "AAAA", target: singleStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) { return reply(req, dns.RcodeServerFailure, false), nil },
		},
		{
			name: "AAAA unexpected answer without v6 exposure", query: dns.TypeAAAA, kind: "AAAA", target: singleStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) {
				return reply(req, dns.RcodeSuccess, true, aaaaRR("fd00::1")), nil
			},
		},
		{
			name: "A SERVFAIL", query: dns.TypeA, kind: "A", target: dualStackTarget(),
			script: func(req *dns.Msg) (*dns.Msg, error) { return reply(req, dns.RcodeServerFailure, false), nil },
			checkFunc: func(t *testing.T, o QueryOutcome) {
				assert.Equal(t, "SERVFAIL", o.Rcode)
			},
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			target := tc.target
			if target.Zone == "" {
				target = dualStackTarget()
			}
			q := scriptedQuerier{
				dns.TypeNS:   happyNS,
				dns.TypeA:    happyA,
				dns.TypeAAAA: happyAAAA,
			}
			q[tc.query] = tc.script

			report := proberFor(q).Probe([]ZoneProbeTarget{target})
			require.False(t, report.Pass)
			r := findResult(t, report)
			var outcome QueryOutcome
			switch tc.kind {
			case "NS":
				outcome = r.NS
			case "A":
				outcome = r.A
			case "AAAA":
				outcome = r.AAAA
			}
			assert.False(t, outcome.Pass)
			assert.Contains(t, r.Summary, tc.kind+"(pass=false")
			if tc.checkFunc != nil {
				tc.checkFunc(t, outcome)
			}
		})
	}
}

func TestProbeMultipleZonesAllMustPass(t *testing.T) {
	q := scriptedQuerier{
		dns.TypeNS: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true,
				nsRR(req.Question[0].Name, "gslb-ns-eu-"+req.Question[0].Name)), nil
		},
		dns.TypeA: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true, aRR(req.Question[0].Name, "10.0.0.1")), nil
		},
		dns.TypeAAAA: func(req *dns.Msg) (*dns.Msg, error) {
			return reply(req, dns.RcodeSuccess, true), nil
		},
	}
	targets := []ZoneProbeTarget{
		{Zone: "cloud.example.com", GlueNSName: "gslb-ns-eu-cloud.example.com", IPv4: []string{"10.0.0.1"}},
		{Zone: "cloud2.example.com", GlueNSName: "gslb-ns-eu-cloud2.example.com", IPv4: []string{"10.0.0.1"}},
	}
	report := proberFor(q).Probe(targets)
	assert.Len(t, report.Results, 2)
	assert.True(t, report.Pass)
}

func TestCanaryServerAddress(t *testing.T) {
	ports := []corev1.ServicePort{
		{Name: "udp-53", Port: 53, TargetPort: intstr.FromInt(5353), Protocol: corev1.ProtocolUDP},
		{Name: "tcp-53", Port: 53, TargetPort: intstr.FromInt(5353), Protocol: corev1.ProtocolTCP},
	}
	assert.Equal(t, "k8gb-coredns-zd-canary.k8gb.svc:53", CanaryServerAddress("k8gb", ports))

	tcpOnly := []corev1.ServicePort{{Name: "dns", Port: 5353, Protocol: corev1.ProtocolTCP}}
	assert.Equal(t, "k8gb-coredns-zd-canary.k8gb.svc:5353", CanaryServerAddress("k8gb", tcpOnly))
}
