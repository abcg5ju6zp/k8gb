const testNamespace = "k8gb"

func testScheme(t *testing.T) *runtime.Scheme {
	scheme := runtime.NewScheme()
	require.NoError(t, corev1.AddToScheme(scheme))
	require.NoError(t, appsv1.AddToScheme(scheme))
	require.NoError(t, v1beta1io.AddToScheme(scheme))
	return scheme
}

func newAnchor(data map[string]string) *corev1.ConfigMap {
	return &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:        AnchorConfigMapName,
			Namespace:   testNamespace,
			Annotations: map[string]string{},
		},
		Data: data,
	}
}

func newStoreWith(t *testing.T, funcs interceptor.Funcs, objs ...client.Object) *Store {
	return NewStore(fake.NewClientBuilder().
		WithScheme(testScheme(t)).
		WithObjects(objs...).
		WithInterceptorFuncs(funcs).
		Build(), testNamespace)
}

func newStore(t *testing.T, objs ...client.Object) *Store {
	return newStoreWith(t, interceptor.Funcs{}, objs...)
}

// configMapsOf lists every ConfigMap currently visible to the store client.
func configMapsOf(ctx context.Context, t *testing.T, s *Store) []corev1.ConfigMap {
	list := &corev1.ConfigMapList{}
	require.NoError(t, s.client.List(ctx, list, client.InNamespace(testNamespace)))
	return list.Items
}

func desiredZones(zones ...string) Desired {
	list := &v1beta1io.ZoneDelegationList{}
	for _, z := range zones {
		list.Items = append(list.Items, zoneDelegation(z))
	}
	return Normalize(list)
}

func getGenerationCM(ctx context.Context, t *testing.T, s *Store, fingerprint string) *corev1.ConfigMap {
	cm := &corev1.ConfigMap{}
	require.NoError(t, s.client.Get(ctx, client.ObjectKey{
		Namespace: testNamespace,
		Name:      GenerationConfigMapName(fingerprint),
	}, cm))
	return cm
}

func TestAdoptFreshEnvironment(t *testing.T) {
	// TR-4.1: fresh environment adopts desired data as immutable gen-0 and the
	// anchor mirrors it.
	ctx := context.Background()
	desired := desiredZones("cloud.example.com")
	s := newStore(t, newAnchor(map[string]string{}))

	state, err := s.AdoptIfNeeded(ctx, desired)
	require.NoError(t, err)
	assert.Equal(t, desired.Fingerprint, state.Active)
	assert.Equal(t, PhaseActive, state.Phase)

	anchor, err := s.GetAnchor(ctx)
	require.NoError(t, err)
	assert.Equal(t, desired.Fingerprint, anchor.Annotations[AnnActiveGeneration])
	assert.Equal(t, desired.Data, anchor.Data)

	gen := getGenerationCM(ctx, t, s, desired.Fingerprint)
	require.NotNil(t, gen.Immutable)
	assert.True(t, *gen.Immutable)
	assert.Equal(t, desired.Data, gen.Data)
	assert.Equal(t, RoleGeneration, gen.Labels[LabelRole])

	// Adoption is idempotent: with an active generation present a different
	// desired set does not change the anchor.
	state2, err := s.AdoptIfNeeded(ctx, desiredZones("cloud2.example.com"))
	require.NoError(t, err)
	assert.Equal(t, state.Active, state2.Active)
	anchor2, err := s.GetAnchor(ctx)
	require.NoError(t, err)
	assert.Equal(t, desired.Data, anchor2.Data)
}

func TestAdoptSnapshotsExistingAnchorData(t *testing.T) {
	// TR-4.1: when the anchor already carries data, gen-0 snapshots that data
	// byte for byte and the anchor content is preserved.
	ctx := context.Background()
	legacy := map[string]string{
		"cloud-example-com.conf": "cloud.example.com:5353 {\n  import k8gbplugins\n}\n",
	}
	s := newStore(t, newAnchor(legacy))

	state, err := s.AdoptIfNeeded(ctx, desiredZones("cloud.example.com", "cloud2.example.com"))
	require.NoError(t, err)
	assert.Equal(t, Fingerprint(legacy), state.Active)

	anchor, err := s.GetAnchor(ctx)
	require.NoError(t, err)
	assert.Equal(t, legacy, anchor.Data)

	gen := getGenerationCM(ctx, t, s, Fingerprint(legacy))
	require.NotNil(t, gen.Immutable)
	assert.True(t, *gen.Immutable)
	assert.Equal(t, legacy, gen.Data)
}

func TestCandidateCreationFailureIsDiscarded(t *testing.T) {
	// TR-4.2: failed candidate creation leaves no generation ConfigMap behind,
	// records a diagnostic and keeps the active generation; a healthy retry
	// succeeds.
	ctx := context.Background()
	active := desiredZones("cloud.example.com")

	// Seed an already-adopted anchor on the failing client.
	seed := newAnchor(active.Data)
	seed.Annotations[AnnActiveGeneration] = active.Fingerprint
	seed.Annotations[AnnCandidatePhase] = string(PhaseActive)

	sFail := newStoreWith(t, interceptor.Funcs{
		Create: func(_ context.Context, _ client.WithWatch, obj client.Object, _ ...client.CreateOption) error {
			if _, ok := obj.(*corev1.ConfigMap); ok && obj.GetName() != AnchorConfigMapName {
				return errors.New("apiserver unavailable")
			}
			return nil
		},
	}, seed)

	candidate := desiredZones("cloud.example.com", "cloud2.example.com")
	_, err := sFail.EnsureGenerationCM(ctx, candidate)
	assert.Error(t, err)

	diag := FailureDiagnostic{
		Hash:      candidate.Fingerprint,
		Phase:     PhaseCandidateRolling,
		Reason:    ReasonCandidateWriteFailed,
		Detail:    "apiserver unavailable",
		Timestamp: time.Now(),
	}
	require.NoError(t, sFail.DiscardCandidate(ctx, diag))

	for _, cm := range configMapsOf(ctx, t, sFail) {
		assert.NotEqual(t, GenerationConfigMapName(candidate.Fingerprint), cm.Name)
	}
	anchor, err := sFail.GetAnchor(ctx)
	require.NoError(t, err)
	assert.Equal(t, active.Fingerprint, anchor.Annotations[AnnActiveGeneration])
	assert.NotContains(t, anchor.Annotations, AnnCandidateGeneration)
	assert.Contains(t, anchor.Annotations[AnnLastFailure], ReasonCandidateWriteFailed)

	// Retry on a healthy client succeeds.
	s := newStore(t, newAnchor(active.Data))
	_, err = s.EnsureGenerationCM(ctx, candidate)
	assert.NoError(t, err)
	getGenerationCM(ctx, t, s, candidate.Fingerprint)
}

func TestGenerationCMAlreadyExistsIsIdempotent(t *testing.T) {
	// TR-4.3: an existing generation ConfigMap makes creation a success
	// without any update against the existing object.
	ctx := context.Background()
	desired := desiredZones("cloud.example.com")
	s := newStore(t, newAnchor(map[string]string{}))
	_, err := s.EnsureGenerationCM(ctx, desired)
	require.NoError(t, err)
	genBefore := getGenerationCM(ctx, t, s, desired.Fingerprint)

	updated := 0
	sNoUpdate := newStoreWith(t, interceptor.Funcs{
		Update: func(_ context.Context, _ client.WithWatch, _ client.Object, _ ...client.UpdateOption) error {
			updated++
			return nil
		},
	}, newAnchor(map[string]string{}), genBefore.DeepCopy())
	_, err = sNoUpdate.EnsureGenerationCM(ctx, desired)
	require.NoError(t, err)
	assert.Equal(t, 0, updated)

	genAfter := getGenerationCM(ctx, t, sNoUpdate, desired.Fingerprint)
	assert.Equal(t, genBefore.ResourceVersion, genAfter.ResourceVersion)
	assert.Equal(t, genBefore.Data, genAfter.Data)
}

func TestAnchorOptimisticConflictRetries(t *testing.T) {
	// TR-4.4: anchor update conflicts are retried and converge to the new state.
	ctx := context.Background()
	active := desiredZones("cloud.example.com")
	anchor := newAnchor(active.Data)
	anchor.Annotations[AnnActiveGeneration] = active.Fingerprint

	attempts := 0
	sConflict := newStoreWith(t, interceptor.Funcs{
		Update: func(ctx context.Context, c client.WithWatch, obj client.Object, opts ...client.UpdateOption) error {
			if obj.GetName() == AnchorConfigMapName {
				attempts++
				if attempts == 1 {
					return apierrors.NewConflict(schema.GroupResource{Resource: "configmaps"}, obj.GetName(),
						errors.New("the object has been modified"))
				}
			}
			return c.Update(ctx, obj, opts...)
		},
	}, anchor, func() *corev1.ConfigMap {
		cm := &corev1.ConfigMap{
			ObjectMeta: metav1.ObjectMeta{
				Name:      GenerationConfigMapName(active.Fingerprint),
				Namespace: testNamespace,
				Labels:    map[string]string{LabelManagedBy: ManagedByValue, LabelRole: RoleGeneration},
			},
			Data:      active.Data,
			Immutable: ptrBool(true),
		}
		return cm
	}())

	candidateSince := time.Date(2026, 10, 10, 8, 0, 0, 0, time.UTC)
	require.NoError(t, sConflict.SetCandidate(ctx, "abcdef123456", PhaseCandidateRolling, candidateSince))
	assert.Equal(t, 2, attempts)

	got, err := sConflict.GetAnchor(ctx)
	require.NoError(t, err)
	assert.Equal(t, "abcdef123456", got.Annotations[AnnCandidateGeneration])
	assert.Equal(t, string(PhaseCandidateRolling), got.Annotations[AnnCandidatePhase])
}

