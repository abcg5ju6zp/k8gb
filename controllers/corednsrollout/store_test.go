func TestQuarantineCandidateLabelsGenerationAndAnchor(t *testing.T) {
	// FR-11/AC-17: quarantine labels the generation ConfigMap metadata (allowed
	// despite immutability), keeps the candidate in Quarantined phase and
	// records the diagnostic while the active generation is untouched.
	ctx := context.Background()
	active := desiredZones("cloud.example.com")
	candidate := desiredZones("cloud.example.com", "cloud2.example.com")

	genCandidate := &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:      GenerationConfigMapName(candidate.Fingerprint),
			Namespace: testNamespace,
			Labels:    map[string]string{LabelManagedBy: ManagedByValue, LabelRole: RoleGeneration, LabelGeneration: candidate.Fingerprint},
		},
		Data:      candidate.Data,
		Immutable: ptrBool(true),
	}
	anchor := newAnchor(active.Data)
	anchor.Annotations[AnnActiveGeneration] = active.Fingerprint
	anchor.Annotations[AnnCandidateGeneration] = candidate.Fingerprint
	anchor.Annotations[AnnCandidatePhase] = string(PhaseCandidateProbing)
	s := newStore(t, anchor, genCandidate)

	diag := FailureDiagnostic{
		Hash:      candidate.Fingerprint,
		Phase:     PhaseCandidateProbing,
		Reason:    ReasonProbeFailed,
		Zone:      "cloud2.example.com",
		Detail:    "A record set mismatch",
		Timestamp: time.Now().UTC(),
	}
	require.NoError(t, s.QuarantineCandidate(ctx, diag))

	labeled := getGenerationCM(ctx, t, s, candidate.Fingerprint)
	assert.Equal(t, ReasonProbeFailed, labeled.Labels[LabelQuarantine])
	assert.Equal(t, ReasonProbeFailed, labeled.Annotations[AnnQuarantineReason])
	assert.Equal(t, candidate.Data, labeled.Data)

	got, err := s.GetAnchor(ctx)
	require.NoError(t, err)
	assert.Equal(t, active.Fingerprint, got.Annotations[AnnActiveGeneration])
	assert.Equal(t, candidate.Fingerprint, got.Annotations[AnnCandidateGeneration])
	assert.Equal(t, string(PhaseQuarantined), got.Annotations[AnnCandidatePhase])
	state := State(got)
	require.NotNil(t, state.LastFailure)
	assert.Equal(t, ReasonProbeFailed, state.LastFailure.Reason)
	assert.Equal(t, "cloud2.example.com", state.LastFailure.Zone)
	assert.Equal(t, active.Data, got.Data)
}

func TestStateRoundTrip(t *testing.T) {
	anchor := newAnchor(nil)
	anchor.Annotations = map[string]string{
		AnnActiveGeneration:    "111111111111",
		AnnCandidateGeneration: "222222222222",
		AnnCandidatePhase:      string(PhaseCandidateProbing),
	}
	diag := FailureDiagnostic{Hash: "222222222222", Phase: PhaseCandidateProbing, Reason: ReasonProbeFailed, Timestamp: time.Now()}
	writeFailure(anchor, &diag)

	state := State(anchor)
	assert.Equal(t, "111111111111", state.Active)
	assert.Equal(t, "222222222222", state.Candidate)
	assert.Equal(t, PhaseCandidateProbing, state.Phase)
	require.NotNil(t, state.LastFailure)
	assert.Equal(t, ReasonProbeFailed, state.LastFailure.Reason)
	assert.Equal(t, "222222222222", state.LastFailure.Hash)

	assert.Equal(t, PhaseActive, State(nil).Phase)
}
