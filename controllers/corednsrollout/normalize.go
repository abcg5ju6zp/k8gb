import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"

	"github.com/k8gb-io/k8gb/api/v1beta1io"
)

const (
	// fingerprintLength is the truncated hex fingerprint length used in
	// generation ConfigMap names.
	fingerprintLength = 12
	// configFileSuffix mirrors zones.configName.
	configFileSuffix = ".conf"
)

// coreDNSZoneData renders a single dynamic zone file. The output is byte
// identical to zones.getCoreDNSData.
func coreDNSZoneData(zone string) string {
	return fmt.Sprintf("%s:5353 {\n  import k8gbplugins\n}\n", zone)
}

// configName renders the ConfigMap data key for a zone. It is byte identical
// to zones.configName/objectName.
func configName(zone string) string {
	return strings.ReplaceAll(zone, ".", "-") + configFileSuffix
}

// Normalize renders the deterministic desired ConfigMap data for the given
// ZoneDelegation set (zone delegations being deleted are skipped) and computes
// its content fingerprint. Data keys are sorted for the fingerprint; the
// returned map itself is unordered like every Go map.
func Normalize(zones *v1beta1io.ZoneDelegationList) Desired {
	data := make(map[string]string)
	if zones != nil {
		for _, zone := range zones.Items {
			if zone.IsInDeletion() {
				continue
			}
			data[configName(zone.Spec.LoadBalancedZone)] = coreDNSZoneData(zone.Spec.LoadBalancedZone)
		}
	}
	return Desired{
		Data:        data,
		Fingerprint: Fingerprint(data),
	}
}

// Fingerprint returns the truncated SHA-256 fingerprint of a ConfigMap data
// map over a canonical length-prefixed, key-sorted encoding.
func Fingerprint(data map[string]string) string {
	keys := make([]string, 0, len(data))
	for k := range data {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	h := sha256.New()
	for _, k := range keys {
		fmt.Fprintf(h, "%d:%s\x00%d:%s\x00", len(k), k, len(data[k]), data[k])
	}
	return hex.EncodeToString(h.Sum(nil))[:fingerprintLength]
}
