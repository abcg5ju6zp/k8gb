// conflictRetries bounds anchor optimistic-concurrency retries.
const conflictRetries = 5

// Store is the single component allowed to read and write the anchor and
// generation ConfigMaps. Generation ConfigMaps are created once and never
// updated (only labels/annotations may be added for quarantine diagnostics).
type Store struct {
	client    client.Client
	namespace string
}

func NewStore(c client.Client, namespace string) *Store {
	return &Store{client: c, namespace: namespace}
}

// AnchorKey returns the namespaced name of the anchor ConfigMap.
func (s *Store) AnchorKey() types.NamespacedName {
	return types.NamespacedName{Namespace: s.namespace, Name: AnchorConfigMapName}
}

// GetAnchor reads the anchor ConfigMap.
func (s *Store) GetAnchor(ctx context.Context) (*corev1.ConfigMap, error) {
	anchor := &corev1.ConfigMap{}
	if err := s.client.Get(ctx, s.AnchorKey(), anchor); err != nil {
		return nil, err
	}
	return anchor, nil
}

// getOrCreateAnchor reads the anchor or creates an empty one (the Helm chart
// normally creates it; this keeps the controller self-sufficient in tests).
func (s *Store) getOrCreateAnchor(ctx context.Context) (*corev1.ConfigMap, error) {
	anchor, err := s.GetAnchor(ctx)
	if err == nil {
		return anchor, nil
	}
	if !apierrors.IsNotFound(err) {
		return nil, err
	}
	anchor = &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:      AnchorConfigMapName,
			Namespace: s.namespace,
			Labels:    map[string]string{LabelManagedBy: ManagedByValue},
		},
		Data: map[string]string{},
	}
	if err := s.client.Create(ctx, anchor); err != nil && !apierrors.IsAlreadyExists(err) {
		return nil, err
	}
	return s.GetAnchor(ctx)
}

// State reconstructs the rollout state from the anchor annotations.
func State(anchor *corev1.ConfigMap) *GenerationState {
	state := &GenerationState{Phase: PhaseActive}
	if anchor == nil {
		return state
	}
	state.Active = anchor.Annotations[AnnActiveGeneration]
	state.Candidate = anchor.Annotations[AnnCandidateGeneration]
	if phase := Phase(anchor.Annotations[AnnCandidatePhase]); phase != "" {
		state.Phase = phase
	}
	state.CandidateSince = parseTime(anchor.Annotations[AnnCandidateSince])
	state.PromotionSince = parseTime(anchor.Annotations[AnnPromotionSince])
	if raw := anchor.Annotations[AnnPromotionSnapshot]; raw != "" {
		snap := &WorkloadSnapshot{}
		if err := json.Unmarshal([]byte(raw), snap); err == nil {
			state.PromotionSnapshot = snap
		}
	}
	if raw := anchor.Annotations[AnnLastFailure]; raw != "" {
		diag := &FailureDiagnostic{}
		if err := json.Unmarshal([]byte(raw), diag); err == nil {
			state.LastFailure = diag
		}
	}
	return state
}

// AdoptIfNeeded snapshots the current configuration as immutable generation
// zero when no active generation exists yet. When the anchor already carries
// zone data, that data is the gen-0 snapshot (upgrade case); otherwise the
// desired data becomes gen-0 (fresh install case). The anchor data always
// mirrors the active generation.
func (s *Store) AdoptIfNeeded(ctx context.Context, desired Desired) (*GenerationState, error) {
	var result *GenerationState
	err := s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		state := State(anchor)
		if state.Active != "" {
			result = state
			return nil
		}
		genData := desired.Data
		if len(anchor.Data) > 0 {
			genData = cloneData(anchor.Data)
		}
		fingerprint := Fingerprint(genData)
		if err := s.ensureGenerationCM(ctx, genData, fingerprint); err != nil {
			return err
		}
		anchor.Data = cloneData(genData)
		anchor.Annotations[AnnActiveGeneration] = fingerprint
		delete(anchor.Annotations, AnnCandidateGeneration)
		delete(anchor.Annotations, AnnCandidatePhase)
		delete(anchor.Annotations, AnnCandidateSince)
		delete(anchor.Annotations, AnnPromotionSince)
		delete(anchor.Annotations, AnnPromotionSnapshot)
		result = &GenerationState{Active: fingerprint, Phase: PhaseActive}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return result, nil
}

// EnsureGenerationCM creates the immutable generation ConfigMap for the
// candidate. An already existing ConfigMap with the same content-addressed
// name is treated as success and is never modified.
func (s *Store) EnsureGenerationCM(ctx context.Context, desired Desired) (string, error) {
	if err := s.ensureGenerationCM(ctx, desired.Data, desired.Fingerprint); err != nil {
		return "", err
	}
	return GenerationConfigMapName(desired.Fingerprint), nil
}

func (s *Store) ensureGenerationCM(ctx context.Context, data map[string]string, fingerprint string) error {
	cm := &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:      GenerationConfigMapName(fingerprint),
			Namespace: s.namespace,
			Labels: map[string]string{
				LabelManagedBy:  ManagedByValue,
				LabelRole:       RoleGeneration,
				LabelGeneration: fingerprint,
			},
			Annotations: map[string]string{AnnFingerprint: fingerprint},
		},
		Data:      cloneData(data),
		Immutable: ptrBool(true),
	}
	if err := s.client.Create(ctx, cm); err != nil {
		if apierrors.IsAlreadyExists(err) {
			return nil
		}
		return fmt.Errorf("cannot create generation ConfigMap %s: %w", cm.Name, err)
	}
	return nil
}

// SetCandidate marks the in-flight candidate fingerprint and phase and records
// when the canary rollout started, establishing the readiness deadline.
func (s *Store) SetCandidate(ctx context.Context, fingerprint string, phase Phase, since time.Time) error {
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		anchor.Annotations[AnnCandidateGeneration] = fingerprint
		anchor.Annotations[AnnCandidatePhase] = string(phase)
		anchor.Annotations[AnnCandidateSince] = since.UTC().Format(time.RFC3339)
		delete(anchor.Annotations, AnnPromotionSince)
		delete(anchor.Annotations, AnnPromotionSnapshot)
		return nil
	})
}

// SetPhase transitions the candidate to a new phase. Entering the Promoting
// phase records the production rollout start time as its timeout deadline.
func (s *Store) SetPhase(ctx context.Context, phase Phase, at time.Time) error {
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		anchor.Annotations[AnnCandidatePhase] = string(phase)
		if phase == PhasePromoting {
			anchor.Annotations[AnnPromotionSince] = at.UTC().Format(time.RFC3339)
		}
		return nil
	})
}

// EnterPromotion persists the phase switch to Promoting together with the
// captured pre-promotion snapshot and the rollout deadline. The snapshot is
// what makes a crash during promotion recoverable.
func (s *Store) EnterPromotion(ctx context.Context, snap WorkloadSnapshot, at time.Time) error {
	raw, err := json.Marshal(snap)
	if err != nil {
		return err
	}
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		anchor.Annotations[AnnCandidatePhase] = string(PhasePromoting)
		anchor.Annotations[AnnPromotionSince] = at.UTC().Format(time.RFC3339)
		anchor.Annotations[AnnPromotionSnapshot] = string(raw)
		return nil
	})
}

// ClearPromotion drops the promotion timing and snapshot after a successful,
// rolled-back or superseded promotion.
func (s *Store) ClearPromotion(ctx context.Context) error {
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		delete(anchor.Annotations, AnnPromotionSince)
		delete(anchor.Annotations, AnnPromotionSnapshot)
		return nil
	})
}

// RecordFailure writes a structured diagnostic without changing any candidate
// or active state. It is used for failures observed before a candidate exists
// (e.g. static validation rejection).
func (s *Store) RecordFailure(ctx context.Context, diag FailureDiagnostic) error {
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		writeFailure(anchor, &diag)
		return nil
	})
}

// QuarantineCandidate isolates a candidate that failed readiness or probing:
// the candidate annotation is retained with the Quarantined phase, a
// diagnostic is recorded and the generation ConfigMap is labeled/annotated
// with the reason (metadata updates remain allowed on immutable ConfigMaps).
func (s *Store) QuarantineCandidate(ctx context.Context, diag FailureDiagnostic) error {
	if err := s.markGenerationQuarantined(ctx, diag.Hash, diag.Reason, diag.Timestamp); err != nil {
		return err
	}
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		anchor.Annotations[AnnCandidateGeneration] = diag.Hash
		anchor.Annotations[AnnCandidatePhase] = string(PhaseQuarantined)
		writeFailure(anchor, &diag)
		return nil
	})
}

// DiscardCandidate removes a candidate whose creation failed (no workload can
// reference it yet), clears the candidate annotations and records the
// diagnostic. The active generation is never deleted and stays unchanged.
func (s *Store) DiscardCandidate(ctx context.Context, diag FailureDiagnostic) error {
	anchor, err := s.GetAnchor(ctx)
	if err != nil && !apierrors.IsNotFound(err) {
		return err
	}
	if diag.Hash != "" && (anchor == nil || State(anchor).Active != diag.Hash) {
		if delErr := s.client.Delete(ctx, &corev1.ConfigMap{
			ObjectMeta: metav1.ObjectMeta{Namespace: s.namespace, Name: GenerationConfigMapName(diag.Hash)},
		}); delErr != nil && !apierrors.IsNotFound(delErr) {
			return delErr
		}
	}
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		delete(anchor.Annotations, AnnCandidateGeneration)
		delete(anchor.Annotations, AnnCandidatePhase)
		delete(anchor.Annotations, AnnCandidateSince)
		delete(anchor.Annotations, AnnPromotionSince)
		delete(anchor.Annotations, AnnPromotionSnapshot)
		writeFailure(anchor, &diag)
		return nil
	})
}

// ClearCandidate drops candidate annotations without touching diagnostics.
func (s *Store) ClearCandidate(ctx context.Context) error {
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		delete(anchor.Annotations, AnnCandidateGeneration)
		delete(anchor.Annotations, AnnCandidatePhase)
		delete(anchor.Annotations, AnnCandidateSince)
		delete(anchor.Annotations, AnnPromotionSince)
		delete(anchor.Annotations, AnnPromotionSnapshot)
		return nil
	})
}

// PromoteActive atomically switches the active generation and mirrors its data
// into the anchor ConfigMap. Candidate annotations are cleared.
func (s *Store) PromoteActive(ctx context.Context, data Desired) error {
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		anchor.Data = cloneData(data.Data)
		anchor.Annotations[AnnActiveGeneration] = data.Fingerprint
		anchor.Annotations[AnnCandidatePhase] = string(PhaseActive)
		delete(anchor.Annotations, AnnCandidateGeneration)
		delete(anchor.Annotations, AnnCandidateSince)
		delete(anchor.Annotations, AnnPromotionSince)
		delete(anchor.Annotations, AnnPromotionSnapshot)
		return nil
	})
}

// WriteAnchorDataLegacy replaces the anchor ConfigMap data directly,
// reproducing the pre-rollout controller behavior used when the feature is
// disabled or workload discovery fails. No generation resources are touched.
func (s *Store) WriteAnchorDataLegacy(ctx context.Context, data map[string]string) error {
	return s.mutateAnchor(ctx, func(anchor *corev1.ConfigMap) error {
		anchor.Data = cloneData(data)
		return nil
	})
}

// ListGenerationCMs enumerates generation ConfigMaps owned by the controller.
func (s *Store) ListGenerationCMs(ctx context.Context) (*corev1.ConfigMapList, error) {
	list := &corev1.ConfigMapList{}
	if err := s.client.List(ctx, list,
		client.InNamespace(s.namespace),
		client.MatchingLabels{LabelManagedBy: ManagedByValue, LabelRole: RoleGeneration}); err != nil {
		return nil, err
	}
	return list, nil
}

// DeleteGenerationCM removes an unreferenced generation ConfigMap. It refuses
// to delete the active generation; NotFound is treated as success.
func (s *Store) DeleteGenerationCM(ctx context.Context, name, activeFingerprint string) error {
	if name == GenerationConfigMapName(activeFingerprint) {
		return fmt.Errorf("refusing to delete active generation ConfigMap %s", name)
	}
	err := s.client.Delete(ctx, &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{Namespace: s.namespace, Name: name},
	})
	if err != nil && !apierrors.IsNotFound(err) {
		return err
	}
	return nil
}

func (s *Store) markGenerationQuarantined(ctx context.Context, fingerprint, reason string, at time.Time) error {
	cm := &corev1.ConfigMap{}
	key := types.NamespacedName{Namespace: s.namespace, Name: GenerationConfigMapName(fingerprint)}
	if err := s.client.Get(ctx, key, cm); err != nil {
		if apierrors.IsNotFound(err) {
			return nil
		}
		return err
	}
	if cm.Labels == nil {
		cm.Labels = map[string]string{}
	}
	if cm.Annotations == nil {
		cm.Annotations = map[string]string{}
	}
	cm.Labels[LabelQuarantine] = reason
	cm.Annotations[AnnQuarantineReason] = reason
	cm.Annotations[AnnQuarantinedAt] = at.UTC().Format(time.RFC3339)
	return s.client.Update(ctx, cm)
}

// mutateAnchor runs mutate against the latest anchor and persists it, retrying
// optimistic-concurrency conflicts. No Update is issued when the mutation did
// not change data, labels or annotations, keeping the steady state write-free.
func (s *Store) mutateAnchor(ctx context.Context, mutate func(*corev1.ConfigMap) error) error {
	for attempt := 0; attempt < conflictRetries; attempt++ {
		anchor, err := s.getOrCreateAnchor(ctx)
		if err != nil {
			return err
		}
		if anchor.Annotations == nil {
			anchor.Annotations = map[string]string{}
		}
		before := anchor.DeepCopy()
		if err := mutate(anchor); err != nil {
			return err
		}
		if mapsEqual(before.Data, anchor.Data) &&
			mapsEqual(before.Annotations, anchor.Annotations) &&
			mapsEqual(before.Labels, anchor.Labels) {
			return nil
		}
		err = s.client.Update(ctx, anchor)
		if err == nil {
			return nil
		}
		if !apierrors.IsConflict(err) {
			return err
		}
	}
	return fmt.Errorf("anchor ConfigMap update conflicted %d times, giving up", conflictRetries)
}

func mapsEqual(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if b[k] != v {
			return false
		}
	}
	return true
}

func writeFailure(anchor *corev1.ConfigMap, diag *FailureDiagnostic) {
	raw, err := json.Marshal(diag)
	if err != nil {
		return
	}
	if anchor.Annotations == nil {
		anchor.Annotations = map[string]string{}
	}
	anchor.Annotations[AnnLastFailure] = string(raw)
}

// parseTime parses an RFC3339 anchor timestamp; unparseable or empty values
// yield the zero time.
func parseTime(raw string) time.Time {
	if raw == "" {
		return time.Time{}
	}
	parsed, err := time.Parse(time.RFC3339, raw)
	if err != nil {
		return time.Time{}
	}
	return parsed
}

func cloneData(in map[string]string) map[string]string {
	out := make(map[string]string, len(in))
	for k, v := range in {
		out[k] = v
	}
	return out
}
