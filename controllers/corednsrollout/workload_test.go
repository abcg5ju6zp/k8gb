func TestPatchPromotionRestorationRoundtripViaClient(t *testing.T) {
	// TR-5.4: minimal JSON patches applied against live objects are exact
	// inverses; promotion touches only the three deployment fields and the
	// Service selector generation label.
	ctx := context.Background()
	depl, svc := productionFixture()
	cb := fake.NewClientBuilder().WithScheme(testScheme(t)).WithObjects(svc, depl).Build()
	w := NewWorkloads(cb, testNamespace, testScheme(t),
		NewStore(fake.NewClientBuilder().WithScheme(testScheme(t)).Build(), testNamespace), nil)
	wl, err := w.Discover(ctx)
	require.NoError(t, err)
	snap := wl.Capture()

	const fp = "abcdef123456"
	// FR-8 ordered switch: deployment patch happens first, the stable Service
	// selector is only switched after the production rollout completes.
	require.NoError(t, w.PatchDeploymentPromotion(ctx, wl, fp))

	gotSvcEarly := &corev1.Service{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotSvcEarly))
	assert.NotContains(t, gotSvcEarly.Spec.Selector, LabelGeneration, "selector must not switch before rollout")

	require.NoError(t, w.PatchServicePromotion(ctx, wl, fp))

	gotDepl := &appsv1.Deployment{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotDepl))
	assert.Equal(t, GenerationConfigMapName(fp), gotDepl.Spec.Template.Spec.Volumes[0].ConfigMap.Name)
	assert.Equal(t, fp, gotDepl.Spec.Template.Labels[LabelGeneration])
	assert.Equal(t, fp, gotDepl.Spec.Template.Annotations[ChecksumAnnotation])
	// Untouched whitelist-exempt fields survive.
	assert.Equal(t, "keep", gotDepl.Spec.Template.Annotations["existing"])
	assert.Equal(t, "coredns", gotDepl.Spec.Template.Spec.ServiceAccountName)
	gotSvc := &corev1.Service{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotSvc))
	assert.Equal(t, fp, gotSvc.Spec.Selector[LabelGeneration])
	assert.Equal(t, "coredns", gotSvc.Spec.Selector["app.kubernetes.io/name"])

	// Restoring returns every patched field to the captured snapshot.
	require.NoError(t, w.PatchServiceRestoration(ctx, wl, snap))
	require.NoError(t, w.PatchDeploymentRestoration(ctx, wl, snap))
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotDepl))
	require.Len(t, gotDepl.Spec.Template.Spec.Volumes, 2)
	assert.Equal(t, AnchorConfigMapName, gotDepl.Spec.Template.Spec.Volumes[0].ConfigMap.Name)
	assert.Equal(t, "config-volume", gotDepl.Spec.Template.Spec.Volumes[1].Name)
	assert.Equal(t, "k8gb-coredns", gotDepl.Spec.Template.Spec.Volumes[1].ConfigMap.Name)
	assert.Equal(t, depl.Spec.Template.Labels, gotDepl.Spec.Template.Labels)
	assert.Equal(t, depl.Spec.Template.Annotations, gotDepl.Spec.Template.Annotations)
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotSvc))
	assert.Equal(t, svc.Spec.Selector, gotSvc.Spec.Selector)
}

func TestPatchRestorationKeepsPreExistingGenerationLabel(t *testing.T) {
	// When the production template already carried a generation label, the
	// restoration replaces it with the captured value instead of removing it.
	ctx := context.Background()
	depl, svc := productionFixture()
	depl.Spec.Template.Labels[LabelGeneration] = "old1234567890"
	svc.Spec.Selector[LabelGeneration] = "old1234567890"
	cb := fake.NewClientBuilder().WithScheme(testScheme(t)).WithObjects(svc, depl).Build()
	w := NewWorkloads(cb, testNamespace, testScheme(t),
		NewStore(fake.NewClientBuilder().WithScheme(testScheme(t)).Build(), testNamespace), nil)
	wl, err := w.Discover(ctx)
	require.NoError(t, err)
	snap := wl.Capture()

	require.NoError(t, w.PatchDeploymentPromotion(ctx, wl, "new1234567890"))
	require.NoError(t, w.PatchServicePromotion(ctx, wl, "new1234567890"))
	require.NoError(t, w.PatchServiceRestoration(ctx, wl, snap))
	require.NoError(t, w.PatchDeploymentRestoration(ctx, wl, snap))

	gotSvc := &corev1.Service{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotSvc))
	assert.Equal(t, "old1234567890", gotSvc.Spec.Selector[LabelGeneration])
	gotDepl := &appsv1.Deployment{}
	require.NoError(t, cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: "coredns"}, gotDepl))
	assert.Equal(t, "old1234567890", gotDepl.Spec.Template.Labels[LabelGeneration])
}

