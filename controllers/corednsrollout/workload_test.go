func requireDiscoveryError(t *testing.T, err error) *DiscoveryError {
	t.Helper()
	var de *DiscoveryError
	require.Error(t, err)
	require.True(t, AsDiscoveryError(err, &de), "expected DiscoveryError, got %T: %v", err, err)
	return de
}

