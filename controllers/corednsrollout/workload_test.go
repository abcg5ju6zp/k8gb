func TestBuildCanaryWhitelistOnly(t *testing.T) {
	// TR-5.1: canary differs from production only in volume source, generation
	// labels/role, checksum annotation and replica count.
	wl := stableFromFixture(t)
	canary, canarySvc, err := wl.BuildCanary("abcdef123456", newAnchor(nil))
	require.NoError(t, err)

	require.Equal(t, int32(1), *canary.Spec.Replicas)

	// Pod spec identity except the whitelisted volume source.
	expectedSpec := wl.Deployment.Spec.Template.Spec.DeepCopy()
	for i := range expectedSpec.Volumes {
		if expectedSpec.Volumes[i].Name == DynamicZonesVolumeName {
			expectedSpec.Volumes[i].ConfigMap.Name = GenerationConfigMapName("abcdef123456")
		}
	}
	assert.Equal(t, *expectedSpec, canary.Spec.Template.Spec)

	// Labels/annotations: originals retained plus whitelist additions.
	assert.Equal(t, "coredns", canary.Spec.Template.Labels["app.kubernetes.io/name"])
	assert.Equal(t, "abcdef123456", canary.Spec.Template.Labels[LabelGeneration])
	assert.Equal(t, RoleCanary, canary.Spec.Template.Labels[LabelRole])
	assert.Equal(t, "keep", canary.Spec.Template.Annotations["existing"])
	assert.Equal(t, "abcdef123456", canary.Spec.Template.Annotations[ChecksumAnnotation])

	// Canary has its own selector and a clean metadata reset.
	assert.Equal(t, map[string]string{LabelGeneration: "abcdef123456", LabelRole: RoleCanary},
		canary.Spec.Selector.MatchLabels)
	assert.Equal(t, CanaryDeploymentName, canary.Name)
	assert.Empty(t, canary.ResourceVersion)

	// TR-5.2: canary Service is ClusterIP with cloned ports/families and a
	// candidate-only selector.
	assert.Equal(t, corev1.ServiceTypeClusterIP, canarySvc.Spec.Type)
	assert.Equal(t, map[string]string{LabelGeneration: "abcdef123456", LabelRole: RoleCanary}, canarySvc.Spec.Selector)
	require.Len(t, canarySvc.Spec.Ports, 2)
	for i, p := range canarySvc.Spec.Ports {
		original := wl.Service.Spec.Ports[i]
		assert.Equal(t, original.Name, p.Name)
		assert.Equal(t, original.Port, p.Port)
		assert.Equal(t, original.TargetPort, p.TargetPort)
		assert.Equal(t, original.Protocol, p.Protocol)
		assert.Empty(t, p.NodePort)
	}
	assert.Equal(t, []corev1.IPFamily{corev1.IPv4Protocol, corev1.IPv6Protocol}, canarySvc.Spec.IPFamilies)
	require.NotNil(t, canarySvc.Spec.IPFamilyPolicy)
	assert.Equal(t, corev1.IPFamilyPolicyRequireDualStack, *canarySvc.Spec.IPFamilyPolicy)
	assert.Empty(t, canarySvc.Spec.ClusterIP)
}

func TestDiscoverTopology(t *testing.T) {
	ctx := context.Background()
	depl, svc := productionFixture()

	// happy path
	w := workloadFor(t, svc, depl)
	got, err := w.Discover(ctx)
	require.NoError(t, err)
	assert.Equal(t, "coredns", got.Service.Name)
	assert.Equal(t, "coredns", got.Deployment.Name)

	// TR-5.3: zero non-metrics services
	wEmpty := workloadFor(t, func() *corev1.Service {
		metrics := svc.DeepCopy()
		metrics.Name = "coredns-metrics"
		metrics.Labels["app.kubernetes.io/component"] = "metrics"
		return metrics
	}())
	_, err = wEmpty.Discover(ctx)
	require.Error(t, err)
	de := requireDiscoveryError(t, err)
	assert.Equal(t, DiscoveryNoService, de.Reason)

	// TR-5.3: multiple non-metrics services
	second := svc.DeepCopy()
	second.Name = "coredns-extra"
	wTwo := workloadFor(t, svc, second, depl)
	_, err = wTwo.Discover(ctx)
	de = requireDiscoveryError(t, err)
	assert.Equal(t, DiscoveryMultipleServices, de.Reason)

	// TR-5.3: no backing deployment
	wNoDepl := workloadFor(t, svc)
	_, err = wNoDepl.Discover(ctx)
	de = requireDiscoveryError(t, err)
	assert.Equal(t, DiscoveryNoDeployment, de.Reason)

	// TR-5.3: multiple backing deployments
	secondDepl := depl.DeepCopy()
	secondDepl.Name = "coredns-shadow"
	wTwoDepl := workloadFor(t, svc, depl, secondDepl)
	_, err = wTwoDepl.Discover(ctx)
	de = requireDiscoveryError(t, err)
	assert.Equal(t, DiscoveryMultipleDeployment, de.Reason)

	// missing dynamic-zones volume
	noVolume := depl.DeepCopy()
	noVolume.Spec.Template.Spec.Volumes = noVolume.Spec.Template.Spec.Volumes[:1]
	noVolume.Spec.Template.Spec.Volumes[0].Name = "config-volume"
	noVolume.Spec.Template.Spec.Volumes[0].ConfigMap.Name = "k8gb-coredns"
	wNoVol := workloadFor(t, svc, noVolume)
	_, err = wNoVol.Discover(ctx)
	de = requireDiscoveryError(t, err)
	assert.Equal(t, DiscoveryMissingVolume, de.Reason)
}

