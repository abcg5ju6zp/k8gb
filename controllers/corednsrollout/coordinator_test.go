func TestCoordinatorHappyPath(t *testing.T) {
	// TR-8.1: full ordered candidate -> canary -> ready -> probe -> deployment
	// patch -> rollout -> selector switch (addresses not reduced) -> anchor.
	ctx := context.Background()
	h := newCoordHarness(t, []string{"cloud.example.com"}, []string{"10.0.0.1"})
	require.Equal(t, DecisionActive, h.ensure("cloud.example.com").Decision)

	h.addZone("cloud2.example.com")
	desired := desiredZones("cloud.example.com", "cloud2.example.com")

	d := h.ensure("cloud.example.com", "cloud2.example.com")
	require.Equal(t, DecisionProgressing, d.Decision)
	require.Equal(t, RequeueInterval, d.RequeueAfter)
	require.True(t, h.canaryExists())
	state := h.anchorState()
	assert.Equal(t, desired.Fingerprint, state.Candidate)
	assert.Equal(t, PhaseCandidateRolling, state.Phase)

	h.markCanaryReady()
	d = h.ensure("cloud.example.com", "cloud2.example.com")
	require.Equal(t, DecisionProgressing, d.Decision, "production rollout pending after promotion patch")

	// New generation pods now serve; old pods are gone after rollout completed.
	h.markProductionComplete()
	h.seedProductionReadyPods(desired.Fingerprint, "10.1.0.1", "10.1.0.2")

	d = h.ensure("cloud.example.com", "cloud2.example.com")
	require.Equal(t, DecisionActive, d.Decision, d.Reason)

	// Anchor active + mirrored data; stable Service selects the new generation.
	state = h.anchorState()
	assert.Equal(t, desired.Fingerprint, state.Active)
	assert.Empty(t, state.Candidate)
	anchor, err := NewStore(h.cb, testNamespace).GetAnchor(ctx)
	require.NoError(t, err)
	assert.Equal(t, desired.Data, anchor.Data)
	svc := h.getService()
	assert.Equal(t, desired.Fingerprint, svc.Spec.Selector[LabelGeneration])
	assert.False(t, h.canaryExists())

	// Previous gen-0 is GC'd only after the new steady state is reached; new
	// generation ConfigMap retained and mounted.
	err = h.cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: GenerationConfigMapName(desired.Fingerprint)}, &corev1.ConfigMap{})
	require.NoError(t, err)
	oldFP := desiredZones("cloud.example.com").Fingerprint
	err = h.cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: GenerationConfigMapName(oldFP)}, &corev1.ConfigMap{})
	assert.True(t, apierrors.IsNotFound(err))
}

