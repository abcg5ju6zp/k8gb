func TestCoordinatorCanaryTimeoutQuarantines(t *testing.T) {
	// TR-6.1/TR-8.2: canary timeout scales it to zero, quarantines the
	// candidate and leaves production and last-known-good untouched.
	ctx := context.Background()
	h := newCoordHarness(t, []string{"cloud.example.com"}, []string{"10.0.0.1"})
	require.Equal(t, DecisionActive, h.ensure("cloud.example.com").Decision)
	activeData := cloneStringMap(h.anchorDataSnapshot())

	h.addZone("cloud2.example.com")
	names := []string{"cloud.example.com", "cloud2.example.com"}
	require.Equal(t, DecisionProgressing, h.ensure(names...).Decision)

	// Time advances past the canary deadline; pod never ready.
	h.clock.now = h.start.Add(testCanaryTimeout + time.Second)
	d := h.ensure(names...)
	require.Equal(t, DecisionFailed, d.Decision)

	canary := h.getDeployment(CanaryDeploymentName)
	require.NotNil(t, canary.Spec.Replicas)
	assert.Equal(t, int32(0), *canary.Spec.Replicas)
	state := h.anchorState()
	assert.Equal(t, PhaseQuarantined, state.Phase)
	require.NotNil(t, state.LastFailure)
	assert.Equal(t, ReasonCanaryNotReady, state.LastFailure.Reason)

	// Last-known-good bytes and production selection unchanged.
	assert.Equal(t, activeData, h.anchorDataSnapshot())
	prod := h.getDeployment("coredns")
	assert.Equal(t, AnchorConfigMapName, prod.Spec.Template.Spec.Volumes[0].ConfigMap.Name)
	assert.NotContains(t, h.getService().Spec.Selector, LabelGeneration)

	// Retrying identical content stays Failed (terminal quarantine).
	d = h.ensure(names...)
	assert.Equal(t, DecisionFailed, d.Decision)
	_ = ctx
}

