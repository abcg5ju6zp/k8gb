// seedProductionReadyPods places ready pods backing the stable Service.
// generation selects the zd-generation label the pods carry ("" = old gen).
func (h *coordHarness) seedProductionReadyPods(generation string, ips ...string) {
	for i, ip := range ips {
		pod := &corev1.Pod{
			ObjectMeta: metav1.ObjectMeta{
				Name:      fmt.Sprintf("coredns-%s-%d", orGen(generation, "old"), i),
				Namespace: testNamespace,
				Labels:    map[string]string{"app.kubernetes.io/name": "coredns"},
			},
			Status: corev1.PodStatus{
				PodIP:      ip,
				PodIPs:     []corev1.PodIP{{IP: ip}},
				Conditions: []corev1.PodCondition{{Type: corev1.PodReady, Status: corev1.ConditionTrue}},
			},
		}
		if generation != "" {
			pod.Labels[LabelGeneration] = generation
		}
		require.NoError(h.t, h.cb.Create(context.Background(), pod))
	}
}

