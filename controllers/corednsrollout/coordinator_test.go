func TestCoordinatorGarbageCollection(t *testing.T) {
	// TR-8.5: referenced and retained-quarantined generations survive GC;
	// unreferenced ones are deleted; unmanaged ConfigMaps are untouched.
	ctx := context.Background()
	activeFP := "aaaaaaaaaaaa"
	makeGen := func(name, fp, quarantineReason string) *corev1.ConfigMap {
		cm := &corev1.ConfigMap{
			ObjectMeta: metav1.ObjectMeta{
				Name:        name,
				Namespace:   testNamespace,
				Labels:      map[string]string{LabelManagedBy: ManagedByValue, LabelRole: RoleGeneration, LabelGeneration: fp},
				Annotations: map[string]string{AnnFingerprint: fp},
			},
			Data:      map[string]string{name + ".conf": "x"},
			Immutable: ptrBool(true),
		}
		if quarantineReason != "" {
			cm.Labels[LabelQuarantine] = quarantineReason
			cm.Annotations[AnnQuarantineReason] = quarantineReason
			cm.Annotations[AnnQuarantinedAt] = "2026-10-10T0" + name[len(name)-1:] + ":00:00Z"
		}
		return cm
	}

	anchor := newAnchor(map[string]string{})
	anchor.Annotations[AnnActiveGeneration] = activeFP
	anchor.Annotations[AnnCandidatePhase] = string(PhaseActive)
	depl, svc := productionFixture()
	svc.Spec.Selector[LabelGeneration] = activeFP
	referenced := makeGen(GenerationConfigMapName("bbbbbbbbbbbb"), "bbbbbbbbbbbb", "") // canary-referenced below
	canary := &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: CanaryDeploymentName, Namespace: testNamespace},
		Spec: appsv1.DeploymentSpec{
			Template: corev1.PodTemplateSpec{ObjectMeta: metav1.ObjectMeta{
				Labels: map[string]string{LabelGeneration: "bbbbbbbbbbbb", LabelRole: RoleCanary},
			}},
		},
	}
	objs := []client.Object{
		anchor, depl, svc,
		makeGen(GenerationConfigMapName(activeFP), activeFP, ""),
		referenced, canary,
		makeGen(GenerationConfigMapName("c1cccccccccc"), "c1cccccccccc", ReasonProbeFailed),
		makeGen(GenerationConfigMapName("c2cccccccccc"), "c2cccccccccc", ReasonProbeFailed),
		makeGen(GenerationConfigMapName("c3cccccccccc"), "c3cccccccccc", ReasonProbeFailed),
		makeGen(GenerationConfigMapName("c4cccccccccc"), "c4cccccccccc", ReasonProbeFailed),
		// Unrelated unmanaged ConfigMap must never be touched.
		&corev1.ConfigMap{ObjectMeta: metav1.ObjectMeta{Name: "someone-elses", Namespace: testNamespace}, Data: map[string]string{"k": "v"}},
	}
	cb := fake.NewClientBuilder().WithScheme(testScheme(t)).WithObjects(objs...).Build()
	coord := NewCoordinator(cb, testScheme(t), testSettings(),
		func(v1beta1io.ZoneDelegation) string { return "" },
		func(context.Context) ([]string, error) { return nil, nil },
		&mutableQuerier{fn: func(*dns.Msg, string) (*dns.Msg, error) { return nil, nil }}, nil, nil)

	wl, err := NewWorkloads(cb, testNamespace, testScheme(t), NewStore(cb, testNamespace), nil).Discover(ctx)
	require.NoError(t, err)
	require.NoError(t, coord.garbageCollect(ctx, wl, State(anchor)))

	exists := func(name string) bool {
		return cb.Get(ctx, client.ObjectKey{Namespace: testNamespace, Name: name}, &corev1.ConfigMap{}) == nil
	}
	assert.True(t, exists(GenerationConfigMapName(activeFP)), "active retained")
	assert.True(t, exists(GenerationConfigMapName("bbbbbbbbbbbb")), "canary-referenced retained")
	// Quarantine retention is 3; c4 (oldest timestamp) is removed.
	assert.True(t, exists(GenerationConfigMapName("c1cccccccccc")))
	assert.True(t, exists(GenerationConfigMapName("c2cccccccccc")))
	assert.True(t, exists(GenerationConfigMapName("c3cccccccccc")))
	assert.False(t, exists(GenerationConfigMapName("c4cccccccccc")), "oldest quarantined beyond N deleted")
	assert.True(t, exists("someone-elses"), "unmanaged ConfigMap untouched")
}

