type mutClock struct{ now time.Time }

func (c *mutClock) Now() time.Time { return c.now }

// mutableQuerier allows swapping DNS behavior mid-test.
type mutableQuerier struct {
	fn func(msg *dns.Msg, server string) (*dns.Msg, error)
}

func (q *mutableQuerier) Exchange(msg *dns.Msg, server string) (*dns.Msg, error) {
	return q.fn(msg, server)
}

