func validData(zones ...string) map[string]string {
	list := &v1beta1io.ZoneDelegationList{}
	for _, z := range zones {
		list.Items = append(list.Items, zoneDelegation(z))
	}
	return Normalize(list).Data
}

func TestValidatePositive(t *testing.T) {
	// TR-3.1: current template product passes.
	assert.NoError(t, Validate(validData("cloud.example.com")))

	// TR-3.1: multiple zones pass.
	assert.NoError(t, Validate(validData("cloud.example.com", "cloud2.example.com", "a.b.cloud.example.com")))

	// TR-3.1: comments and blank lines pass.
	assert.NoError(t, Validate(map[string]string{
		"cloud-example-com.conf": "# top comment\n\ncloud.example.com:5353 { # inline comment\n  import k8gbplugins # trailing comment\n}\n",
	}))
}

func TestValidateEmpty(t *testing.T) {
	assert.NoError(t, Validate(map[string]string{}))
}

func TestValidateNegative(t *testing.T) {
	// TR-3.1: each negative example is rejected with a ValidationError that
	// names the affected zone whenever a zone token is available.
	tests := []struct {
		name         string
		data         map[string]string
		expectedFile string
	}{
		{
			name:         "unbalanced braces",
			data:         map[string]string{"cloud-example-com.conf": "cloud.example.com:5353 {\n  import k8gbplugins\n"},
			expectedFile: "cloud-example-com.conf",
		},
		{
			name:         "invalid zone character",
			data:         map[string]string{"cloud_example-com.conf": "cloud_example.com:5353 {\n  import k8gbplugins\n}\n"},
			expectedFile: "cloud_example-com.conf",
		},
		{
			name: "duplicate server block in one file",
			data: map[string]string{
				"cloud-example-com.conf": "cloud.example.com:5353 {\n  import k8gbplugins\n}\ncloud.example.com:5353 {\n  import k8gbplugins\n}\n",
			},
			expectedFile: "cloud-example-com.conf",
		},
		{
			name:         "port zero",
			data:         map[string]string{"cloud-example-com.conf": "cloud.example.com:0 {\n  import k8gbplugins\n}\n"},
			expectedFile: "cloud-example-com.conf",
		},
		{
			name:         "port out of range",
			data:         map[string]string{"cloud-example-com.conf": "cloud.example.com:70000 {\n  import k8gbplugins\n}\n"},
			expectedFile: "cloud-example-com.conf",
		},
		{
			name:         "unknown plugin line",
			data:         map[string]string{"cloud-example-com.conf": "cloud.example.com:5353 {\n  whoami\n}\n"},
			expectedFile: "cloud-example-com.conf",
		},
		{
			name:         "empty zone file",
			data:         map[string]string{"cloud-example-com.conf": ""},
			expectedFile: "cloud-example-com.conf",
		},
		{
			name:         "content after closing brace",
			data:         map[string]string{"cloud-example-com.conf": "cloud.example.com:5353 {\n  import k8gbplugins\n}\nextra\n"},
			expectedFile: "cloud-example-com.conf",
		},
		{
			name:         "file name does not match zone",
			data:         map[string]string{"other-name.conf": "cloud.example.com:5353 {\n  import k8gbplugins\n}\n"},
			expectedFile: "other-name.conf",
		},
		{
			name:         "nested block",
			data:         map[string]string{"cloud-example-com.conf": "cloud.example.com:5353 {\n  import k8gbplugins\n  k8s_crd {\n  }\n}\n"},
			expectedFile: "cloud-example-com.conf",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := Validate(tt.data)
			var verr *ValidationError
			assert.ErrorAs(t, err, &verr)
			assert.NotEmpty(t, verr.Reason)
			assert.Equal(t, tt.expectedFile, verr.File)
			assert.Contains(t, err.Error(), tt.expectedFile)
		})
	}
}

func TestValidateRejectsDuplicateZoneTokens(t *testing.T) {
	// TR-3.1: a zone token whose file key is inconsistent with it is rejected
	// before it could alias another file's zone.
	zone, verr := validateZoneFile("cloud-example-com-x.conf", "cloud.example.com:5353 {\n  import k8gbplugins\n}\n")
	assert.Equal(t, "cloud.example.com", zone)
	if assert.NotNil(t, verr) {
		assert.Equal(t, "cloud-example-com-x.conf", verr.File)
		assert.Contains(t, verr.Reason, "does not match zone token")
	}
}
