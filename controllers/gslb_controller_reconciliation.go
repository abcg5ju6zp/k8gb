// GslbReconciler reconciles a Gslb object
type GslbReconciler struct {
	client.Client
	Scheme             *runtime.Scheme
	Config             *resolver.Config
	Resolver           resolver.GslbResolver
	DNSProvider        dns.Provider
	Recorder           record.EventRecorder
	Tracer             trace.Tracer
	ZoneService        zones.ZoneDelegation
	GslbIngressHandler Handler
	// Ownership arbitrates per-hostname ownership so only the single recorded
	// owner Gslb publishes DNS results. When nil, legacy single-writer behavior
	// is preserved.
	Ownership *ownership.Manager
	Logger    *zerolog.Logger
}

const (
	primaryGeoTagAnnotation = "k8gb.io/primary-geotag"
	strategyAnnotation      = "k8gb.io/strategy"
	dnsTTLSecondsAnnotation = "k8gb.io/dns-ttl-seconds"
)

var k8gbAnnotations = []string{strategyAnnotation, primaryGeoTagAnnotation, dnsTTLSecondsAnnotation}

var m = metrics.Metrics()

// +kubebuilder:rbac:groups=k8gb.io,resources=gslbs,verbs=get;list;watch;create;update;patch;delete
// +kubebuilder:rbac:groups=k8gb.io,resources=gslbs/status,verbs=get;update;patch
// +kubebuilder:rbac:groups=k8gb.io,resources=gslbs/finalizers,verbs=update
// +kubebuilder:rbac:groups=k8gb.io,resources=hostnameownerships,verbs=get;list;watch;create;update;patch;delete
// +kubebuilder:rbac:groups="",resources=events,verbs=create;patch

// Reconcile runs main reconciliation loop
func (r *GslbReconciler) Reconcile(ctx context.Context, req ctrl.Request) (ctrl.Result, error) {
	ctx, span := r.Tracer.Start(ctx, "Reconcile")
	defer span.End()

	result := utils.NewReconcileResultHandler(r.Config.ReconcileRequeueSeconds, r.Config.ReconcileRequeueSeconds)
	// Check that cluster provides available IPs. Without IP's I'm skipping GSLB reconciliation
	if !r.ZoneService.HasAvailableIPs(ctx) {
		r.Logger.Info().
			Str("name", req.Name).
			Str("namespace", req.Namespace).
			Msg("Waiting for available IPs. Skipping GSLB reconciliation")
		return result.Requeue()
	}

	// Fetch the Gslb instance
	gslb := &k8gbv1beta1io.Gslb{}
	err := r.Get(ctx, req.NamespacedName, gslb)
	if err != nil {
		if k8serrors.IsNotFound(err) {
			// Request object not found, could have been deleted after reconcile request.
			// Owned objects are automatically garbage collected. For additional cleanup logic use finalizers.
			// Return and don't requeue
			return result.Stop()
		}
		m.IncrementError(gslb)
		return result.RequeueError(fmt.Errorf("error reading the object (%s)", err))
	}

	// Deleting Gslbs only run hostname ownership handoff; their computed
	// DNSEndpoint must keep serving until the successor publication is
	// confirmed, so the finalizer blocks garbage collection until then.
	if gslb.DeletionTimestamp != nil {
		return r.reconcileGslbDeletion(ctx, gslb, result)
	}

	err = r.Resolver.ResolveGslbSpec(ctx, gslb, r.Client)
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(fmt.Errorf("resolving spec (%s)", err))
	}
	r.Logger.Debug().
		Str("gslb", gslb.Name).
		Str("namespace", gslb.Namespace).
		Str("strategy", gslb.Spec.Strategy.Type).
		Msg("Resolved strategy")

	// == Ingress ==========
	// Only create embedded Ingress if ResourceRef is empty (embedded mode)
	if reflect.DeepEqual(gslb.Spec.ResourceRef, k8gbv1beta1io.ResourceRef{}) {
		ingress, err := r.createIngressFromGslb(gslb)
		if err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}

		err = r.saveDependentIngress(ctx, gslb, ingress)
		if err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
	}

	// == Reference resolution ==
	refResolver, err := refresolver.New(gslb, r.Client)
	if err != nil {
		m.IncrementError(gslb)
		errorMsg := fmt.Sprintf("error resolving references (%s)", err)
		r.Recorder.Event(gslb, corev1.EventTypeWarning, "ReconcileError", errorMsg)
		return result.RequeueError(errors.New(errorMsg))
	}
	servers, err := refResolver.GetServers()
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(fmt.Errorf("getting GSLB servers (%s)", err))
	}

	list, err := r.ZoneService.List(ctx)
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(fmt.Errorf("getting delegation zones (%s)", err))
	}
	filteredServers := filterServersByZoneDelegations(servers, list)

	if len(filteredServers) == 0 {
		r.Logger.
			Info().
			Str("gslb", gslb.Name).
			Str("namespace", gslb.Namespace).
			Strs("server hosts", listHosts(servers)).
			Msgf("Skipping reconciliation: ZoneDelegation is not present or Status is empty")
		return result.Requeue()
	}

	gslb.Status.Servers = filteredServers

	loadBalancerExposedIPs, err := refresolver.ResolveGslbExposedIPs(
		refResolver, gslb.Annotations, r.Config.ClusterExposedIPs, r.Config.ParentZoneDNSServers)
	if err != nil {
		m.IncrementError(gslb)
		errorMsg := fmt.Sprintf("getting load balancer exposed IPs (%s)", err)
		r.Recorder.Event(gslb, corev1.EventTypeWarning, "ExposedIPResolutionError", errorMsg)
		return result.RequeueError(errors.New(errorMsg))
	}
	lbIpv4Addresses, _ := splitIPsByVersion(r.Logger, loadBalancerExposedIPs)
	gslb.Status.LoadBalancer.ExposedIPs = lbIpv4Addresses

	r.Logger.Debug().
		Str("gslb", gslb.Name).
		Msg("Resolved LoadBalancer and Server configuration referenced by Ingress")

	// == health status of applications ==
	serviceHealth, err := r.getServiceHealthStatus(ctx, gslb)
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}
	gslb.Status.ServiceHealth = serviceHealth

	// == external-dns dnsendpoints CRs ==
	_, s := r.Tracer.Start(context.Background(), "gslbDNSEndpoint")
	epProvider := k8gbendpoint.NewApplicationDNSEndpoint(
		context.TODO(),
		r.Client,
		r.Config,
		gslb,
		r.Logger,
		utils.NewDNSQueryService(),
		r.ZoneService,
		r.updateRuntimeStatus)
	dnsEndpoint, err := epProvider.GetDNSEndpoint()
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}
	s.End()

	// Keep the Gslb alive while hostname ownership may need to be handed over
	// on deletion.
	if err = r.ensureHostnameFinalizer(ctx, gslb); err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}

	// == per-hostname ownership arbitration ==
	// Every declared hostname participates, even when its computed record set
	// is currently empty.
	digests := ownership.HostDigests(dnsEndpoint.Spec.Endpoints)
	claimedHosts := ownership.ClaimedHosts(gslb)
	for host := range claimedHosts {
		if _, exists := digests[host]; !exists {
			digests[host] = ""
		}
	}
	var decision *ownership.Decision
	if r.Ownership != nil {
		decision, err = r.Ownership.ReconcileHosts(ctx, gslb, digests)
		if err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(fmt.Errorf("arbitrating hostname ownership: %w", err))
		}
	} else {
		decision = ownership.AllowAllDecision(claimedHosts)
	}
	applyOwnershipConditions(gslb, decision)

	// The intended records reflect the full computation and feed status and
	// metrics regardless of what is actually published.
	intendedEndpoint := dnsEndpoint.DeepCopy()
	publishedRecords, withheldRecords := ownership.PartitionEndpoints(dnsEndpoint.Spec.Endpoints, decision.Owners)

	// Only the recorded owner may publish; a Gslb owning none of its hostnames
	// drops its public DNSEndpoint so it cannot overwrite external records.
	_, s = r.Tracer.Start(ctx, "SaveDNSEndpoint")
	var publishedEndpoint *externaldnsApi.DNSEndpoint
	if len(publishedRecords) > 0 {
		dnsEndpoint.Spec.Endpoints = publishedRecords
		if err = controllerutil.SetControllerReference(gslb, dnsEndpoint, r.Scheme); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
		if err = epProvider.SaveDNSEndpoint(dnsEndpoint); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
		publishedEndpoint = dnsEndpoint
	} else {
		if err = epProvider.RemoveEndpoint(); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
	}
	s.End()

	// Conflicting hostnames keep their computed records in a secondary,
	// non-selected DNSEndpoint instead of rewriting external records.
	_, s = r.Tracer.Start(ctx, "SaveWithheldDNSEndpoint")
	if len(withheldRecords) > 0 {
		withheldEndpoint := epProvider.NewWithheldEndpoint(withheldRecords, conflictOwnerRefs(decision))
		if err = controllerutil.SetControllerReference(gslb, withheldEndpoint, r.Scheme); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
		if err = epProvider.SaveEndpoint(withheldEndpoint); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
	} else {
		if err = epProvider.RemoveEndpointByName(epProvider.WithheldEndpointName()); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
	}
	s.End()

	// == Status =
	err = r.updateGslbStatus(ctx, gslb, intendedEndpoint, publishedEndpoint)
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}

	// == Finish ==========
	// Everything went fine, requeue after some time to catch up
	// with external Gslb status
	// TODO: potentially enhance with smarter reaction to external Event
	m.IncrementReconciliation(gslb)
	return result.Requeue()
}

// splitIPsByVersion splits a list of IP addresses into IPv4 and IPv6 addresses
func splitIPsByVersion(logger *zerolog.Logger, ips []string) ([]string, []string) {
	ipv4Addresses := []string{}
	ipv6Addresses := []string{}
	for _, ip := range ips {
		parsedIP := net.ParseIP(ip)
		if parsedIP == nil {
			logger.Warn().Str("ip", ip).Msg("Invalid IP address")
			continue
		}
		if parsedIP.To4() == nil {
			// cannot be parsed as IPv4, must be IPv6
			ipv6Addresses = append(ipv6Addresses, ip)
		} else {
			ipv4Addresses = append(ipv4Addresses, ip)
		}
	}
	return ipv4Addresses, ipv6Addresses
}

// filterServersByZoneDelegations filters servers to only include those with hosts that match the delegation zones
func filterServersByZoneDelegations(
	servers []*k8gbv1beta1io.Server,
	zoneDelegations *k8gbv1beta1io.ZoneDelegationList) []*k8gbv1beta1io.Server {
	var filtered []*k8gbv1beta1io.Server
	for _, server := range servers {
		if zoneDelegations.ContainsZone(server.Host) {
			filtered = append(filtered, server)
		}
	}
	return filtered
}

func listHosts(servers []*k8gbv1beta1io.Server) []string {
	hosts := []string{}
	for _, server := range servers {
		hosts = append(hosts, server.Host)
	}
	return hosts
}
