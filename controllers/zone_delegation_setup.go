// Namespace-scoped RBAC used by the safe CoreDNS generation rollout. The
// verb sets below must stay in sync with chart/k8gb/templates/role.yaml
// (TR-10.2): anchor/generation ConfigMaps, production and canary CoreDNS
// Deployments/Services, ready Pod projection for capacity checks and
// rollout Events. No cluster-wide grants are added for the rollout.
//
// +kubebuilder:rbac:groups="",resources=configmaps,verbs=get;list;watch;create;update;patch;delete
// +kubebuilder:rbac:groups=apps,resources=deployments,verbs=get;list;watch;create;update;patch;delete
// +kubebuilder:rbac:groups="",resources=services,verbs=get;list;watch;create;update;patch;delete
// +kubebuilder:rbac:groups="",resources=pods,verbs=list;watch
// +kubebuilder:rbac:groups="",resources=events,verbs=create;patch
func (r *ZoneDelegationReconciler) SetupWithManager(mgr ctrl.Manager) error {
	blder := ctrl.NewControllerManagedBy(mgr).
		Named("zone-delegation").
		For(&v1beta1io.ZoneDelegation{})

	// Rollout resource events drive immediate reconciliation; the fixed
	// RequeueAfter remains the non-blocking polling backstop. All rollout
	// watches use the namespace-scoped rollout cache.
	if r.RolloutCache != nil {
		enqueueAll := handler.EnqueueRequestsFromMapFunc(r.enqueueAllZoneDelegations)
		blder.
			WatchesRawSource(source.Kind[client.Object](
				r.RolloutCache, &corev1.ConfigMap{}, enqueueAll, rolloutAnchorOrGenerationPredicate())).
			WatchesRawSource(source.Kind[client.Object](
				r.RolloutCache, &appsv1.Deployment{}, enqueueAll, coreDNSWorkloadPredicate())).
			WatchesRawSource(source.Kind[client.Object](
				r.RolloutCache, &corev1.Service{}, enqueueAll, coreDNSWorkloadPredicate())).
			WatchesRawSource(source.Kind[client.Object](
				r.RolloutCache, &corev1.Pod{}, enqueueAll, canaryPodPredicate()))
	}
	return blder.Complete(r)
}

// enqueueAllZoneDelegations maps every rollout resource event to a
// reconciliation of every ZoneDelegation in the cluster.
func (r *ZoneDelegationReconciler) enqueueAllZoneDelegations(ctx context.Context, _ client.Object) []reconcile.Request {
	list := &v1beta1io.ZoneDelegationList{}
	if err := r.List(ctx, list); err != nil {
		return nil
	}
	requests := make([]reconcile.Request, 0, len(list.Items))
	for i := range list.Items {
		requests = append(requests, reconcile.Request{
			NamespacedName: types.NamespacedName{Name: list.Items[i].Name},
		})
	}
	return requests
}

// objectMatcher reports whether an object event is relevant to the rollout.
type objectMatcher func(obj client.Object) bool

func predicateFor(matches objectMatcher) predicate.Funcs {
	return predicate.Funcs{
		CreateFunc:  func(e event.CreateEvent) bool { return matches(e.Object) },
		UpdateFunc:  func(e event.UpdateEvent) bool { return matches(e.ObjectNew) },
		DeleteFunc:  func(e event.DeleteEvent) bool { return matches(e.Object) },
		GenericFunc: func(e event.GenericEvent) bool { return matches(e.Object) },
	}
}

func rolloutAnchorOrGenerationPredicate() predicate.Predicate {
	return predicateFor(func(obj client.Object) bool {
		if obj.GetName() == corednsrollout.AnchorConfigMapName {
			return true
		}
		return obj.GetLabels()[corednsrollout.LabelManagedBy] == corednsrollout.ManagedByValue
	})
}

func coreDNSWorkloadPredicate() predicate.Predicate {
	return predicateFor(func(obj client.Object) bool {
		if obj.GetLabels()[assistant.CoreDNSServiceLabelName] == assistant.CoreDNSServiceLabelValue {
			return true
		}
		return obj.GetLabels()[corednsrollout.LabelManagedBy] == corednsrollout.ManagedByValue
	})
}

func canaryPodPredicate() predicate.Predicate {
	return predicateFor(func(obj client.Object) bool {
		return obj.GetLabels()[corednsrollout.LabelRole] == corednsrollout.RoleCanary
	})
}
