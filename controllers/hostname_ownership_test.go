func testScheme(t *testing.T) *runtime.Scheme {
	t.Helper()
	s := runtime.NewScheme()
	utilruntime.Must(k8gbv1beta1io.AddToScheme(s))
	return s
}

func deletingGslb() *k8gbv1beta1io.Gslb {
	return &k8gbv1beta1io.Gslb{
		ObjectMeta: metav1.ObjectMeta{
			Name:              "g",
			Namespace:         "ns",
			UID:               "uid-g",
			DeletionTimestamp: &metav1.Time{Time: metav1.Now().Time},
			Finalizers:        []string{gslbHostnameFinalizer},
		},
	}
}

func TestDeletionWithoutOwnershipManagerRemovesFinalizer(t *testing.T) {
	gslb := deletingGslb()
	c := fake.NewClientBuilder().WithScheme(testScheme(t)).WithObjects(gslb).Build()
	log := logging.Logger()
	cleanup, tracer := tracing.SetupTracing(context.Background(), tracing.Settings{}, log)
	defer cleanup()

	r := &GslbReconciler{
		Client: c,
		Config: &resolver.Config{ReconcileRequeueSeconds: 0},
		Tracer: tracer,
		Logger: log,
	}
	result := utils.NewReconcileResultHandler(0, 0)
	_, err := r.reconcileGslbDeletion(context.Background(), gslb, result)
	require.NoError(t, err)

	// with the last finalizer gone and a deletion timestamp set, the API
	// object is finalized and removed
	updated := &k8gbv1beta1io.Gslb{}
	err = c.Get(context.Background(), types.NamespacedName{Name: "g", Namespace: "ns"}, updated)
	assert.True(t, apierrors.IsNotFound(err), "expected finalized object to be gone, got %v", err)
}

func TestCleanupOnlyRetriesFromFreshObject(t *testing.T) {
	gslb := deletingGslb()
	c := fake.NewClientBuilder().WithScheme(testScheme(t)).WithObjects(gslb).Build()
	log := logging.Logger()
	r := &GslbReconciler{Client: c, Logger: log}

	require.NoError(t, r.removeHostnameFinalizerCleanupOnly(context.Background(), gslb))
	updated := &k8gbv1beta1io.Gslb{}
	err := c.Get(context.Background(), types.NamespacedName{Name: "g", Namespace: "ns"}, updated)
	assert.True(t, apierrors.IsNotFound(err))
}

func TestApplyOwnershipConditions(t *testing.T) {
	gslb := &k8gbv1beta1io.Gslb{ObjectMeta: metav1.ObjectMeta{Generation: 3}}

	applyOwnershipConditions(gslb, &ownership.Decision{
		Owners: map[string]bool{"a.example.com": true},
		Conflicts: map[string]k8gbv1beta1io.HostnameClaimant{
			"b.example.com": {Name: "owner", Namespace: "other"},
		},
		Handoff: map[string]bool{"a.example.com": true},
	})

	conflict := meta.FindStatusCondition(gslb.Status.Conditions, ownership.ConditionConflict)
	require.NotNil(t, conflict)
	assert.Equal(t, metav1.ConditionTrue, conflict.Status)
	assert.Equal(t, ownership.ReasonConflicting, conflict.Reason)
	assert.Contains(t, conflict.Message, "b.example.com owned by other/owner")
	assert.Equal(t, int64(3), conflict.ObservedGeneration)

	handoff := meta.FindStatusCondition(gslb.Status.Conditions, ownership.ConditionHandoff)
	require.NotNil(t, handoff)
	assert.Equal(t, metav1.ConditionTrue, handoff.Status)

	// clears once conflicts resolve
	applyOwnershipConditions(gslb, ownership.AllowAllDecision(map[string]bool{"a.example.com": true, "b.example.com": true}))
	conflict = meta.FindStatusCondition(gslb.Status.Conditions, ownership.ConditionConflict)
	require.NotNil(t, conflict)
	assert.Equal(t, metav1.ConditionFalse, conflict.Status)
}

func TestConflictOwnerRefsDeduplicated(t *testing.T) {
	decision := &ownership.Decision{
		Owners: map[string]bool{},
		Conflicts: map[string]k8gbv1beta1io.HostnameClaimant{
			"a.example.com": {Name: "o", Namespace: "n"},
			"b.example.com": {Name: "o", Namespace: "n"},
			"c.example.com": {Name: "p", Namespace: "n"},
			"d.example.com": {},
		},
		Handoff: map[string]bool{},
	}
	assert.Equal(t, []string{"n/o", "n/p"}, conflictOwnerRefs(decision))
}
