const (
	embeddedResourceRefAPIVersion = "networking.k8s.io/v1"
	embeddedResourceRefKind       = "Ingress"

	eventResourceRefHandoffStarted   = "ResourceRefHandoffStarted"
	eventResourceRefHandoffPending   = "ResourceRefHandoffPendingTakeover"
	eventResourceRefHandoffDiscarded = "ResourceRefHandoffDiscarded"
	eventResourceRefHandoffCompleted = "ResourceRefHandoffCompleted"
)

// errStaleHandoffGeneration is returned by the generation fence when another
// reconciliation advancing a newer Gslb generation is in progress. It never
// reaches the user as an error: the stale reconciliation stops without any
// write and requeues.
var errStaleHandoffGeneration = errors.New("stale Gslb generation, skipping DNSEndpoint writes")

// desiredResourceRefIdentity returns the coordinates the spec currently points
// at. An embedded Ingress is represented by its stable coordinates so that the
// embedded/referenced Ingress transition does not open a handoff.
func desiredResourceRefIdentity(gslb *k8gbv1beta1io.Gslb) k8gbv1beta1io.ResourceRefIdentity {
	if isEmbeddedResourceRef(gslb) {
		return k8gbv1beta1io.ResourceRefIdentity{
			APIVersion: embeddedResourceRefAPIVersion,
			Kind:       embeddedResourceRefKind,
			Name:       gslb.Name,
		}
	}
	identity := k8gbv1beta1io.ResourceRefIdentity{
		APIVersion: gslb.Spec.ResourceRef.APIVersion,
		Kind:       gslb.Spec.ResourceRef.Kind,
		Name:       gslb.Spec.ResourceRef.Name,
	}
	if selector := selectorIdentity(&gslb.Spec.ResourceRef); selector != "" {
		identity.Selector = selector
	}
	return identity
}

func isEmbeddedResourceRef(gslb *k8gbv1beta1io.Gslb) bool {
	return reflect.DeepEqual(gslb.Spec.ResourceRef, k8gbv1beta1io.ResourceRef{})
}

func selectorIdentity(ref *k8gbv1beta1io.ResourceRef) string {
	if ref == nil {
		return ""
	}
	if ref.MatchLabels == nil && ref.MatchExpressions == nil {
		return ""
	}
	selector, err := metav1.LabelSelectorAsSelector(&ref.LabelSelector)
	if err != nil {
		return ""
	}
	return selector.String()
}

// refCoordinatesEqual compares the switch-relevant coordinates. The UID is
// intentionally excluded: deleting/recreating the referenced object without
// changing the spec does not start a new handoff, its UID is pinned only for
// the duration of an ongoing handoff.
func refCoordinatesEqual(a, b k8gbv1beta1io.ResourceRefIdentity) bool {
	return a.APIVersion == b.APIVersion &&
		a.Kind == b.Kind &&
		a.Name == b.Name &&
		a.Selector == b.Selector
}

func pinnedHosts(gslb *k8gbv1beta1io.Gslb) []string {
	hosts := make([]string, 0, len(gslb.Status.Servers))
	seen := map[string]bool{}
	for _, server := range gslb.Status.Servers {
		if server == nil || server.Host == "" || seen[server.Host] {
			continue
		}
		seen[server.Host] = true
		hosts = append(hosts, server.Host)
	}
	if len(hosts) > 0 {
		return hosts
	}
	// fall back to the last published host list if status servers were not populated yet
	for _, host := range strings.Split(gslb.Status.Hosts, ",") {
		host = strings.TrimSpace(host)
		if host == "" || seen[host] {
			continue
		}
		seen[host] = true
		hosts = append(hosts, host)
	}
	return hosts
}

// initOrGetResourceRefHandoff detects ResourceRef switches and establishes the
// pinned ownership handoff generation. It never recomputes hostnames: the
// pinned set, the last usable health inputs and the frozen DNSEndpoint content
// all come from the previous owner generation.
func (r *GslbReconciler) initOrGetResourceRefHandoff(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
) (*k8gbv1beta1io.ResourceRefHandoff, error) {
	desired := desiredResourceRefIdentity(gslb)

	if h := gslb.Status.ResourceRefHandoff; h != nil {
		switch {
		case !refCoordinatesEqual(h.To, desired):
			// spec switched again while the handoff was in flight: the new
			// candidate becomes the target, but the old owner (From) and its
			// frozen result remain authoritative until the newest generation
			// validates.
			h.To = desired
			h.To.UID = ""
			h.Generation = gslb.Generation
			h.Receipt = nil
			h.Reason = ""
			resetHostStates(h, k8gbv1beta1io.HostHandoffPendingTakeover)
			if err := r.Status().Update(ctx, gslb); err != nil {
				return nil, err
			}
			r.recordEvent(gslb, corev1.EventTypeNormal, eventResourceRefHandoffStarted,
				"ResourceRef handoff %s/%s re-targeted to %s %s at generation %d",
				gslb.Namespace, gslb.Name, desired.Kind, refDisplayName(desired), gslb.Generation)
		case gslb.Generation > h.Generation:
			// advance the fence to the latest observed generation without
			// touching hostnames, snapshot or phases
			h.Generation = gslb.Generation
			if err := r.Status().Update(ctx, gslb); err != nil {
				return nil, err
			}
		}
		return gslb.Status.ResourceRefHandoff, nil
	}

	active := gslb.Status.ActiveResourceRef
	if active == nil || refCoordinatesEqual(*active, desired) {
		return nil, nil
	}

	hosts := pinnedHosts(gslb)
	if len(hosts) == 0 {
		// nothing previously published, hence nothing to protect; adopt without handoff
		return nil, nil
	}

	frozen, err := r.snapshotLiveDNSEndpoint(ctx, gslb)
	if err != nil {
		return nil, err
	}

	handoff := &k8gbv1beta1io.ResourceRefHandoff{
		Generation:   gslb.Generation,
		From:         *active,
		To:           desired,
		Hosts:        hosts,
		Health:       cloneHealth(gslb.Status.ServiceHealth),
		Servers:      cloneServers(gslb.Status.Servers),
		LastEndpoint: frozen,
		HostStates:   make([]k8gbv1beta1io.HostHandoff, 0, len(hosts)),
	}
	for _, host := range hosts {
		handoff.HostStates = append(handoff.HostStates, k8gbv1beta1io.HostHandoff{
			Host:  host,
			Phase: k8gbv1beta1io.HostHandoffPendingTakeover,
		})
	}
	gslb.Status.ResourceRefHandoff = handoff
	if err := r.Status().Update(ctx, gslb); err != nil {
		return nil, err
	}
	r.recordEvent(gslb, corev1.EventTypeNormal, eventResourceRefHandoffStarted,
		"ResourceRef handoff %s/%s started at generation %d: %s %s -> %s %s for hosts %s",
		gslb.Namespace, gslb.Name, gslb.Generation,
		active.Kind, refDisplayName(*active), desired.Kind, refDisplayName(desired), strings.Join(hosts, ","))
	return handoff, nil
}

func (r *GslbReconciler) snapshotLiveDNSEndpoint(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
) ([]k8gbv1beta1io.PublishedEndpoint, error) {
	live := &externaldnsApi.DNSEndpoint{}
	err := r.Get(ctx, client.ObjectKey{Namespace: gslb.Namespace, Name: gslb.Name}, live)
	if err != nil {
		if k8serrors.IsNotFound(err) {
			return nil, nil
		}
		return nil, err
	}
	return k8gbendpoint.SnapshotEndpoints(live.Spec.Endpoints), nil
}

// assertLatestGeneration is the write fence. A reconciliation is only allowed
// to write if it still observes the same Gslb generation and the same handoff
// generation it started with; concurrent or late reconciliations (including
// slow external DNS queries spanning a spec switch) stop before touching the
// DNSEndpoint or the status.
func (r *GslbReconciler) assertLatestGeneration(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
) error {
	fresh := &k8gbv1beta1io.Gslb{}
	if err := r.Get(ctx, client.ObjectKeyFromObject(gslb), fresh); err != nil {
		return err
	}
	if fresh.Generation != gslb.Generation {
		return fmt.Errorf("%w: observed generation %d, latest generation %d",
			errStaleHandoffGeneration, gslb.Generation, fresh.Generation)
	}
	switch {
	case h == nil && fresh.Status.ResourceRefHandoff != nil:
		return fmt.Errorf("%w: handoff for generation %d started", errStaleHandoffGeneration,
			fresh.Status.ResourceRefHandoff.Generation)
	case h != nil && fresh.Status.ResourceRefHandoff == nil:
		return fmt.Errorf("%w: handoff for generation %d completed", errStaleHandoffGeneration, h.Generation)
	case h != nil && fresh.Status.ResourceRefHandoff.Generation != h.Generation:
		return fmt.Errorf("%w: observed handoff generation %d, latest handoff generation %d",
			errStaleHandoffGeneration, h.Generation, fresh.Status.ResourceRefHandoff.Generation)
	}
	return nil
}

// reconcileResourceRefHandoff drives the per-hostname ownership handoff.
// The previous owner keeps publishing the frozen last usable result until the
// new reference is fully resolved and validated; every write goes through the
// generation fence and every result stays clipped to the pinned hostname set.
func (r *GslbReconciler) reconcileResourceRefHandoff(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	result *utils.ReconcileResultHandler,
) (ctrl.Result, error) {
	// Publish receipt recovery: a previous reconciliation wrote the candidate
	// DNSEndpoint but failed to confirm the status. Verify the live object
	// against the receipt and backfill without recomputing.
	if h.Receipt != nil {
		done, reconcileResult, err := r.recoverFromReceipt(ctx, gslb, h, result)
		if err != nil {
			return r.abortStaleOrError(gslb, result, err)
		}
		if done {
			return reconcileResult, nil
		}
	}

	refResolver, err := refresolver.New(gslb, r.Client)
	if err != nil {
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			fmt.Sprintf("referenced %s %q is not available yet, waiting for takeover: %v",
				h.To.Kind, refDisplayName(h.To), err))
	}

	newUID := refResolver.GetReferencedUID()
	switch {
	case h.To.UID == "":
		h.To.UID = newUID
		if err := r.fencedStatusUpdate(ctx, gslb, h); err != nil {
			return r.abortStaleOrError(gslb, result, err)
		}
	case h.To.UID != newUID:
		// the pinned referenced object was deleted, recreated or renamed
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			fmt.Sprintf("referenced %s identity changed, waiting for the pinned object %s: observed UID %s",
				h.To.Kind, refDisplayName(h.To), newUID))
	}

	servers, err := refResolver.GetServers()
	if err != nil {
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			fmt.Sprintf("new reference %s %s is not fully resolved, waiting for takeover: %v",
				h.To.Kind, refDisplayName(h.To), err))
	}
	zoneList, err := r.ZoneService.List(ctx)
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(fmt.Errorf("getting delegation zones (%s)", err))
	}
	filteredServers := filterServersByZoneDelegations(servers, zoneList)
	candidateServers := clipServersToHosts(filteredServers, h.Hosts)
	if len(servers) != len(candidateServers) {
		r.Logger.Info().
			Str("gslb", gslb.Name).
			Strs("pinnedHosts", h.Hosts).
			Strs("resolvedHosts", listHosts(servers)).
			Msg("Ignoring new-reference hostnames outside the pinned handoff set")
	}
	if len(candidateServers) == 0 {
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			fmt.Sprintf("new reference %s %s does not fully resolve any pinned hostname yet, waiting for takeover",
				h.To.Kind, refDisplayName(h.To)))
	}

	loadBalancerExposedIPs, err := refresolver.ResolveGslbExposedIPs(
		refResolver, gslb.Annotations, r.Config.ClusterExposedIPs, r.Config.ParentZoneDNSServers)
	if err != nil {
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			fmt.Sprintf("new reference exposed IPs are not resolved yet, waiting for takeover: %v", err))
	}
	lbIPs, _ := splitIPsByVersion(r.Logger, loadBalancerExposedIPs)

	view := gslb.DeepCopy()
	view.Status.Servers = candidateServers
	view.Status.LoadBalancer.ExposedIPs = lbIPs
	candidateHealth, err := calculateServiceHealth(ctx, r.Client, view)
	if err != nil {
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			fmt.Sprintf("new reference health inputs are not resolved yet, waiting for takeover: %v", err))
	}
	view.Status.ServiceHealth = candidateHealth

	_, span := r.Tracer.Start(context.Background(), "gslbHandoffCandidateDNSEndpoint")
	epProvider := k8gbendpoint.NewApplicationDNSEndpoint(
		context.TODO(),
		r.Client,
		r.Config,
		view,
		r.Logger,
		utils.NewDNSQueryService(),
		r.ZoneService,
		r.updateRuntimeStatus)
	candidateEndpoint, err := epProvider.GetDNSEndpoint()
	span.End()
	if err != nil {
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			fmt.Sprintf("candidate DNSEndpoint for %s %s is not fully validated yet, waiting for takeover: %v",
				h.To.Kind, refDisplayName(h.To), err))
	}

	validated, err := k8gbendpoint.ValidatedHostsFromCandidate(h.Hosts, candidateEndpoint.Spec.Endpoints)
	if err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}
	// A hostname whose new-reference backing services are not present yet
	// (NotFound) must not take over even when failover semantics produce a
	// non-empty record from external targets: the new reference is not fully
	// resolved until its own health inputs exist.
	for host, ok := range validated {
		if ok && candidateHealth[host] == k8gbv1beta1io.NotFound {
			validated[host] = false
		}
	}
	candidateValidatedCount := 0
	for _, ok := range validated {
		if ok {
			candidateValidatedCount++
		}
	}
	if candidateValidatedCount == 0 {
		return r.keepPendingHandoff(ctx, gslb, h, result, nil,
			"candidate reference resolves but publishes no usable targets yet, waiting for takeover")
	}

	mergedEndpoints := k8gbendpoint.MergeHandoffEndpoints(h.Hosts, h.LastEndpoint, candidateEndpoint.Spec.Endpoints, validated)
	dnsEndpoint := k8gbendpoint.NewHandoffDNSEndpointObject(gslb.Namespace, gslb.Name, mergedEndpoints)
	if err := controllerutil.SetControllerReference(gslb, dnsEndpoint, r.Scheme); err != nil {
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}

	if err := r.assertLatestGeneration(ctx, gslb, h); err != nil {
		return r.abortStaleOrError(gslb, result, err)
	}

	// Record the publish receipt BEFORE the candidate write. Hosts the
	// candidate was validated for enter TakingOver; everything else stays on
	// the frozen result.
	setHostPhases(h, validated, k8gbv1beta1io.HostHandoffTakingOver)
	h.Receipt = &k8gbv1beta1io.PublishReceipt{
		Generation: h.Generation,
		ToUID:      h.To.UID,
		Endpoint:   k8gbendpoint.SnapshotEndpoints(mergedEndpoints),
	}
	h.Reason = ""
	if err := r.Status().Update(ctx, gslb); err != nil {
		if k8serrors.IsConflict(err) {
			return result.Requeue()
		}
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}

	if err := epProvider.SaveDNSEndpoint(dnsEndpoint); err != nil {
		// Candidate publish failed: discard the new generation. The API kept
		// the previous DNSEndpoint, and the frozen result continues serving.
		discardErr := r.discardCandidateGeneration(ctx, gslb, h,
			fmt.Sprintf("candidate DNSEndpoint write failed, new generation discarded: %v", err))
		if discardErr != nil {
			m.IncrementError(gslb)
			return result.RequeueError(discardErr)
		}
		m.IncrementError(gslb)
		return result.Requeue()
	}

	if err := r.assertLatestGeneration(ctx, gslb, h); err != nil {
		// Do not touch the status: the receipt lets the next reconciliation
		// verify the write which just succeeded.
		return r.abortStaleOrError(gslb, result, err)
	}

	candidateView := &handoffCandidateView{
		servers:    candidateServers,
		health:     candidateHealth,
		exposedIPs: lbIPs,
	}
	return r.confirmHandoff(ctx, gslb, h, validated, mergedEndpoints, candidateView, result)
}

// confirmHandoff moves validated hostnames to Active and either finalizes the
// handoff when every pinned hostname was taken over or keeps publishing the
// frozen result for the remaining pending hostnames.
func (r *GslbReconciler) confirmHandoff(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	validated map[string]bool,
	publishedEndpoints []*externaldns.Endpoint,
	view *handoffCandidateView,
	result *utils.ReconcileResultHandler,
) (ctrl.Result, error) {
	setHostPhases(h, validated, k8gbv1beta1io.HostHandoffActive)

	allActive := true
	for _, state := range h.HostStates {
		if state.Phase != k8gbv1beta1io.HostHandoffActive {
			allActive = false
			break
		}
	}

	if !allActive {
		// Advance the per-host frozen baseline to the records just confirmed
		// so that discarding a later candidate cannot move an already taken
		// hostname back to the previous owner.
		advanceFrozenBaseline(h, view, publishedEndpoints)
	}

	applyHandoffStatusPresentation(gslb, h, view, publishedEndpoints, r.Config.ClusterGeoTag)
	dnsEndpoint := k8gbendpoint.NewHandoffDNSEndpointObject(gslb.Namespace, gslb.Name, publishedEndpoints)

	if allActive {
		to := h.To
		gslb.Status.ActiveResourceRef = &k8gbv1beta1io.ResourceRefIdentity{
			APIVersion: to.APIVersion,
			Kind:       to.Kind,
			Name:       to.Name,
			Selector:   to.Selector,
			UID:        to.UID,
		}
		gslb.Status.ResourceRefHandoff = nil
	} else {
		remaining := make([]string, 0)
		for _, state := range h.HostStates {
			if state.Phase != k8gbv1beta1io.HostHandoffActive {
				remaining = append(remaining, state.Host)
			}
		}
		h.Reason = fmt.Sprintf("waiting for takeover of hostnames %s", strings.Join(remaining, ","))
	}
	h.Receipt = nil

	updateHandoffMetrics(gslb, dnsEndpoint)
	if err := r.Status().Update(ctx, gslb); err != nil {
		if k8serrors.IsConflict(err) {
			return result.Requeue()
		}
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}

	if allActive {
		r.recordEvent(gslb, corev1.EventTypeNormal, eventResourceRefHandoffCompleted,
			"ResourceRef handoff %s/%s completed at generation %d: %s %s now publishes hosts %s",
			gslb.Namespace, gslb.Name, h.Generation, h.To.Kind, refDisplayName(h.To), strings.Join(h.Hosts, ","))
	}
	m.IncrementReconciliation(gslb)
	return result.Requeue()
}

// handoffCandidateView carries the freshly computed inputs of an in-memory
// candidate. It is nil on the receipt-recovery path, in which case status is
// backfilled solely from frozen inputs and the receipt.
type handoffCandidateView struct {
	servers    []*k8gbv1beta1io.Server
	health     map[string]k8gbv1beta1io.HealthStatus
	exposedIPs []string
}

// recoverFromReceipt handles controller restarts and failed status updates.
// It verifies the live DNSEndpoint against the receipt and either confirms the
// takeover from the receipt alone, or drops the receipt if the write never
// landed. Recomputation is not involved, so the hostname scope cannot grow.
func (r *GslbReconciler) recoverFromReceipt(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	result *utils.ReconcileResultHandler,
) (bool, ctrl.Result, error) {
	if err := r.assertLatestGeneration(ctx, gslb, h); err != nil {
		return true, ctrl.Result{}, err
	}
	if h.Receipt.Generation != h.Generation {
		if err := r.discardReceipt(ctx, gslb, h, "dropping publish receipt from an older handoff generation"); err != nil {
			return true, ctrl.Result{}, err
		}
		return false, ctrl.Result{}, nil
	}
	live := &externaldnsApi.DNSEndpoint{}
	getErr := r.Get(ctx, client.ObjectKey{Namespace: gslb.Namespace, Name: gslb.Name}, live)
	if getErr != nil && !k8serrors.IsNotFound(getErr) {
		return true, ctrl.Result{}, getErr
	}
	if getErr != nil || !k8gbendpoint.VerifyPublishedEndpoint(live, h.Receipt.Endpoint) {
		if err := r.discardReceipt(ctx, gslb, h,
			"candidate DNSEndpoint write was not confirmed, dropping publish receipt and keeping previous owner"); err != nil {
			return true, ctrl.Result{}, err
		}
		return false, ctrl.Result{}, nil
	}

	takingOver := make(map[string]bool, len(h.HostStates))
	for _, state := range h.HostStates {
		if state.Phase == k8gbv1beta1io.HostHandoffTakingOver {
			takingOver[state.Host] = true
		}
	}
	published := k8gbendpoint.RestoreEndpoints(h.Receipt.Endpoint)
	reconcileResult, err := r.confirmHandoff(ctx, gslb, h, takingOver, published, nil, result)
	return true, reconcileResult, err
}

func (r *GslbReconciler) discardReceipt(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	reason string,
) error {
	r.Logger.Warn().Str("gslb", gslb.Name).Int64("generation", h.Generation).Msg(reason)
	h.Receipt = nil
	resetHostStates(h, k8gbv1beta1io.HostHandoffPendingTakeover)
	h.Reason = reason
	return r.fencedStatusUpdate(ctx, gslb, h)
}

func (r *GslbReconciler) discardCandidateGeneration(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	reason string,
) error {
	r.Logger.Warn().Str("gslb", gslb.Name).Int64("generation", h.Generation).Msg(reason)
	r.recordEvent(gslb, corev1.EventTypeWarning, eventResourceRefHandoffDiscarded, "%s", reason)
	h.Receipt = nil
	resetHostStates(h, k8gbv1beta1io.HostHandoffPendingTakeover)
	h.Reason = reason
	if err := r.assertLatestGeneration(ctx, gslb, h); err != nil {
		return err
	}
	return r.presentPendingStatus(ctx, gslb, h, reason)
}

// keepPendingHandoff keeps the frozen previous owner publishing and surfaces
// the PendingTakeover state. Candidate inputs are never mixed into the frozen
// DNSEndpoint.
func (r *GslbReconciler) keepPendingHandoff(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	result *utils.ReconcileResultHandler,
	_ *handoffCandidateView,
	reason string,
) (ctrl.Result, error) {
	if h.Receipt != nil {
		if err := r.discardReceipt(ctx, gslb, h, reason); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
	} else {
		h.Reason = reason
	}
	r.Logger.Info().
		Str("gslb", gslb.Name).
		Int64("generation", h.Generation).
		Strs("hosts", h.Hosts).
		Str("from", h.From.Kind+"/"+refDisplayName(h.From)).
		Str("to", h.To.Kind+"/"+refDisplayName(h.To)).
		Msg(reason)

	// Make sure the frozen last usable result remains published even if the
	// candidate attempt rewrote nothing or the object was altered externally.
	// When there is no frozen result to protect, do not create an empty
	// candidate-less DNSEndpoint: the takeover resumes once the new reference
	// resolves.
	frozenEndpoints := k8gbendpoint.RestoreEndpoints(h.LastEndpoint)
	if len(frozenEndpoints) > 0 {
		frozenEndpoint := k8gbendpoint.NewHandoffDNSEndpointObject(gslb.Namespace, gslb.Name, frozenEndpoints)
		if err := controllerutil.SetControllerReference(gslb, frozenEndpoint, r.Scheme); err != nil {
			m.IncrementError(gslb)
			return result.RequeueError(err)
		}
		if err := r.assertLatestGeneration(ctx, gslb, h); err != nil {
			return r.abortStaleOrError(gslb, result, err)
		}
		live := &externaldnsApi.DNSEndpoint{}
		getErr := r.Get(ctx, client.ObjectKeyFromObject(frozenEndpoint), live)
		switch {
		case getErr != nil && k8serrors.IsNotFound(getErr):
			if err := r.saveHandoffEndpoint(ctx, gslb, h, frozenEndpoint); err != nil {
				m.IncrementError(gslb)
				return result.RequeueError(err)
			}
		case getErr != nil:
			m.IncrementError(gslb)
			return result.RequeueError(getErr)
		case !k8gbendpoint.VerifyPublishedEndpoint(live, k8gbendpoint.SnapshotEndpoints(frozenEndpoint.Spec.Endpoints)):
			if err := r.saveHandoffEndpoint(ctx, gslb, h, frozenEndpoint); err != nil {
				m.IncrementError(gslb)
				return result.RequeueError(err)
			}
		}
	}

	if err := r.presentPendingStatus(ctx, gslb, h, reason); err != nil {
		if k8serrors.IsConflict(err) || errors.Is(err, errStaleHandoffGeneration) {
			return result.Requeue()
		}
		m.IncrementError(gslb)
		return result.RequeueError(err)
	}
	r.recordEvent(gslb, corev1.EventTypeNormal, eventResourceRefHandoffPending,
		"ResourceRef handoff %s/%s generation %d is waiting for %s %s takeover: %s",
		gslb.Namespace, gslb.Name, h.Generation, h.To.Kind, refDisplayName(h.To), reason)
	m.IncrementReconciliation(gslb)
	return result.Requeue()
}

func (r *GslbReconciler) saveHandoffEndpoint(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	dnsEndpoint *externaldnsApi.DNSEndpoint,
) error {
	if err := r.assertLatestGeneration(ctx, gslb, h); err != nil {
		return err
	}
	epProvider := k8gbendpoint.NewApplicationDNSEndpoint(
		ctx, r.Client, r.Config, gslb, r.Logger, utils.NewDNSQueryService(), r.ZoneService, r.updateRuntimeStatus)
	return epProvider.SaveDNSEndpoint(dnsEndpoint)
}

func (r *GslbReconciler) presentPendingStatus(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	reason string,
) error {
	applyHandoffStatusPresentation(gslb, h, nil, k8gbendpoint.RestoreEndpoints(h.LastEndpoint), r.Config.ClusterGeoTag)
	h.Reason = reason
	return r.Status().Update(ctx, gslb)
}

func (r *GslbReconciler) fencedStatusUpdate(
	ctx context.Context,
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
) error {
	if err := r.assertLatestGeneration(ctx, gslb, h); err != nil {
		return err
	}
	return r.Status().Update(ctx, gslb)
}

func (r *GslbReconciler) abortStaleOrError(
	gslb *k8gbv1beta1io.Gslb,
	result *utils.ReconcileResultHandler,
	err error,
) (ctrl.Result, error) {
	if errors.Is(err, errStaleHandoffGeneration) {
		r.Logger.Info().Str("gslb", gslb.Name).Err(err).
			Msg("Skipping writes from a stale handoff reconciliation")
		return result.Requeue()
	}
	m.IncrementError(gslb)
	return result.RequeueError(err)
}

func (r *GslbReconciler) recordEvent(gslb *k8gbv1beta1io.Gslb, eventType, reason, message string, args ...any) {
	if r.Recorder == nil {
		return
	}
	r.Recorder.Eventf(gslb, eventType, reason, message, args...)
}

func refDisplayName(ref k8gbv1beta1io.ResourceRefIdentity) string {
	if ref.Name != "" {
		return ref.Name
	}
	if ref.Selector != "" {
		return "selector=" + ref.Selector
	}
	return ""
}

func resetHostStates(h *k8gbv1beta1io.ResourceRefHandoff, phase k8gbv1beta1io.HostHandoffPhase) {
	for i := range h.HostStates {
		h.HostStates[i].Phase = phase
	}
}

func setHostPhases(h *k8gbv1beta1io.ResourceRefHandoff, hosts map[string]bool, phase k8gbv1beta1io.HostHandoffPhase) {
	for i := range h.HostStates {
		if !hosts[h.HostStates[i].Host] {
			continue
		}
		// already confirmed owners are not moved backwards to TakingOver while
		// later hostnames of the same handoff generation catch up
		if phase == k8gbv1beta1io.HostHandoffTakingOver &&
			h.HostStates[i].Phase == k8gbv1beta1io.HostHandoffActive {
			continue
		}
		h.HostStates[i].Phase = phase
	}
}

// advanceFrozenBaseline moves the per-host frozen last-usable result forward
// for hostnames which completed takeover. Together with the pinned hostname
// set this ensures that: a discarded candidate reverts only hostnames that
// have not taken over yet; the frozen snapshot never shrinks below the
// confirmed set; and ordering remains localtargets-first per pinned host.
func advanceFrozenBaseline(
	h *k8gbv1beta1io.ResourceRefHandoff,
	view *handoffCandidateView,
	published []*externaldns.Endpoint,
) {
	active := make(map[string]bool)
	for _, state := range h.HostStates {
		if state.Phase == k8gbv1beta1io.HostHandoffActive {
			active[state.Host] = true
		}
	}
	if len(active) == 0 {
		return
	}

	publishedByHost := make(map[string][]k8gbv1beta1io.PublishedEndpoint)
	for _, p := range k8gbendpoint.SnapshotEndpoints(published) {
		host := k8gbendpoint.HostOfPublishedEndpoint(p)
		if active[host] {
			publishedByHost[host] = append(publishedByHost[host], p)
		}
	}
	frozenByHost := make(map[string][]k8gbv1beta1io.PublishedEndpoint)
	for _, p := range h.LastEndpoint {
		host := k8gbendpoint.HostOfPublishedEndpoint(p)
		frozenByHost[host] = append(frozenByHost[host], p)
	}

	next := make([]k8gbv1beta1io.PublishedEndpoint, 0, len(h.LastEndpoint))
	for _, host := range h.Hosts {
		if active[host] {
			next = append(next, publishedByHost[host]...)
			continue
		}
		next = append(next, frozenByHost[host]...)
	}
	h.LastEndpoint = next

	if view == nil {
		return
	}
	for host := range active {
		if health, ok := view.health[host]; ok {
			h.Health[host] = health
		}
	}
	candidateServers := make(map[string]*k8gbv1beta1io.Server)
	for _, server := range view.servers {
		if server != nil {
			candidateServers[server.Host] = server
		}
	}
	previousServers := make(map[string]*k8gbv1beta1io.Server)
	for _, server := range h.Servers {
		if server != nil {
			previousServers[server.Host] = server
		}
	}
	servers := make([]*k8gbv1beta1io.Server, 0, len(h.Hosts))
	for _, host := range h.Hosts {
		if server, ok := candidateServers[host]; ok {
			servers = append(servers, server)
			continue
		}
		if server, ok := previousServers[host]; ok {
			servers = append(servers, server)
		}
	}
	h.Servers = servers
}

func clipServersToHosts(servers []*k8gbv1beta1io.Server, hosts []string) []*k8gbv1beta1io.Server {
	pinned := make(map[string]bool, len(hosts))
	for _, host := range hosts {
		pinned[host] = true
	}
	clipped := make([]*k8gbv1beta1io.Server, 0, len(servers))
	for _, server := range servers {
		if server != nil && pinned[server.Host] {
			clipped = append(clipped, server)
		}
	}
	return clipped
}

func cloneHealth(health map[string]k8gbv1beta1io.HealthStatus) map[string]k8gbv1beta1io.HealthStatus {
	cloned := make(map[string]k8gbv1beta1io.HealthStatus, len(health))
	for host, status := range health {
		cloned[host] = status
	}
	return cloned
}

func cloneServers(servers []*k8gbv1beta1io.Server) []*k8gbv1beta1io.Server {
	cloned := make([]*k8gbv1beta1io.Server, 0, len(servers))
	for _, server := range servers {
		if server == nil {
			continue
		}
		copied := &k8gbv1beta1io.Server{Host: server.Host}
		for _, service := range server.Services {
			if service == nil {
				continue
			}
			copied.Services = append(copied.Services, &k8gbv1beta1io.NamespacedName{
				Namespace: service.Namespace,
				Name:      service.Name,
			})
		}
		cloned = append(cloned, copied)
	}
	return cloned
}

// applyHandoffStatusPresentation projects the pinned handoff state onto the
// Gslb status. Only pinned hostnames are ever exposed: candidate inputs for
// activated hostnames overlay the frozen inputs for still-pending hostnames,
// and the healthy records come from the exact published endpoint content.
func applyHandoffStatusPresentation(
	gslb *k8gbv1beta1io.Gslb,
	h *k8gbv1beta1io.ResourceRefHandoff,
	view *handoffCandidateView,
	publishedEndpoints []*externaldns.Endpoint,
	geoTag string,
) {
	gslb.Status.GeoTag = geoTag
	gslb.Status.Hosts = strings.Join(h.Hosts, ", ")

	frozenServers := make(map[string]*k8gbv1beta1io.Server, len(h.Servers))
	for _, server := range h.Servers {
		if server != nil {
			frozenServers[server.Host] = server
		}
	}
	candidateServers := map[string]*k8gbv1beta1io.Server{}
	if view != nil {
		for _, server := range view.servers {
			if server != nil {
				candidateServers[server.Host] = server
			}
		}
	}
	servers := make([]*k8gbv1beta1io.Server, 0, len(h.Hosts))
	for _, host := range h.Hosts {
		if server, ok := candidateServers[host]; ok {
			servers = append(servers, server)
			continue
		}
		if server, ok := frozenServers[host]; ok {
			servers = append(servers, server)
		} else {
			servers = append(servers, &k8gbv1beta1io.Server{Host: host})
		}
	}
	gslb.Status.Servers = servers

	health := make(map[string]k8gbv1beta1io.HealthStatus, len(h.Hosts))
	for _, host := range h.Hosts {
		health[host] = h.Health[host]
	}
	if view != nil {
		for host, status := range view.health {
			if _, pinned := health[host]; pinned || containsHost(h.Hosts, host) {
				health[host] = status
			}
		}
		if len(view.exposedIPs) > 0 {
			gslb.Status.LoadBalancer.ExposedIPs = view.exposedIPs
		}
	}
	gslb.Status.ServiceHealth = health
	gslb.Status.HealthyRecords = collectHealthyRecords(publishedEndpoints)
}

func containsHost(hosts []string, host string) bool {
	for _, candidate := range hosts {
		if candidate == host {
			return true
		}
	}
	return false
}

func collectHealthyRecords(endpoints []*externaldns.Endpoint) map[string][]string {
	healthyRecords := make(map[string][]string)
	for _, endpoint := range endpoints {
		if endpoint == nil {
			continue
		}
		if strings.HasPrefix(endpoint.DNSName, "localtargets-") {
			continue
		}
		if endpoint.RecordType == "A" && len(endpoint.Targets) > 0 {
			healthyRecords[endpoint.DNSName] = append([]string(nil), endpoint.Targets...)
		}
	}
	return healthyRecords
}

func updateHandoffMetrics(gslb *k8gbv1beta1io.Gslb, ep *externaldnsApi.DNSEndpoint) {
	m.UpdateIngressHostsPerStatusMetric(gslb, gslb.Status.ServiceHealth)
	m.UpdateHealthyRecordsMetric(gslb, gslb.Status.HealthyRecords)
	m.UpdateHealthyLocalRecordsMetric(gslb, gslb.Status.HealthyRecords, gslb.Status.LoadBalancer.ExposedIPs)
	m.UpdateEndpointStatus(ep)
}
