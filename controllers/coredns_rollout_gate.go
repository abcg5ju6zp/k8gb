import (
	"context"

	"github.com/k8gb-io/k8gb/api/v1beta1io"
	"github.com/k8gb-io/k8gb/controllers/corednsrollout"
	"github.com/k8gb-io/k8gb/controllers/zones"
)

// coreDNSRolloutGate adapts the corednsrollout Coordinator decision to the
// zones.GenerationCoordinator boundary, keeping the zones package free of the
// rollout state machine dependency.
type coreDNSRolloutGate struct {
	coordinator *corednsrollout.Coordinator
}

// NewCoreDNSRolloutGate wraps the safe rollout coordinator for ZoneService.
func NewCoreDNSRolloutGate(coordinator *corednsrollout.Coordinator) zones.GenerationCoordinator {
	return &coreDNSRolloutGate{coordinator: coordinator}
}

// EnsureGeneration delegates to the rollout coordinator and maps its decision
// to the reconciler-facing gate.
func (g *coreDNSRolloutGate) EnsureGeneration(ctx context.Context, zoneDelegations *v1beta1io.ZoneDelegationList) (zones.CoreDNSGenerationGate, error) {
	decision, err := g.coordinator.EnsureGeneration(ctx, zoneDelegations)
	if err != nil {
		return zones.CoreDNSGenerationGate{}, err
	}
	return zones.CoreDNSGenerationGate{
		Active:       decision.Decision == corednsrollout.DecisionActive,
		RequeueAfter: decision.RequeueAfter,
		Reason:       decision.Reason,
	}, nil
}
